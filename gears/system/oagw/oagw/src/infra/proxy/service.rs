/// Where the bytes of a response came from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ResponseSource {
    /// From the upstream, including failures it reported itself.
    Upstream,
    /// Generated by the gateway.
    Gateway,
}

/// Everything the proxy needs to know about one inbound request.
#[derive(Debug)]
pub struct ProxyRequestContext {
    /// Alias the request addressed.
    pub alias: String,
    /// Path suffix after `/proxy/{alias}`; empty when none was supplied.
    pub path_suffix: String,
    /// Decoded query parameters, in request order.
    pub query: Vec<(String, String)>,
    /// Inbound headers, including `X-OAGW-Target-Host`.
    pub inbound_headers: HeaderMap,
    /// HTTP method.
    pub method: http::Method,
    /// Calling tenant.
    pub tenant_id: Uuid,
    /// Authenticated subject, or nil for an anonymous call.
    pub subject_id: Uuid,
    /// Client address, when known.
    pub client_ip: Option<std::net::IpAddr>,
    /// Bearer token on the inbound request, when present.
    pub bearer_token: Option<String>,
}

/// A gateway refusal, with any headers the response must carry.
#[derive(Debug)]
pub struct ProxyFailure {
    /// The error and its GTS classification.
    pub error: DomainError,
    /// Extra response headers, such as `Retry-After`.
    pub extra_headers: Vec<(String, String)>,
    /// The upstream the request had resolved to, when one had.
    pub upstream_id: Option<Uuid>,
}

impl From<DomainError> for ProxyFailure {
    fn from(error: DomainError) -> Self {
        Self {
            error,
            extra_headers: Vec::new(),
            upstream_id: None,
        }
    }
}

/// An upstream response ready to be handed to the client.
pub struct ForwardedResponse {
    /// Upstream status.
    pub status: http::StatusCode,
    /// Transformed response headers.
    pub headers: HeaderMap,
    /// Upstream body, still streaming.
    pub body: axum::body::Body,
    /// Where the bytes came from.
    pub source: ResponseSource,
}

