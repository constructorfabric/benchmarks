//! `DataPlaneServiceImpl` — the proxy orchestrator (DESIGN §3.5).
//!
//! Implements [`DataPlaneService`] by running the full request flow:
//!
//! 1. Scope check (`proxy:invoke`).
//! 2. Upstream chain resolution (alias → ancestor walk, shadowing).
//! 3. Route resolution (longest path prefix, method allowlist).
//! 4. Effective-config merge (auth / rate / CORS / plugins).
//! 5. CORS actual-request validation (ADR-0004), then rate limiting with
//!    `min()` semantics across the hierarchy (ADR-0003).
//! 6. Auth plugin → guards → transform(request), in that order.
//! 7. `X-OAGW-Target-Host` endpoint selection (ADR-0001 matrix) and outbound
//!    forwarding via `toolkit_http`.
//! 8. transform(response) → guard(response) → CORS response headers →
//!    `X-OAGW-Error-Source: upstream` on every forwarded response.
//!
//! Errors generated by OAGW map to [`OagwError`] (rendered downstream as
//! `application/problem+json` with `X-OAGW-Error-Source: gateway`);
//! upstream responses are passed through unchanged with
//! `X-OAGW-Error-Source: upstream` (ADR-0007). No credential material is ever
//! logged or placed in error details.

