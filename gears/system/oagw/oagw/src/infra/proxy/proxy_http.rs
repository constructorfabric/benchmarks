//! The pingora [`ProxyHttp`] implementation hosting the OAGW data plane.
//!
//! [`DataPlaneService`] runs inside the pingora server (the [`super`] bridge)
//! and drives the [`DataPlaneGate`](super::DataPlaneGate) pipeline per request,
//! then forwards admitted requests to the selected upstream over pingora's
//! pooled/load-balanced transport. It implements the data-plane stages of
//! `cpt-cf-oagw-feature-data-plane`: upstream peer selection, internal-header
//! stripping and credential injection, path-prefix application, response
//! transforms (CORS headers, request-id echo, error-source distinction), and
//! the upstream-sourced error mapping (502/503/504 per DESIGN.md §3.3).

use std::sync::Arc;
use std::time::Instant;

use async_trait::async_trait;
use bytes::Bytes;
use dashmap::DashMap;

use pingora_core::upstreams::peer::HttpPeer;
use pingora_core::{Error, ErrorType, Result};
use pingora_http::{RequestHeader, ResponseHeader};
use pingora_load_balancing::LoadBalancer;
use pingora_load_balancing::selection::RoundRobin;
use pingora_proxy::{ProxyHttp, Session};

use super::{
    DataPlaneGate, GatePass, HDR_BACKEND_ALIAS, HDR_BEARER, HDR_ERROR_SOURCE, HDR_RELAY_SECRET,
    HDR_SUBJECT_ID, HDR_TENANT_ID, HDR_TOKEN_SCOPES, ProblemResponse, error_types,
};
use crate::domain::models::EffectiveRouteConfig;
use crate::domain::plugins::PluginRegistry;

/// Per-request proxy context produced by the request filter.
#[allow(dead_code)]
pub struct ProxyCtx {
    /// Route alias being proxied.
    alias: String,
    /// Caller tenant id (subject tenant).
    tenant_id: String,
    /// Request id generated by the `request_id` transform.
    request_id: Option<String>,
    /// Effective configuration (for peer selection and timeouts).
    effective: Option<Arc<EffectiveRouteConfig>>,
    /// Plugin registry (for access logging / metrics).
    registry: Option<PluginRegistry>,
    /// Credential headers to inject into the upstream request.
    auth_injections: Vec<(String, String)>,
    /// Headers to attach to the proxied response (CORS).
    response_headers: Vec<(String, String)>,
    /// SSRF-validated upstream address to connect to (instead of re-resolving
    /// the hostname; DNS-rebind hardening). `None` when the guard is disabled.
    pinned_ip: Option<std::net::IpAddr>,
    /// Wall-clock start of the request.
    start: Instant,
}

/// The pingora proxy hosting the OAGW data plane.
#[derive(Clone)]
pub struct DataPlaneService {
    gate: Arc<DataPlaneGate>,
    /// Load-balancers per upstream (`alias|host:port`), shared across
    /// requests for connection reuse and round-robin selection.
    upstreams: Arc<DashMap<String, Arc<LoadBalancer<RoundRobin>>>>,
    /// Per-bridge relay secret stamped by the axum surface. Every internal
    /// request must present it before any identity header is trusted (an
    /// empty string disables the check, used only before the spawner installs
    /// a fresh secret).
    relay_secret: Arc<str>,
}

impl DataPlaneService {
    /// Creates the service for the given gate.
    #[must_use]
    pub fn new(gate: Arc<DataPlaneGate>) -> Self {
        let upstreams: Arc<DashMap<String, Arc<LoadBalancer<RoundRobin>>>> =
            Arc::new(DashMap::new());
        // Prune per-upstream load-balancer state when the upstream is deleted
        // from the control plane (no unbounded growth).
        gate.control().on_upstream_delete({
            let upstreams = upstreams.clone();
            move |alias| {
                let prefix = format!("{alias}|");
                upstreams.retain(|key, _| !key.starts_with(&prefix));
            }
        });
        Self {
            gate,
            upstreams,
            relay_secret: Arc::from(""),
        }
    }

    /// Installs the per-bridge relay secret the gate verifies on every
    /// internal request.
    #[must_use]
    pub fn with_relay_secret(mut self, secret: String) -> Self {
        self.relay_secret = Arc::from(secret.as_str());
        self
    }

    /// Resolves the alias and rebuilds the caller [`SecurityContext`] from
    /// the internal relay headers.
    ///
    /// [`SecurityContext`]: toolkit_security::SecurityContext
    fn read_request_identity(
        &self,
        session: &Session,
    ) -> Result<(String, toolkit_security::SecurityContext)>
    where
        Self: Sized,
    {
        let req = session.req_header();
        let headers = &req.headers;

        // The internal bridge is unauthenticated loopback transport: only a
        // request presenting the per-bridge relay secret is allowed to carry
        // caller identity, so a port probe can neither spoof identity headers
        // nor drive the pipeline.
        let presented = headers
            .get(HDR_RELAY_SECRET)
            .and_then(|v| v.to_str().ok())
            .unwrap_or_default();
        if !self.relay_secret.is_empty() && presented != self.relay_secret.as_ref() {
            return Err(Error::explain(
                ErrorType::HTTPStatus(403),
                "missing or invalid x-oagw-relay-secret",
            ));
        }

        let alias = headers
            .get(HDR_BACKEND_ALIAS)
            .and_then(|v| v.to_str().ok())
            .map(str::to_owned)
            .ok_or_else(|| {
                Error::explain(ErrorType::HTTPStatus(400), "missing x-oagw-backend-alias")
            })?;
        let subject_id = headers
            .get(HDR_SUBJECT_ID)
            .and_then(|v| v.to_str().ok())
            .and_then(|s| s.parse::<uuid::Uuid>().ok())
            .ok_or_else(|| {
                Error::explain(ErrorType::HTTPStatus(400), "missing x-oagw-subject-id")
            })?;
        let tenant_id = headers
            .get(HDR_TENANT_ID)
            .and_then(|v| v.to_str().ok())
            .and_then(|s| s.parse::<uuid::Uuid>().ok())
            .ok_or_else(|| {
                Error::explain(ErrorType::HTTPStatus(400), "missing x-oagw-tenant-id")
            })?;

        let mut builder = toolkit_security::SecurityContext::builder()
            .subject_id(subject_id)
            .subject_tenant_id(tenant_id);
        if let Some(bearer) = headers
            .get(HDR_BEARER)
            .and_then(|v| v.to_str().ok())
            .filter(|s| !s.is_empty())
        {
            builder = builder.bearer_token(bearer.to_owned());
        }
        if let Some(scopes) = headers.get(HDR_TOKEN_SCOPES).and_then(|v| v.to_str().ok()) {
            let scopes: Vec<String> = scopes
                .split(',')
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .map(str::to_owned)
                .collect();
            if !scopes.is_empty() {
                builder = builder.token_scopes(scopes);
            }
        }
        Ok((
            alias,
            builder.build().map_err(|e| {
                Error::explain(
                    ErrorType::HTTPStatus(400),
                    format!("malformed caller identity: {e}"),
                )
            })?,
        ))
    }

    /// Writes an RFC 9457 problem response with the error-source header.
    async fn write_problem(&self, session: &mut Session, problem: &ProblemResponse) -> Result<()> {
        // @cpt-begin:cpt-cf-oagw-algo-data-plane-error-mapping:ph-1:inst-problem-body
        let status = http::StatusCode::from_u16(problem.status)
            // @cpt-end:cpt-cf-oagw-algo-data-plane-error-mapping:ph-1:inst-problem-body
            .unwrap_or(http::StatusCode::INTERNAL_SERVER_ERROR);
        let body = serde_json::to_vec(&problem.to_body())
            .unwrap_or_else(|_| b"{\"title\":\"error\"}".to_vec());
        let has_body = !body.is_empty() && problem.status != 204;

        let mut resp = ResponseHeader::build(status, Some(16))
            .map_err(|e| Error::explain(ErrorType::HTTPStatus(400), format!("{e}")))?;
        resp.insert_header("Content-Type", "application/problem+json")
            .ok();
        resp.insert_header(HDR_ERROR_SOURCE, problem.error_source)
            .ok();
        for (k, v) in &problem.extra_headers {
            resp.append_header(k.clone(), v.clone()).ok();
        }
        if has_body {
            resp.append_header("Content-Length", body.len().to_string())
                .ok();
        }
        session
            .write_response_header(Box::new(resp), !has_body)
            .await?;
        if has_body {
            session
                .write_response_body(Some(Bytes::from(body)), true)
                .await?;
        }
        // @cpt-begin:cpt-cf-oagw-algo-data-plane-error-mapping:ph-1:inst-problem-return
        Ok(())
        // @cpt-end:cpt-cf-oagw-algo-data-plane-error-mapping:ph-1:inst-problem-return
    }

    /// Picks (or builds) the load balancer for an upstream endpoint. `addr`
    /// is the caller-selected connect address (`ip:port`, or `host:port`
    /// when no validated pin exists).
    fn load_balancer(&self, key: &str, addr: &str) -> Result<Arc<LoadBalancer<RoundRobin>>> {
        if let Some(existing) = self.upstreams.get(key) {
            return Ok(existing.clone());
        }
        let lb = LoadBalancer::try_from_iter([addr.to_owned()])
            .map_err(|e| Error::explain(ErrorType::ConnectError, format!("{e}")))?;
        let lb = Arc::new(lb);
        self.upstreams.insert(key.to_owned(), lb.clone());
        Ok(lb)
    }
}

/// Maps an upstream-sourced failure to the authoritative error catalog
/// (502/503/504 per DESIGN.md §3.3).
#[must_use]
pub fn map_upstream_error_source(e: &Error) -> (&'static str, u16) {
    // @cpt-begin:cpt-cf-oagw-algo-data-plane-error-mapping:ph-1:inst-upstream-source
    match e.etype() {
        // @cpt-end:cpt-cf-oagw-algo-data-plane-error-mapping:ph-1:inst-upstream-source
        ErrorType::HTTPStatus(code) if *code >= 502 && *code <= 504 => {
            (error_types::DOWNSTREAM, *code)
        }
        ErrorType::ConnectTimedout | ErrorType::TLSHandshakeTimedout => {
            // @cpt-begin:cpt-cf-oagw-algo-data-plane-error-mapping:ph-1:inst-upstream-map
            (error_types::TIMEOUT, 504)
            // @cpt-end:cpt-cf-oagw-algo-data-plane-error-mapping:ph-1:inst-upstream-map
        }
        ErrorType::ConnectRefused | ErrorType::ConnectNoRoute | ErrorType::ConnectError => {
            (error_types::LINK_UNAVAILABLE, 503)
        }
        _ => (error_types::DOWNSTREAM, 502),
    }
}

#[async_trait]
impl ProxyHttp for DataPlaneService {
    type CTX = ProxyCtx;

    fn new_ctx(&self) -> Self::CTX {
        ProxyCtx {
            alias: String::new(),
            tenant_id: String::new(),
            request_id: None,
            effective: None,
            registry: None,
            auth_injections: Vec::new(),
            response_headers: Vec::new(),
            pinned_ip: None,
            start: Instant::now(),
        }
    }

    async fn request_filter(&self, session: &mut Session, ctx: &mut Self::CTX) -> Result<bool> {
        // @cpt-begin:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-proxy-request
        // @cpt-begin:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-l1-resolve
        let (alias, security) = match self.read_request_identity(session) {
            // @cpt-end:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-proxy-request
            // @cpt-end:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-l1-resolve
            Ok(pair) => pair,
            Err(e) => {
                let problem = ProblemResponse::new(
                    401,
                    error_types::AUTH_FAILED,
                    "Unauthorized",
                    format!("{e}"),
                );
                self.write_problem(session, &problem).await?;
                return Ok(true);
            }
        };

        let method = session.req_header().method.as_str().to_owned();
        let path = session.req_header().uri.path().to_owned();
        let mut headers = session.req_header().headers.clone();

        match self
            .gate
            .evaluate(&alias, &method, &path, &security, &mut headers)
            .await
        {
            Ok(GatePass {
                effective,
                registry,
                request_id,
                auth_injections,
                response_headers,
                pinned_ip,
            }) => {
                ctx.alias = alias.clone();
                ctx.tenant_id = security.subject_tenant_id().to_string();
                ctx.effective = Some(effective);
                ctx.registry = Some(registry);
                ctx.request_id = request_id;
                ctx.auth_injections = auth_injections;
                ctx.response_headers = response_headers;
                ctx.pinned_ip = pinned_ip;
                // @cpt-begin:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-forward
                Ok(false)
                // @cpt-end:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-forward
            }
            Err(problem) => {
                // Gateway-sourced problem response (auth/rate/PEP/CORS/SSRF/
                // guard); never reaches an upstream.
                self.write_problem(session, &problem).await?;
                Ok(true)
            }
        }
    }

    async fn upstream_peer(
        &self,
        _session: &mut Session,
        ctx: &mut Self::CTX,
    ) -> Result<Box<HttpPeer>> {
        let effective = ctx
            .effective
            .as_ref()
            .ok_or_else(|| Error::explain(ErrorType::InternalError, "no effective config"))?;
        let upstream = effective
            .upstream
            .as_ref()
            .ok_or_else(|| Error::explain(ErrorType::InternalError, "no upstream selected"))?;

        // Connect to the SSRF-validated (pinned) address when one exists so
        // the upstream hostname is never re-resolved after validation
        // (DNS-rebind TOCTOU). Without a pin (guard disabled) fall back to
        // plain hostname resolution.
        let addr = match ctx.pinned_ip {
            Some(ip) => format!("{ip}:{}", upstream.port),
            None => format!("{}:{}", upstream.host, upstream.port),
        };
        let key = format!("{}|{}", upstream.alias, addr);
        let lb = self.load_balancer(&key, &addr)?;
        let backend = lb.select(b"", 256).ok_or_else(|| {
            Error::explain(ErrorType::ConnectError, "no healthy upstream backend")
        })?;

        let mut peer = Box::new(HttpPeer::new(
            backend,
            upstream.scheme.is_tls(),
            upstream.host.clone(),
        ));
        peer.options.connection_timeout = Some(effective.proxy_timeout);
        peer.options.read_timeout = Some(effective.proxy_timeout);
        peer.options.write_timeout = Some(effective.proxy_timeout);
        peer.options.idle_timeout = Some(effective.proxy_timeout);
        Ok(peer)
    }

    async fn upstream_request_filter(
        &self,
        _session: &mut Session,
        upstream_request: &mut RequestHeader,
        ctx: &mut Self::CTX,
    ) -> Result<()> {
        // Never leak internal routing/identity headers upstream. Removed via
        // the request-header helpers so pingora's case-preserving header map
        // stays in sync (a raw `headers.remove(..)` desyncs the paired
        // case-name map and panics on serialization).
        let internal: Vec<http::HeaderName> = upstream_request
            .headers
            .keys()
            .filter(|k| k.as_str().starts_with("x-oagw-"))
            .cloned()
            .collect();
        for name in internal {
            let _ = upstream_request.remove_header(&name);
        }

        // @cpt-begin:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-inject-credentials
        for (k, v) in &ctx.auth_injections {
            // @cpt-end:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-inject-credentials
            upstream_request.insert_header(k.clone(), v.clone()).ok();
        }
        if let Some(rid) = &ctx.request_id {
            upstream_request.insert_header("x-request-id", rid).ok();
        }

        if let Some(eff) = &ctx.effective
            && let Some(u) = &eff.upstream
        {
            upstream_request.insert_header("Host", &u.host).ok();
            // Apply the upstream path prefix to the forwarded URI.
            let path = upstream_request.uri.path().to_owned();
            let query = upstream_request
                .uri
                .query()
                .map(|q| format!("?{q}"))
                .unwrap_or_default();
            let new_path = format!("{}{}{}", u.path_prefix, path, query);
            upstream_request.set_raw_path(new_path.as_bytes()).ok();
        }
        // The bridged pingora transport forwards from here (pooled,
        // load-balanced) and streams the upstream response back.
        // @cpt-begin:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-upstream-try
        // @cpt-begin:cpt-cf-oagw-algo-data-plane-pipeline-execution:ph-1:inst-pingora-forward
        // @cpt-begin:cpt-cf-oagw-algo-data-plane-pipeline-execution:ph-1:inst-forward-try
        Ok(())
        // @cpt-end:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-upstream-try
        // @cpt-end:cpt-cf-oagw-algo-data-plane-pipeline-execution:ph-1:inst-pingora-forward
        // @cpt-end:cpt-cf-oagw-algo-data-plane-pipeline-execution:ph-1:inst-forward-try
    }

    async fn response_filter(
        &self,
        _session: &mut Session,
        upstream_response: &mut ResponseHeader,
        ctx: &mut Self::CTX,
    ) -> Result<()> {
        // @cpt-begin:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-forward-response
        if let Some(rid) = &ctx.request_id {
            // @cpt-end:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-forward-response
            upstream_response.insert_header("x-request-id", rid).ok();
        }
        for (k, v) in &ctx.response_headers {
            upstream_response.append_header(k.clone(), v.clone()).ok();
        }
        // @cpt-begin:cpt-cf-oagw-algo-data-plane-pipeline-execution:ph-1:inst-stream-response
        // @cpt-begin:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-return-response
        // Attributable to the upstream on every proxied response (ADR 0007).
        // @cpt-end:cpt-cf-oagw-algo-data-plane-pipeline-execution:ph-1:inst-stream-response
        // @cpt-end:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-return-response
        upstream_response
            .insert_header(HDR_ERROR_SOURCE, "upstream")
            .ok();
        Ok(())
    }

    async fn logging(&self, session: &mut Session, _e: Option<&Error>, ctx: &mut Self::CTX) {
        // @cpt-begin:cpt-cf-oagw-algo-data-plane-pipeline-execution:ph-1:inst-done
        let status = session
            // @cpt-end:cpt-cf-oagw-algo-data-plane-pipeline-execution:ph-1:inst-done
            .response_written()
            .map(|h| h.status.as_u16())
            .unwrap_or(0);
        if let Some(registry) = &ctx.registry {
            registry.record_access(
                &ctx.alias,
                session.req_header().method.as_ref(),
                status,
                ctx.start.elapsed(),
            );
        }
    }

    fn error_while_proxy(
        &self,
        peer: &HttpPeer,
        session: &mut Session,
        e: Box<Error>,
        ctx: &mut Self::CTX,
        client_reused: bool,
    ) -> Box<Error> {
        let mut e = e.more_context(format!("Peer: {peer}"));
        e.retry
            .decide_reuse(client_reused && !session.as_ref().retry_buffer_truncated());
        let _ = ctx;
        e
    }

    async fn fail_to_proxy(
        &self,
        session: &mut Session,
        e: &Error,
        _ctx: &mut Self::CTX,
    ) -> pingora_proxy::FailToProxy {
        // @cpt-begin:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-upstream-catch
        // @cpt-begin:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-upstream-error
        // @cpt-begin:cpt-cf-oagw-algo-data-plane-pipeline-execution:ph-1:inst-forward-catch
        // @cpt-begin:cpt-cf-oagw-algo-data-plane-error-mapping:ph-1:inst-upstream-source
        let (error_type, status) = map_upstream_error_source(e);
        // @cpt-end:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-upstream-catch
        // @cpt-end:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-upstream-error
        // @cpt-end:cpt-cf-oagw-algo-data-plane-pipeline-execution:ph-1:inst-forward-catch
        // @cpt-end:cpt-cf-oagw-algo-data-plane-error-mapping:ph-1:inst-upstream-source
        // @cpt-begin:cpt-cf-oagw-algo-data-plane-pipeline-execution:ph-1:inst-forward-map
        // @cpt-begin:cpt-cf-oagw-algo-data-plane-error-mapping:ph-1:inst-upstream-map
        let mut problem = ProblemResponse::new(
            // @cpt-end:cpt-cf-oagw-algo-data-plane-pipeline-execution:ph-1:inst-forward-map
            // @cpt-end:cpt-cf-oagw-algo-data-plane-error-mapping:ph-1:inst-upstream-map
            status,
            error_type,
            match status {
                504 => "Upstream timeout",
                503 => "Upstream unavailable",
                _ => "Bad gateway",
            },
            format!("upstream failure: {e}"),
        );
        // @cpt-begin:cpt-cf-oagw-algo-data-plane-pipeline-execution:ph-1:inst-forward-map-return
        // @cpt-begin:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-upstream-error-return
        // @cpt-begin:cpt-cf-oagw-algo-data-plane-error-mapping:ph-1:inst-upstream-source-header
        problem.error_source = "upstream";
        // @cpt-end:cpt-cf-oagw-algo-data-plane-pipeline-execution:ph-1:inst-forward-map-return
        // @cpt-end:cpt-cf-oagw-flow-data-plane-proxy-request:ph-1:inst-upstream-error-return
        // @cpt-end:cpt-cf-oagw-algo-data-plane-error-mapping:ph-1:inst-upstream-source-header
        let written = self.write_problem(session, &problem).await;
        pingora_proxy::FailToProxy {
            error_code: status,
            can_reuse_downstream: written.is_ok(),
        }
    }
}
