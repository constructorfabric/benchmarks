//! OAGW — Outbound API Gateway gear.
//!
//! OAGW is a centralized outbound API gateway that manages all outbound API
//! requests from gears to external services. It provides routing,
//! authentication, rate limiting and monitoring through a unified proxy layer
//! that enforces security and observability policies (DESIGN.md §1.1).
//!
//! The gear separates a **control plane**, which owns configuration data
//! (upstreams, routes, plugins), from a **data plane**, which orchestrates
//! proxied requests to external services. Both are domain traits within this
//! single crate, layered DDD-Light style (DESIGN.md §1.3):
//!
//! - `api/` — transport: HTTP handling, request parsing, response
//!   serialization
//! - `domain/` — business logic: service traits, repository contracts, domain
//!   models
//! - `infra/` — external integrations: persistence, proxy engine, plugin
//!   registry
//!
//! The domain layer has no infrastructure dependencies; infrastructure
//! implements domain traits; transport maps between HTTP and domain types.
//!
//! ## Error-source contract
//!
//! Every response this gear produces carries `X-OAGW-Error-Source`, telling
//! clients whether the failure was generated by the gateway or passed through
//! from the upstream service. Gateway-generated failures are RFC 9457
//! `application/problem+json` documents whose `type` member is a GTS error
//! type identifier. See [`crate::error`] and ADR 0007.
//!
//! ## Module map
//!
//! - [`api`] — transport: the management REST API (routes, handlers, DTOs)
//! - [`config`] — the `gears.oagw.config` contract
//! - [`domain`] — the configuration model, validation rules, alias derivation,
//!   in-memory store and hierarchical merge
//! - [`error`] — error-source distinction and problem rendering
//! - [`gear`] — gear registration and capability wiring
//! - [`proxy`] — data plane: the `/oagw/v1/proxy/{alias}/…` endpoint

