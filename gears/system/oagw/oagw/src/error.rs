//! OAGW domain error model and its RFC 9457 (`application/problem+json`)
//! mapping.
//!
//! Every gateway failure carries a three-tuple that is stable on the wire:
//!
//! * the PRD error code (`docs/PRD.md` §5.6),
//! * the HTTP status of that code, and
//! * the GTS identifier of the error type (`docs/DESIGN.md` §3.3
//!   "Error Response Format").
//!
//! Two projections are provided so later phases cannot fork the model:
//!
//! * [`OagwError::problem`] builds the RFC 9457 body exactly as the OAGW
//!   wire contract documents it — `type` is the OAGW GTS identifier, and the
//!   `X-OAGW-Error-Source` value plus the OAGW extension fields
//!   (`upstream_id`, `host`, `path`, `retry_after_seconds`) live in
//!   `context`.
//! * [`OagwError::to_canonical`] / `From<OagwError> for
//!   [`toolkit_canonical_errors::CanonicalError`] projects the same failure
//!   onto the AIP-193 canonical categories, so handlers returning
//!   `toolkit::api::ApiResult` can propagate it with `?` and the toolkit
//!   `canonical_error_middleware` renders and logs it.
//!
//! Errors returned by an *upstream* are not [`OagwError`]s at all — they are
//! passthroughs (ADR 0007) — but the [`ErrorSource`] vocabulary is reserved
//! here so the data plane can only tag a response with one of the two
//! documented values.

