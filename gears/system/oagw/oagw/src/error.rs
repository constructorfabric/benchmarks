/// Domain errors of the OAGW gear.
///
/// Every variant carries a typed payload (never a bare string-only code) and
/// maps to exactly one documented PRD error code, HTTP status and GTS type
/// identifier — see [`OagwError::metadata`].
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum OagwError {
    /// 400 — generic validation failure (`ValidationError`).
    #[error("validation failed: {detail}")]
    Validation {
        /// Human-readable explanation of the violated invariant.
        detail: String,
    },

    /// 400 — alias does not satisfy the alias grammar or length bound.
    #[error("invalid upstream alias '{alias}': {reason}")]
    InvalidAlias {
        /// Rejected alias, as submitted.
        alias: String,
        /// Why the alias was rejected.
        reason: String,
    },

    /// 400 — the alias is a bare public suffix and would shadow a
    /// registrable suffix (`docs/PRD.md` §5.5, e.g. `co.uk`).
    #[error("alias '{alias}' is a bare public suffix and cannot be used as an upstream alias")]
    AliasShadowsPublicSuffix {
        /// Rejected alias.
        alias: String,
    },

    /// 400 — the endpoint pool is IP-based or shares no derivable suffix, so
    /// an explicit alias is mandatory (`docs/PRD.md` §5.5).
    #[error("{detail}")]
    AliasRequired {
        /// Human-readable explanation.
        detail: String,
    },

    /// 400 — an endpoint carries an invalid scheme, host or port.
    #[error("invalid upstream endpoint: {reason}")]
    InvalidEndpoint {
        /// Why the endpoint was rejected.
        reason: String,
    },

    /// 400 — the endpoint pool mixes schemes or ports
    /// (`docs/PRD.md` §5.5 "Multi-Endpoint Pooling").
    #[error("upstream endpoint pool is not homogeneous: {reason}")]
    EndpointPoolMismatch {
        /// Why the pool was rejected.
        reason: String,
    },

    /// 401 — upstream authentication failed.
    #[error("{detail}")]
    AuthenticationFailed {
        /// Human-readable explanation.
        detail: String,
    },

    /// 404 — no upstream is registered for the requested alias
    /// (`docs/PRD.md`: "Upstream not found: Return 404 `RouteNotFound`").
    #[error("no upstream registered for alias '{alias}'")]
    UpstreamNotFound {
        /// Requested alias.
        alias: String,
    },

    /// 404 — no route matched the request.
    #[error("{detail}")]
    RouteNotFound {
        /// Human-readable explanation.
        detail: String,
    },

    /// 409 — the alias is already used by another upstream of the same
    /// tenant (`docs/PRD.md` "Configure Upstream": alias conflict → 409).
    #[error("alias '{alias}' is already used by upstream {existing_upstream_id} in this tenant")]
    AliasConflict {
        /// Colliding alias.
        alias: String,
        /// Upstream that already holds the alias.
        existing_upstream_id: Uuid,
    },

    /// 409 — the plugin is still referenced by an upstream or route.
    #[error("plugin '{plugin_ref}' is referenced by an upstream or route")]
    PluginInUse {
        /// GTS identifier of the plugin.
        plugin_ref: String,
    },

    /// 409 — a management conflict the error tables name no dedicated code
    /// for: a resource is still referenced by another one (deleting an
    /// upstream a route still points at) or its identity keys are already
    /// claimed by a sibling (a duplicate route match rule,
    /// `docs/DESIGN.md` §3.3 "PUT (Replace)").
    #[error("{detail}")]
    Conflict {
        /// Human-readable explanation naming the colliding resources.
        detail: String,
    },

    /// 413 — request payload exceeds the configured body limit.
    #[error("request payload exceeds the {limit_bytes} byte limit")]
    PayloadTooLarge {
        /// Configured body limit in bytes.
        limit_bytes: u64,
    },

    /// 429 — rate limit exceeded (retry advice `Yes`).
    #[error("{detail}")]
    RateLimitExceeded {
        /// Retry guidance in seconds for the `Retry-After` header.
        retry_after_secs: u64,
        /// Human-readable explanation.
        detail: String,
    },

    /// 500 — the referenced credential is not in the credential store.
    #[error("secret '{secret_ref}' was not found in the credential store")]
    SecretNotFound {
        /// `cred://` URI of the missing secret.
        secret_ref: String,
    },

    /// 500 — unexpected gateway failure.
    #[error("internal gateway error: {detail}")]
    Internal {
        /// Human-readable explanation (kept out of the wire detail for
        /// `Internal` by the canonical-error projection).
        detail: String,
    },

    /// 502 — protocol-level error.
    #[error("{detail}")]
    ProtocolError {
        /// Human-readable explanation.
        detail: String,
    },

    /// 502 — upstream service error (retry advice `Depends`).
    #[error("{detail}")]
    DownstreamError {
        /// Human-readable explanation.
        detail: String,
    },

    /// 502 — stream connection aborted.
    #[error("{detail}")]
    StreamAborted {
        /// Human-readable explanation.
        detail: String,
    },

    /// 503 — upstream link unavailable (retry advice `Yes`).
    #[error("{detail}")]
    LinkUnavailable {
        /// Human-readable explanation.
        detail: String,
    },

    /// 503 — circuit breaker open (retry advice `Yes`).
    #[error("{detail}")]
    CircuitBreakerOpen {
        /// Human-readable explanation.
        detail: String,
    },

    /// 503 — plugin could not be resolved.
    #[error("plugin '{plugin_ref}' could not be resolved")]
    PluginNotFound {
        /// GTS identifier of the plugin.
        plugin_ref: String,
    },

    /// 504 — connection to the upstream timed out.
    #[error("{detail}")]
    ConnectionTimeout {
        /// Human-readable explanation.
        detail: String,
    },

    /// 504 — the upstream response exceeded the proxy timeout.
    #[error("{detail}")]
    RequestTimeout {
        /// Human-readable explanation.
        detail: String,
    },

    /// 504 — idle stream timeout.
    #[error("{detail}")]
    IdleTimeout {
        /// Human-readable explanation.
        detail: String,
    },
}

/// Request-scoped extension fields merged into an RFC 9457 problem body.
///
/// `instance` and `trace_id` map to the standard RFC 9457 fields;
/// `upstream_id` / `host` / `path` are the OAGW extension fields of
/// `docs/DESIGN.md` §3.3.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ProblemExtensions {
    /// URI reference of the request (RFC 9457 `instance`).
    pub instance: Option<String>,
    /// Upstream the request was resolved to.
    pub upstream_id: Option<Uuid>,
    /// Target host of the upstream, when resolved.
    pub host: Option<String>,
    /// Request path.
    pub path: Option<String>,
    /// Distributed-trace correlation id.
    pub trace_id: Option<String>,
}

/// Resource-scoped builder for the canonical projection of [`OagwError`].
///
/// Every OAGW gateway error is an *instance* of the platform error type
/// `cf.core.errors.err.v1~` (see [`ERROR_GTS_TYPE`]), so the marker carries
/// that type as the canonical `resource_type`; the OAGW-specific instance id
/// is written to `Problem.problem_type` by [`OagwError::problem`].
#[resource_error(gts_id!("cf.core.errors.err.v1~"))]
struct OagwProblemError;

impl OagwError {
    /// PRD error code, HTTP status, GTS type id and retry advice of this
    /// failure.
    #[must_use]
    pub const fn metadata(&self) -> ErrorMetadata {
        match self {
            Self::Validation { .. }
            | Self::InvalidAlias { .. }
            | Self::AliasShadowsPublicSuffix { .. }
            | Self::AliasRequired { .. }
            | Self::InvalidEndpoint { .. }
            | Self::EndpointPoolMismatch { .. } => META_VALIDATION,
            Self::AuthenticationFailed { .. } => META_AUTH_FAILED,
            Self::UpstreamNotFound { .. } | Self::RouteNotFound { .. } => META_ROUTE_NOT_FOUND,
            Self::AliasConflict { .. } => META_ALIAS_CONFLICT,
            Self::PluginInUse { .. } => META_PLUGIN_IN_USE,
            Self::Conflict { .. } => META_CONFLICT,
            Self::PayloadTooLarge { .. } => META_PAYLOAD_TOO_LARGE,
            Self::RateLimitExceeded { .. } => META_RATE_LIMIT,
            Self::SecretNotFound { .. } => META_SECRET_NOT_FOUND,
            Self::Internal { .. } => META_INTERNAL,
            Self::ProtocolError { .. } => META_PROTOCOL_ERROR,
            Self::DownstreamError { .. } => META_DOWNSTREAM,
            Self::StreamAborted { .. } => META_STREAM_ABORTED,
            Self::LinkUnavailable { .. } => META_LINK_UNAVAILABLE,
            Self::CircuitBreakerOpen { .. } => META_CIRCUIT_BREAKER,
            Self::PluginNotFound { .. } => META_PLUGIN_NOT_FOUND,
            Self::ConnectionTimeout { .. } => META_CONNECTION_TIMEOUT,
            Self::RequestTimeout { .. } => META_REQUEST_TIMEOUT,
            Self::IdleTimeout { .. } => META_IDLE_TIMEOUT,
        }
    }

    /// PRD error code of this failure.
    #[must_use]
    pub const fn code(&self) -> ErrorCode {
        self.metadata().code
    }

    /// HTTP status of the RFC 9457 response.
    #[must_use]
    pub const fn http_status(&self) -> u16 {
        self.metadata().http_status
    }

    /// GTS identifier of the error type. Timeout variants carry their own
    /// (connection / request / idle) identifier, all mapped to
    /// [`ErrorCode::Timeout`].
    #[must_use]
    pub const fn gts_type_id(&self) -> &'static str {
        self.metadata().gts_type_id
    }

    /// Retry advice of the PRD §5.6 table.
    #[must_use]
    pub const fn retry_advice(&self) -> RetryAdvice {
        self.metadata().retry_advice
    }

    /// Error source of this failure (ADR 0007).
    ///
    /// Everything modelled here is generated by OAGW, so it is always
    /// [`ErrorSource::Gateway`]; upstream failures are *not* [`OagwError`]s —
    /// they are passed through untouched and tagged
    /// [`ErrorSource::Upstream`] by the data plane.
    #[must_use]
    pub const fn error_source(&self) -> ErrorSource {
        ErrorSource::Gateway
    }

    /// Identifier of the resource the failure is about, when there is one.
    /// Becomes the canonical `resource_name` of the problem.
    #[must_use]
    pub fn resource_name(&self) -> Option<&str> {
        match self {
            Self::UpstreamNotFound { alias } | Self::AliasConflict { alias, .. } => {
                Some(alias.as_str())
            }
            Self::PluginInUse { plugin_ref } | Self::PluginNotFound { plugin_ref } => {
                Some(plugin_ref.as_str())
            }
            Self::SecretNotFound { secret_ref } => Some(secret_ref.as_str()),
            _ => None,
        }
    }

    /// Retry guidance in seconds, when the failure carries one.
    #[must_use]
    pub const fn retry_after_secs(&self) -> Option<u64> {
        match self {
            Self::RateLimitExceeded {
                retry_after_secs, ..
            } => Some(*retry_after_secs),
            _ => None,
        }
    }

    /// Builds the RFC 9457 `application/problem+json` body for this failure,
    /// as specified by `docs/DESIGN.md` §3.3: `type` is the OAGW GTS
    /// identifier, and the `X-OAGW-Error-Source` value plus the OAGW
    /// extension fields travel in `context`.
    #[must_use]
    pub fn problem(&self, extensions: ProblemExtensions) -> Problem {
        let metadata = self.metadata();
        let mut problem = Problem::from(self.to_canonical());
        problem.problem_type = metadata.gts_type_id.to_owned();
        problem.error_code = Some(metadata.code.as_str().to_owned());
        problem.error_domain = Some(ERROR_DOMAIN.to_owned());
        if let Some(instance) = &extensions.instance {
            problem.instance = Some(instance.clone());
        }
        if let Some(trace_id) = &extensions.trace_id {
            problem.trace_id = Some(trace_id.clone());
        }
        if let Some(context) = problem.context.as_object_mut() {
            self.extend_context(&mut *context, &extensions);
        }
        problem
    }

    /// Canonical (AIP-193) projection, for `toolkit` handlers returning
    /// `ApiResult` (propagation via `?`).
    #[must_use]
    pub fn to_canonical(&self) -> CanonicalError {
        let status = self.http_status();
        let detail = self.to_string();
        match status {
            401 => CanonicalError::unauthenticated()
                .with_reason(detail)
                .create(),
            404 => not_found_canonical(&detail, self.resource_name()),
            409 => already_exists_canonical(&detail, self.resource_name()),
            413 => invalid_argument_canonical(&detail, Some(413)),
            429 => rate_limited_canonical(&detail, self.retry_after_secs()),
            500 | 502 => internal_canonical(&detail, status),
            503 => CanonicalError::service_unavailable()
                .with_detail(detail)
                .create(),
            504 => OagwProblemError::deadline_exceeded(detail).create(),
            // 400 and any future client-fault status fall back to the
            // canonical client-fault category.
            _ => invalid_argument_canonical(&detail, None),
        }
    }

    /// Fills the `context` object of a problem body with the OAGW extension
    /// fields.
    fn extend_context(
        &self,
        context: &mut serde_json::Map<String, serde_json::Value>,
        extensions: &ProblemExtensions,
    ) {
        context.insert(
            "error_source".to_owned(),
            serde_json::Value::String(self.error_source().as_str().to_owned()),
        );
        if let Some(upstream_id) = extensions.upstream_id {
            context.insert(
                "upstream_id".to_owned(),
                serde_json::Value::String(upstream_id.to_string()),
            );
        }
        if let Some(host) = &extensions.host {
            context.insert("host".to_owned(), serde_json::Value::String(host.clone()));
        }
        if let Some(path) = &extensions.path {
            context.insert("path".to_owned(), serde_json::Value::String(path.clone()));
        }
        if let Some(retry_after) = self.retry_after_secs() {
            context.insert(
                "retry_after_seconds".to_owned(),
                serde_json::Value::from(retry_after),
            );
        }
    }

    /// Human-readable detail used as the RFC 9457 `detail` field.
    #[must_use]
    pub fn detail(&self) -> Cow<'_, str> {
        Cow::Owned(self.to_string())
    }
}

impl From<OagwError> for CanonicalError {
    fn from(err: OagwError) -> Self {
        err.to_canonical()
    }
}

/// Canonical `invalid_argument` projection (400, or 413 with a same-class
/// status override for the body-limit violation).
fn invalid_argument_canonical(detail: &str, status_override: Option<u16>) -> CanonicalError {
    let builder = OagwProblemError::invalid_argument().with_format(detail);
    match status_override {
        Some(status) => builder.with_override(Http::status_code(status)).create(),
        None => builder.create(),
    }
}

/// Resource name used by the AIP-193 `not_found` / `already_exists`
/// projections when the failure carries no specific resource identifier: the
/// toolkit requires one for those categories.
const CANONICAL_RESOURCE_FALLBACK: &str = "oagw.resource";

/// Canonical `not_found` projection (404).
fn not_found_canonical(detail: &str, resource: Option<&str>) -> CanonicalError {
    OagwProblemError::not_found(detail)
        .with_resource(resource.unwrap_or(CANONICAL_RESOURCE_FALLBACK))
        .create()
}

/// Canonical `already_exists` projection (409).
fn already_exists_canonical(detail: &str, resource: Option<&str>) -> CanonicalError {
    OagwProblemError::already_exists(detail)
        .with_resource(resource.unwrap_or(CANONICAL_RESOURCE_FALLBACK))
        .create()
}

/// Canonical `resource_exhausted` projection (429), carrying the retry hint
/// as a quota violation.
fn rate_limited_canonical(detail: &str, retry_after_secs: Option<u64>) -> CanonicalError {
    let builder = OagwProblemError::resource_exhausted(detail)
        .with_quota_violation(RATE_LIMIT_QUOTA_SUBJECT, detail);
    match retry_after_secs {
        Some(secs) => builder
            .with_quota_violation_retry_after_seconds(secs)
            .create(),
        None => builder.create(),
    }
}

/// Canonical `internal` projection (500, or 502 with a same-class status
/// override for upstream failures).
fn internal_canonical(detail: &str, status: u16) -> CanonicalError {
    let builder = CanonicalError::internal(detail);
    if status == 502 {
        builder.with_override(Http::status_code(502)).create()
    } else {
        builder.create()
    }
}

