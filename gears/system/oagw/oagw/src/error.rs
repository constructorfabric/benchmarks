/// Header that distinguishes gateway errors from upstream passthroughs
/// (ADR 0007). Wire spelling: `X-OAGW-Error-Source`.
pub const ERROR_SOURCE_HEADER: &str = "x-oagw-error-source";

/// `X-OAGW-Error-Source` value for an error generated by OAGW.
pub const ERROR_SOURCE_GATEWAY: &str = "gateway";

/// `X-OAGW-Error-Source` value for an upstream response passed through as-is.
pub const ERROR_SOURCE_UPSTREAM: &str = "upstream";

/// Namespace owning the machine-readable `error_code` problem extension
/// field (`<service>.<version>`, per `Problem::with_error_domain`).
pub const ERROR_DOMAIN: &str = "oagw.v1";

/// GTS type of every OAGW gateway error instance
/// (`docs/DESIGN.md` §3.3: all `type` values are instances of
/// `cf.core.errors.err.v1~`).
pub const ERROR_GTS_TYPE: &str = gts_id!("cf.core.errors.err.v1~");

/// Subject used for the quota violation of a rate-limit problem.
const RATE_LIMIT_QUOTA_SUBJECT: &str = "oagw.rate_limit";

/// Whether a client should retry after this failure (`docs/PRD.md` §5.6
/// "Retriable" column).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum RetryAdvice {
    /// Never retry (PRD: `No`).
    Never,
    /// Retry only when the failure cause says so (PRD: `Depends`).
    Depends,
    /// Safe to retry (PRD: `Yes`).
    Always,
}

impl RetryAdvice {
    /// `true` unless the code explicitly forbids a retry.
    #[must_use]
    pub const fn is_retryable(self) -> bool {
        !matches!(self, Self::Never)
    }
}

impl fmt::Display for RetryAdvice {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let label = match self {
            Self::Never => "no",
            Self::Depends => "depends",
            Self::Always => "yes",
        };
        write!(f, "{label}")
    }
}

/// Whether an error was produced by OAGW or passed through from an upstream
/// (ADR 0007).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ErrorSource {
    /// Error generated by OAGW (rate limit, auth failure, route not found,
    /// timeout, circuit breaker). Response body is `application/problem+json`.
    Gateway,
    /// Error returned by the upstream service and passed through unchanged.
    Upstream,
}

impl ErrorSource {
    /// Value carried by the [`ERROR_SOURCE_HEADER`] header.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Gateway => ERROR_SOURCE_GATEWAY,
            Self::Upstream => ERROR_SOURCE_UPSTREAM,
        }
    }
}

impl fmt::Display for ErrorSource {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.as_str())
    }
}

/// Documented OAGW error codes.
///
/// `ValidationError` .. `Timeout` are the nine codes of `docs/PRD.md` §5.6;
/// the remainder are the additional rows of the
/// `docs/DESIGN.md` §3.3 error table. Each code fixes an HTTP status, a GTS
/// type identifier and a retry advice.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ErrorCode {
    /// 400 — request or configuration validation failed.
    ValidationError,
    /// 401 — authentication to the upstream failed.
    AuthenticationFailed,
    /// 404 — no matching route (or no upstream for the requested alias).
    RouteNotFound,
    /// 409 — the requested alias is already taken in this tenant
    /// (`docs/PRD.md` "Configure Upstream": alias conflict → 409).
    AliasConflict,
    /// 409 — plugin still referenced by an upstream or route.
    PluginInUse,
    /// 409 — management conflict with no dedicated documented code: a
    /// resource is still referenced by another one, or its match keys are
    /// already claimed by a sibling resource.
    Conflict,
    /// 413 — request payload exceeds the body limit.
    PayloadTooLarge,
    /// 429 — rate limit exceeded.
    RateLimitExceeded,
    /// 500 — referenced credential is missing from the credential store.
    SecretNotFound,
    /// 500 — unexpected gateway failure.
    Internal,
    /// 502 — protocol-level error while talking to the upstream.
    ProtocolError,
    /// 502 — upstream service error.
    DownstreamError,
    /// 502 — stream connection aborted.
    StreamAborted,
    /// 503 — upstream link unavailable.
    LinkUnavailable,
    /// 503 — circuit breaker open.
    CircuitBreakerOpen,
    /// 503 — plugin not found.
    PluginNotFound,
    /// 504 — connection, request or idle timeout.
    Timeout,
}

