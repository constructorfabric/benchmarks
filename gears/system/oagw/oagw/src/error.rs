    #[test]
    fn problem_json_contains_standard_and_extension_fields() {
        let err = OagwError::rate_limit_exceeded("upstream api.openai.com is over budget", 15)
            .with_instance("/oagw/v1/upstreams")
            .with_extension("upstream_id", json!("uuid-123"))
            .with_extension("host", json!("api.openai.com"))
            .with_trace_id("01J...");

        let body = err.to_problem_json();
        let obj = body.as_object().expect("problem body must be an object");

        assert_eq!(
            obj.get("type").and_then(Value::as_str),
            Some("gts.cf.core.errors.err.v1~cf.oagw.rate_limit.exceeded.v1")
        );
        assert_eq!(
            obj.get("title").and_then(Value::as_str),
            Some("Rate Limit Exceeded")
        );
        assert_eq!(obj.get("status").and_then(Value::as_u64), Some(429));
        assert_eq!(
            obj.get("detail").and_then(Value::as_str),
            Some("upstream api.openai.com is over budget")
        );
        assert_eq!(
            obj.get("retry_after_seconds").and_then(Value::as_u64),
            Some(15)
        );
        assert_eq!(
            obj.get("upstream_id").and_then(Value::as_str),
            Some("uuid-123")
        );
        assert_eq!(
            obj.get("host").and_then(Value::as_str),
            Some("api.openai.com")
        );
        assert_eq!(obj.get("trace_id").and_then(Value::as_str), Some("01J..."));
        assert_eq!(
            obj.get("instance").and_then(Value::as_str),
            Some("/oagw/v1/upstreams")
        );
        // Middleware-compatible mirror of the extension fields.
        let ctx = obj
            .get("context")
            .and_then(Value::as_object)
            .expect("context object");
        assert_eq!(
            ctx.get("upstream_id").and_then(Value::as_str),
            Some("uuid-123")
        );
    }

