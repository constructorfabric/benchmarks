/// A gateway error occurrence.
///
/// Carries the fixed [`OagwErrorKind`] metadata plus the per-occurrence
/// detail, the RFC 9457 `instance` and OAGW extension fields
/// (`upstream_id`, `host`, `path`, `retry_after_seconds`, `trace_id`, ...).
#[derive(Debug, Clone, PartialEq)]
pub struct OagwError {
    kind: OagwErrorKind,
    detail: String,
    instance: Option<String>,
    extensions: BTreeMap<String, Value>,
}

impl OagwError {
    /// Build an error of `kind` from a displayable detail.
    #[must_use]
    pub fn new(kind: OagwErrorKind, detail: impl Into<String>) -> Self {
        Self {
            kind,
            detail: detail.into(),
            instance: None,
            extensions: BTreeMap::new(),
        }
    }

    /// Attach the RFC 9457 `instance` URI reference.
    #[must_use]
    pub fn with_instance(mut self, instance: impl Into<String>) -> Self {
        self.instance = Some(instance.into());
        self
    }

    /// Attach an OAGW extension field (e.g. `upstream_id`, `host`, `path`).
    #[must_use]
    pub fn with_extension(mut self, key: impl Into<String>, value: Value) -> Self {
        self.extensions.insert(key.into(), value);
        self
    }

    /// Attach the distributed-tracing correlation id (DESIGN §3.3).
    #[must_use]
    pub fn with_trace_id(mut self, trace_id: impl Into<String>) -> Self {
        self.extensions
            .insert("trace_id".to_owned(), Value::String(trace_id.into()));
        self
    }

    /// Attach retry guidance, also surfaced as the `Retry-After` header.
    #[must_use]
    pub fn with_retry_after_secs(mut self, seconds: u64) -> Self {
        self.extensions
            .insert("retry_after_seconds".to_owned(), json!(seconds));
        self
    }

    /// Attach the rate-limit state of a 429 (ADR-0003 "Response Headers").
    ///
    /// It becomes the `rate_limit` extension member of the problem document and
    /// the `X-RateLimit-Limit`, `X-RateLimit-Remaining` and `X-RateLimit-Reset`
    /// headers of the response; see
    /// [`crate::domain::policy::rate_limit::RateLimitDecision`].
    #[must_use]
    pub fn with_rate_limit_state(
        mut self,
        limit: &str,
        remaining: u64,
        reset_unix_secs: u64,
    ) -> Self {
        self.extensions.insert(
            "rate_limit".to_owned(),
            json!({
                "limit": limit,
                "remaining": remaining,
                "reset_unix_seconds": reset_unix_secs,
            }),
        );
        self
    }

    /// The rate-limit state carried by a 429, as `(limit, remaining, reset)`.
    #[must_use]
    pub fn rate_limit_state(&self) -> Option<(&str, u64, u64)> {
        let state = self.extensions.get("rate_limit")?.as_object()?;
        Some((
            state.get("limit")?.as_str()?,
            state.get("remaining")?.as_u64()?,
            state.get("reset_unix_seconds")?.as_u64()?,
        ))
    }

    /// The error kind.
    #[must_use]
    pub const fn kind(&self) -> OagwErrorKind {
        self.kind
    }

    /// The per-occurrence detail.
    #[must_use]
    pub fn detail(&self) -> &str {
        &self.detail
    }

    /// The RFC 9457 `instance`, when known.
    #[must_use]
    pub fn instance(&self) -> Option<&str> {
        self.instance.as_deref()
    }

    /// The OAGW extension fields.
    #[must_use]
    pub const fn extensions(&self) -> &BTreeMap<String, Value> {
        &self.extensions
    }

    /// HTTP status for this occurrence.
    #[must_use]
    pub const fn status(&self) -> StatusCode {
        self.kind.http_status()
    }

    /// Render the RFC 9457 problem document body for this occurrence.
    ///
    /// The standard fields come first, then the OAGW extension fields, then a
    /// `context` object that mirrors the extension fields. The `context` member
    /// is what the host gateway's canonical error middleware round-trips
    /// (`toolkit::api::canonical_error_middleware` re-serializes every
    /// `application/problem+json` body into its `Problem` model, which has a
    /// required `context` member and drops unknown top-level members); keeping
    /// the extensions there too means they survive that round-trip while the
    /// flat form stays byte-compatible with the ADR-0007 examples.
    #[must_use]
    pub fn to_problem_json(&self) -> Value {
        let mut body = Map::new();
        body.insert("type".to_owned(), json!(self.kind.gts_type_id()));
        body.insert("title".to_owned(), json!(self.kind.title()));
        body.insert("status".to_owned(), json!(self.status().as_u16()));
        body.insert("detail".to_owned(), json!(self.detail));
        if let Some(instance) = &self.instance {
            body.insert("instance".to_owned(), json!(instance));
        }
        for (key, value) in &self.extensions {
            body.insert(key.clone(), value.clone());
        }
        body.insert("context".to_owned(), Value::Object(self.context_member()));

        Value::Object(body)
    }

    /// Extension fields collected into the middleware-compatible `context`
    /// member of the problem document.
    fn context_member(&self) -> Map<String, Value> {
        self.extensions
            .iter()
            .map(|(key, value)| (key.clone(), value.clone()))
            .collect()
    }

    /// Render this error as an axum [`http::Response`](axum::response::Response).
    #[must_use]
    pub fn to_response(&self) -> axum::response::Response {
        error::render_problem(self)
    }

    /// `Retry-After` guidance carried by this error, in seconds.
    #[must_use]
    pub fn retry_after_secs(&self) -> Option<u64> {
        match self.extensions.get("retry_after_seconds") {
            Some(Value::Number(n)) => n.as_u64(),
            Some(Value::String(s)) => s.parse().ok(),
            _ => None,
        }
    }
}

impl fmt::Display for OagwError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}: {}", self.kind, self.detail)
    }
}

impl std::error::Error for OagwError {}

impl From<OagwErrorKind> for OagwError {
    fn from(kind: OagwErrorKind) -> Self {
        Self::new(kind, kind.title())
    }
}

impl axum::response::IntoResponse for OagwError {
    fn into_response(self) -> axum::response::Response {
        error::render_problem(&self)
    }
}

/// Constructors for the documented error kinds.
impl OagwError {
    /// 400 — request validation failed.
    #[must_use]
    pub fn validation(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::ValidationError, detail)
    }

    /// 404 — no matching route.
    #[must_use]
    pub fn route_not_found(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::RouteNotFound, detail)
    }

    /// 400 — `X-OAGW-Target-Host` is required to disambiguate a multi-endpoint
    /// upstream with a common-suffix alias, and none was supplied.
    #[must_use]
    pub fn missing_target_host(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::MissingTargetHost, detail)
    }

    /// 400 — `X-OAGW-Target-Host` is not a hostname or IP literal.
    #[must_use]
    pub fn invalid_target_host(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::InvalidTargetHost, detail)
    }

    /// 400 — `X-OAGW-Target-Host` matches no endpoint of the upstream.
    #[must_use]
    pub fn unknown_target_host(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::UnknownTargetHost, detail)
    }

    /// 503 — the upstream link is unavailable (disabled upstream), with retry
    /// guidance.
    #[must_use]
    pub fn link_unavailable(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::LinkUnavailable, detail)
    }

    /// 504 — establishing the upstream connection timed out.
    #[must_use]
    pub fn connection_timeout(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::ConnectionTimeout, detail)
    }

    /// 404 — upstream unknown for the calling tenant.
    #[must_use]
    pub fn upstream_not_found(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::UpstreamNotFound, detail)
    }

    /// 503 — plugin unknown for the calling tenant (DESIGN §3.3 error table).
    #[must_use]
    pub fn plugin_not_found(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::PluginNotFound, detail)
    }

    /// 409 — duplicate alias within the tenant.
    #[must_use]
    pub fn alias_conflict(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::AliasConflict, detail)
    }

    /// 409 — duplicate route match rule within the upstream.
    #[must_use]
    pub fn match_conflict(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::MatchConflict, detail)
    }

    /// 409 — plugin still referenced by an upstream or route.
    #[must_use]
    pub fn plugin_in_use(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::PluginInUse, detail)
    }

    /// 413 — payload above the hard limit.
    #[must_use]
    pub fn payload_too_large(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::PayloadTooLarge, detail)
    }

    /// 401 — authentication to the upstream failed.
    #[must_use]
    pub fn authentication_failed(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::AuthenticationFailed, detail)
    }

    /// 401 — the request carries no authenticated caller.
    ///
    /// Used by the fail-closed tenant resolution: a request without a caller
    /// context (or with an anonymous one) is never served against a default
    /// tenant.
    #[must_use]
    pub fn authentication_required() -> Self {
        Self::new(
            OagwErrorKind::AuthenticationFailed,
            "authentication required",
        )
    }

    /// 429 — rate limit exceeded, with retry guidance.
    #[must_use]
    pub fn rate_limit_exceeded(detail: impl Into<String>, retry_after_secs: u64) -> Self {
        Self::new(OagwErrorKind::RateLimitExceeded, detail).with_retry_after_secs(retry_after_secs)
    }

    /// 503 — circuit breaker open, with retry guidance.
    #[must_use]
    pub fn circuit_breaker_open(detail: impl Into<String>, retry_after_secs: u64) -> Self {
        Self::new(OagwErrorKind::CircuitBreakerOpen, detail).with_retry_after_secs(retry_after_secs)
    }

    /// 502 — upstream returned an error.
    #[must_use]
    pub fn downstream_error(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::DownstreamError, detail)
    }

    /// 403 — an actual (non-preflight) cross-origin request came from an origin
    /// the upstream does not allow (ADR-0004 "Error Responses").
    ///
    /// Preflight requests are *never* rejected here: ADR-0004 answers them
    /// permissively and defers origin validation to the actual request.
    #[must_use]
    pub fn cors_origin_not_allowed(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::CorsOriginNotAllowed, detail)
    }

    /// 403 — an actual (non-preflight) cross-origin request used a method the
    /// upstream does not allow (ADR-0004 "Error Responses").
    #[must_use]
    pub fn cors_method_not_allowed(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::CorsMethodNotAllowed, detail)
    }

    /// 500 — a `cred://` secret reference could not be resolved (DESIGN §3.3
    /// error table `SecretNotFound`).
    ///
    /// Fail-closed by construction: an auth plugin that cannot obtain the
    /// credential it is configured to inject never forwards the request
    /// without it, because injecting *nothing* would silently downgrade the
    /// upstream's authentication.
    #[must_use]
    pub fn secret_not_found(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::SecretNotFound, detail)
    }

    /// 504 — outbound request timed out.
    #[must_use]
    pub fn timeout(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::Timeout, detail)
    }

    /// 405 — HTTP method not supported by the endpoint.
    #[must_use]
    pub fn method_not_allowed(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::MethodNotAllowed, detail)
    }

    /// 500 — unrecoverable gateway failure.
    #[must_use]
    pub fn internal(detail: impl Into<String>) -> Self {
        Self::new(OagwErrorKind::InternalError, detail)
    }
}

/// Serialize a response header value for the error-source header.
///
/// Exposed for the data-plane slice, which must stamp
/// `X-OAGW-Error-Source: upstream` on passthrough responses too.
#[must_use]
pub fn error_source_header_value(source: &str) -> HeaderValue {
    HeaderValue::from_str(source).unwrap_or(HeaderValue::from_static(ERROR_SOURCE_GATEWAY))
}

/// Header name for [`ERROR_SOURCE_HEADER`].
#[must_use]
pub fn error_source_header_name() -> HeaderName {
    HeaderName::from_static(ERROR_SOURCE_HEADER)
}

