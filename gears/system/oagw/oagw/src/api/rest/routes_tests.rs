#![allow(clippy::unwrap_used, clippy::expect_used)]
//! `Router::oneshot` tests of the management API.
//!
//! They exercise the HTTP surface itself: status codes, the JSON shape of the
//! stored representations, the `Problem` envelope of every failure and the
//! `OData` list parameters. Every request injects the caller's
//! [`SecurityContext`] as an extension, exactly as the gateway middleware does.

use std::sync::Arc;

use axum::Router;
use axum::body::{Body, to_bytes};
use axum::http::{Request, StatusCode};
use serde_json::Value;
use toolkit::api::OpenApiRegistryImpl;
use toolkit_security::SecurityContext;
use tower::ServiceExt;
use uuid::Uuid;

use crate::domain::service::Service;
use crate::infra::store::Store;

use super::register_routes;

// ── Harness ───────────────────────────────────────────────────────────────

/// Builds the router with a fresh store behind the shared service.
fn harness() -> (Router, Arc<Store>) {
    let store = Arc::new(Store::new());
    let svc = Arc::new(Service::new(
        Arc::clone(&store),
        Arc::new(toolkit::ClientHub::new()),
    ));
    let openapi = OpenApiRegistryImpl::new();
    let router = register_routes(Router::new(), &openapi, svc);
    (router, store)
}

/// The security context of one tenant, as the gateway middleware would inject.
fn ctx(tenant: Uuid) -> SecurityContext {
    SecurityContext::builder()
        .subject_id(Uuid::now_v7())
        .subject_tenant_id(tenant)
        .build()
        .expect("valid security context")
}

/// Builds a JSON request with the `SecurityContext` injected as an extension.
fn request(method: &str, uri: &str, body: Option<Value>, tenant: Uuid) -> Request<Body> {
    let mut builder = Request::builder().method(method).uri(uri);
    if body.is_some() {
        builder = builder.header("content-type", "application/json");
    }
    let body = match body {
        Some(json) => Body::from(serde_json::to_vec(&json).unwrap()),
        None => Body::empty(),
    };
    let mut req = builder.body(body).unwrap();
    req.extensions_mut().insert(ctx(tenant));
    req
}

/// Deserializes a JSON response body, or `null` for an empty one.
async fn body(response: axum::response::Response) -> Value {
    let bytes = to_bytes(response.into_body(), 1024 * 256).await.unwrap();
    serde_json::from_slice(&bytes).unwrap_or(Value::Null)
}

/// An upstream payload with one HTTPS hostname endpoint.
fn hostname_upstream(host: &str) -> Value {
    serde_json::json!({
        "server": { "endpoints": [{ "scheme": "https", "host": host, "port": 443 }] },
        "protocol": "gts.cf.core.oagw.protocol.v1~cf.core.oagw.http.v1",
    })
}

/// An upstream payload with one HTTPS IP endpoint and an explicit alias.
fn ip_upstream(alias: &str) -> Value {
    serde_json::json!({
        "alias": alias,
        "server": { "endpoints": [{ "scheme": "https", "host": "10.0.0.1", "port": 443 }] },
        "protocol": "gts.cf.core.oagw.protocol.v1~cf.core.oagw.http.v1",
    })
}

/// A route payload with a single GET rule on `path`.
fn route_request(upstream_id: Uuid, path: &str) -> Value {
    serde_json::json!({
        "upstream_id": upstream_id,
        "match": {
            "http": { "methods": ["GET"], "path": path, "path_suffix_mode": "append" },
        },
    })
}

