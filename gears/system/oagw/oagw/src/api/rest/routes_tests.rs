#[tokio::test]
async fn a_request_without_a_security_context_is_a_401() {
    let (router, _) = harness();

    // The same request without the injected extension.
    let req = Request::builder()
        .method("POST")
        .uri("/oagw/v1/upstreams")
        .header("content-type", "application/json")
        .body(Body::from(
            serde_json::to_vec(&hostname_upstream("api.openai.com")).unwrap(),
        ))
        .unwrap();
    let response = router.oneshot(req).await.unwrap();
    assert_eq!(response.status(), StatusCode::UNAUTHORIZED);
}

#[tokio::test]
async fn an_invalid_payload_is_a_400_with_field_violations() {
    let (router, _) = harness();
    let tenant = Uuid::new_v4();

    let payload = serde_json::json!({
        "server": { "endpoints": [{ "scheme": "https", "host": "api.openai.com", "port": 70000 }] },
        "protocol": "gts.cf.core.oagw.protocol.v1~cf.core.oagw.http.v1",
    });
    let response = router
        .clone()
        .oneshot(request("POST", "/oagw/v1/upstreams", Some(payload), tenant))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::BAD_REQUEST);
    let problem = body(response).await;
    let violations = problem["context"]["field_violations"]
        .as_array()
        .cloned()
        .unwrap_or_default();
    assert!(!violations.is_empty(), "{problem}");
    assert_eq!(violations[0]["field"], "server.endpoints[0].port");

    // An empty payload is missing its required fields.
    let response = router
        .clone()
        .oneshot(request(
            "POST",
            "/oagw/v1/upstreams",
            Some(serde_json::json!({})),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::BAD_REQUEST);

    // A route payload without methods is rejected as well.
    let upstream_id = create_upstream(&router, tenant).await;
    let response = router
        .clone()
        .oneshot(request(
            "POST",
            "/oagw/v1/routes",
            Some(serde_json::json!({
                "upstream_id": upstream_id,
                "match": { "http": { "methods": [], "path": "/v1", "path_suffix_mode": "append" } },
            })),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::BAD_REQUEST);
}

#[tokio::test]
async fn a_route_cors_block_allowing_credentials_on_a_wildcard_is_a_400() {
    let (router, _) = harness();
    let tenant = Uuid::new_v4();
    let upstream_id = create_upstream(&router, tenant).await;

    let response = router
        .clone()
        .oneshot(request(
            "POST",
            "/oagw/v1/routes",
            Some(serde_json::json!({
                "upstream_id": upstream_id,
                "match": { "http": { "methods": ["GET"], "path": "/v1", "path_suffix_mode": "append" } },
                "cors": { "enabled": true, "allowed_origins": ["*"], "allowed_methods": ["GET"],
                          "allow_credentials": true },
            })),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::BAD_REQUEST);
    let problem = body(response).await;
    let violations = problem["context"]["field_violations"]
        .as_array()
        .cloned()
        .unwrap_or_default();
    assert!(!violations.is_empty(), "{problem}");
    assert!(
        violations
            .iter()
            .any(|violation| violation["field"] == "cors.allow_credentials"),
        "{problem}"
    );
}
