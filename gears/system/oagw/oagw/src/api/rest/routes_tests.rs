#[tokio::test]
async fn create_upstream_returns_201_with_a_server_generated_id() {
    let (router, store) = harness();
    let tenant = Uuid::new_v4();

    let response = router
        .clone()
        .oneshot(request(
            "POST",
            "/oagw/v1/upstreams",
            Some(hostname_upstream("api.openai.com")),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::CREATED);

    let created = body(response).await;
    let id = created["id"]
        .as_str()
        .expect("id")
        .parse::<Uuid>()
        .expect("uuid");
    assert_ne!(id, Uuid::nil(), "the id is generated by the server");
    assert_eq!(created["alias"], "api.openai.com");
    assert_eq!(created["enabled"], true);
    assert_eq!(
        created["protocol"],
        "gts.cf.core.oagw.protocol.v1~cf.core.oagw.http.v1"
    );
    assert_eq!(created["server"]["endpoints"][0]["host"], "api.openai.com");
    assert!(store.get_upstream(tenant, id).is_some(), "stored");
}

