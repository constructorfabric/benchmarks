#[tokio::test]
async fn a_route_put_is_a_full_replacement_and_cannot_move_the_upstream() {
    let (router, _) = harness();
    let tenant = Uuid::new_v4();
    let upstream_id = create_upstream(&router, tenant).await;

    let response = router
        .clone()
        .oneshot(request(
            "POST",
            "/oagw/v1/routes",
            Some(route_request(upstream_id, "/v1/chat")),
            tenant,
        ))
        .await
        .unwrap();
    let id: Uuid = body(response).await["id"]
        .as_str()
        .expect("id")
        .parse()
        .unwrap();

    // Full replacement with an unchanged `upstream_id`.
    let response = router
        .clone()
        .oneshot(request(
            "PUT",
            &format!("/oagw/v1/routes/{id}"),
            Some(route_request(upstream_id, "/v2/chat")),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::OK);
    assert_eq!(
        body(response).await["match_rule"]["http"]["path"],
        "/v2/chat"
    );

    // Renaming the upstream is a 400.
    let response = router
        .clone()
        .oneshot(request(
            "PUT",
            &format!("/oagw/v1/routes/{id}"),
            Some(route_request(Uuid::new_v4(), "/v2/chat")),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::BAD_REQUEST);

    // A payload without `upstream_id` keeps the existing upstream (it is
    // immutable, not re-required).
    let response = router
        .clone()
        .oneshot(request(
            "PUT",
            &format!("/oagw/v1/routes/{id}"),
            Some(serde_json::json!({
                "match": {
                    "http": { "methods": ["GET"], "path": "/v3", "path_suffix_mode": "append" },
                },
            })),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::OK);
    assert_eq!(body(response).await["upstream_id"], upstream_id.to_string());

    // The same match rule of another route is still a 409.
    let response = router
        .clone()
        .oneshot(request(
            "POST",
            "/oagw/v1/routes",
            Some(route_request(upstream_id, "/v3")),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::CONFLICT);
}

