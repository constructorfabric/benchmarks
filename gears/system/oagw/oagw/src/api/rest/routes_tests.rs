#[tokio::test]
async fn a_put_is_a_full_replacement_and_never_changes_the_alias() {
    let (router, store) = harness();
    let tenant = Uuid::new_v4();

    let id: Uuid = {
        let response = router
            .clone()
            .oneshot(request(
                "POST",
                "/oagw/v1/upstreams",
                Some(hostname_upstream("api.openai.com")),
                tenant,
            ))
            .await
            .unwrap();
        body(response).await["id"]
            .as_str()
            .expect("id")
            .parse()
            .unwrap()
    };

    // Full replacement: tags are added and the optional `cors` block cleared.
    let mut replacement = hostname_upstream("api.openai.com");
    replacement["tags"] = serde_json::json!(["llm"]);
    replacement["cors"] = serde_json::json!({ "enabled": true, "allowed_origins": ["*"] });
    let response = router
        .clone()
        .oneshot(request(
            "PUT",
            &format!("/oagw/v1/upstreams/{id}"),
            Some(replacement),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::OK);
    let replaced = body(response).await;
    assert_eq!(replaced["id"], id.to_string());
    assert_eq!(replaced["alias"], "api.openai.com");
    assert_eq!(replaced["tags"], serde_json::json!(["llm"]));
    assert_eq!(
        replaced["cors"]["allowed_origins"],
        serde_json::json!(["*"])
    );

    // An endpoint change that would move the alias is rejected.
    let response = router
        .clone()
        .oneshot(request(
            "PUT",
            &format!("/oagw/v1/upstreams/{id}"),
            Some(hostname_upstream("api2.openai.com")),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::BAD_REQUEST);

    // Derivable -> non-derivable is rejected even with an explicit alias.
    let response = router
        .clone()
        .oneshot(request(
            "PUT",
            &format!("/oagw/v1/upstreams/{id}"),
            Some(ip_upstream("api.openai.com")),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::BAD_REQUEST);
    assert!(store.get_upstream(tenant, id).is_some(), "unchanged");
}

#[tokio::test]
async fn status_transitions_are_persisted() {
    let (router, store) = harness();
    let tenant = Uuid::new_v4();

    let response = router
        .clone()
        .oneshot(request(
            "POST",
            "/oagw/v1/upstreams",
            Some(ip_upstream("internal")),
            tenant,
        ))
        .await
        .unwrap();
    let id: Uuid = body(response).await["id"]
        .as_str()
        .expect("id")
        .parse()
        .unwrap();

    let response = router
        .clone()
        .oneshot(request(
            "POST",
            &format!("/oagw/v1/upstreams/{id}/status"),
            Some(serde_json::json!({ "enabled": false })),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::OK);
    assert_eq!(body(response).await["enabled"], false);
    assert!(!store.get_upstream(tenant, id).unwrap().enabled);

    let response = router
        .clone()
        .oneshot(request(
            "POST",
            &format!("/oagw/v1/upstreams/{id}/status"),
            Some(serde_json::json!({ "enabled": true })),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::OK);
    assert_eq!(body(response).await["enabled"], true);
    assert!(store.get_upstream(tenant, id).unwrap().enabled);

    // An unknown id is a 404.
    let response = router
        .clone()
        .oneshot(request(
            "POST",
            &format!("/oagw/v1/upstreams/{}/status", Uuid::new_v4()),
            Some(serde_json::json!({ "enabled": true })),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::NOT_FOUND);
}

#[tokio::test]
async fn listing_supports_the_odata_parameters() {
    let (router, _) = harness();
    let tenant = Uuid::new_v4();
    for host in ["a.openai.com", "b.openai.com", "c.openai.com"] {
        let response = router
            .clone()
            .oneshot(request(
                "POST",
                "/oagw/v1/upstreams",
                Some(hostname_upstream(host)),
                tenant,
            ))
            .await
            .unwrap();
        assert_eq!(response.status(), StatusCode::CREATED);
    }

    // `$top` above the documented maximum is a 400.
    let response = router
        .clone()
        .oneshot(request("GET", "/oagw/v1/upstreams?$top=101", None, tenant))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::BAD_REQUEST);

    // `$top` + `$skip` page through the list.
    let response = router
        .clone()
        .oneshot(request(
            "GET",
            "/oagw/v1/upstreams?$top=2&$skip=1",
            None,
            tenant,
        ))
        .await
        .unwrap();
    let page = body(response).await;
    assert_eq!(page.as_array().expect("array").len(), 2);

    // `$orderby` + `$filter` + `$select`.
    let response = router
        .clone()
        .oneshot(request(
            "GET",
            "/oagw/v1/upstreams?$orderby=alias%20desc&$filter=alias%20eq%20'a.openai.com'\
             &$select=id,alias",
            None,
            tenant,
        ))
        .await
        .unwrap();
    let page = body(response).await;
    let items = page.as_array().expect("array");
    assert_eq!(items.len(), 1);
    assert_eq!(items[0]["alias"], "a.openai.com");
    assert!(items[0].get("server").is_none(), "`$select` projects");
}

