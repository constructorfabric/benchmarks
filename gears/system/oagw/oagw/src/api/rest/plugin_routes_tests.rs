#![allow(clippy::unwrap_used, clippy::expect_used)]
//! `Router::oneshot` tests of the plugin management API.
//!
//! They exercise the HTTP surface of the phase's plugin framework: the
//! immutability of a definition (no `PUT`/`PATCH`), the `Problem` envelopes of
//! the rejections and the binding list a refused delete carries in its context.
//! Every request injects the caller's [`SecurityContext`] as an extension,
//! exactly as the gateway middleware does.

