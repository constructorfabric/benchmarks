#[tokio::test]
async fn a_bound_plugin_is_refused_with_409_and_the_binding_list() {
    let router = harness();
    let tenant = Uuid::new_v4();
    let created = create_plugin(&router, tenant, "redact_pii").await;
    let id: Uuid = created["id"].as_str().expect("id").parse().unwrap();

    // An upstream and a route of the same tenant still reference the plugin.
    let upstream = serde_json::json!({
        "server": { "endpoints": [{ "scheme": "https", "host": "api.openai.com", "port": 443 }] },
        "protocol": "gts.cf.core.oagw.protocol.v1~cf.core.oagw.http.v1",
        "plugins": { "items": [id.to_string()] },
    });
    let response = router
        .clone()
        .oneshot(request(
            "POST",
            "/oagw/v1/upstreams",
            Some(upstream),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::CREATED, "plugin bound");
    let upstream_id: Uuid = body(response).await["id"]
        .as_str()
        .expect("id")
        .parse()
        .unwrap();

    let response = router
        .clone()
        .oneshot(request(
            "DELETE",
            &format!("/oagw/v1/plugins/{id}"),
            None,
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::CONFLICT);
    let problem = body(response).await;
    assert!(
        problem["context"]["resource_type"]
            .as_str()
            .unwrap_or_default()
            .ends_with("cf.oagw.plugin.in_use.v1~"),
        "{problem}"
    );
    let violations = problem["context"]["violations"]
        .as_array()
        .cloned()
        .unwrap_or_default();
    assert_eq!(violations.len(), 1, "{problem}");
    assert_eq!(
        violations[0]["subject"],
        format!("upstream/{upstream_id}"),
        "{problem}"
    );
    assert_eq!(violations[0]["type"], "plugin_binding", "{problem}");
    assert!(
        violations[0]["description"]
            .as_str()
            .unwrap_or_default()
            .contains("plugins.items[0]"),
        "{problem}"
    );

    // The refused deletion leaves the definition in place.
    let response = router
        .oneshot(request(
            "GET",
            &format!("/oagw/v1/plugins/{id}"),
            None,
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::OK);
}

// ── Validation ────────────────────────────────────────────────────────────

#[tokio::test]
async fn an_invalid_payload_is_a_400_with_field_violations() {
    let router = harness();
    let tenant = Uuid::new_v4();

    let response = router
        .clone()
        .oneshot(request(
            "POST",
            "/oagw/v1/plugins",
            Some(serde_json::json!({})),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::BAD_REQUEST);
    let problem = body(response).await;
    assert!(
        problem["context"]["resource_type"]
            .as_str()
            .unwrap_or_default()
            .ends_with("cf.oagw.validation.error.v1~"),
        "{problem}"
    );
    let violations = problem["context"]["field_violations"]
        .as_array()
        .cloned()
        .unwrap_or_default();
    let fields: Vec<&str> = violations
        .iter()
        .filter_map(|violation| violation["field"].as_str())
        .collect();
    assert_eq!(fields, ["plugin_type", "name", "source_code"], "{problem}");

    // An unknown kind is rejected per field.
    let response = router
        .clone()
        .oneshot(request(
            "POST",
            "/oagw/v1/plugins",
            Some(serde_json::json!({
                "plugin_type": "middleware",
                "name": "redact_pii",
                "source_code": "def transform(ctx):\n    return None\n",
            })),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::BAD_REQUEST);
    let problem = body(response).await;
    let violations = problem["context"]["field_violations"]
        .as_array()
        .cloned()
        .unwrap_or_default();
    assert_eq!(violations[0]["field"], "plugin_type", "{problem}");
    assert_eq!(violations[0]["reason"], "INVALID_VALUE", "{problem}");
}

#[tokio::test]
async fn a_catalog_only_identifier_cannot_be_redefined() {
    let router = harness();
    let tenant = Uuid::new_v4();

    // `timeout`, `cors` and `logging` are catalog-only identifiers of core Data
    // Plane logic: a custom plugin may not shadow them.
    for name in ["timeout", "cors", "logging", "metrics", "noop"] {
        let response = router
            .clone()
            .oneshot(request(
                "POST",
                "/oagw/v1/plugins",
                Some(plugin_request(name)),
                tenant,
            ))
            .await
            .unwrap();
        assert_eq!(response.status(), StatusCode::BAD_REQUEST, "{name}");
        let problem = body(response).await;
        let violations = problem["context"]["field_violations"]
            .as_array()
            .cloned()
            .unwrap_or_default();
        assert_eq!(violations[0]["field"], "name", "{problem}");
        assert_eq!(violations[0]["reason"], "RESERVED_NAME", "{problem}");
    }

    // A duplicate name is refused as well.
    create_plugin(&router, tenant, "redact_pii").await;
    let response = router
        .oneshot(request(
            "POST",
            "/oagw/v1/plugins",
            Some(plugin_request("redact_pii")),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::BAD_REQUEST);
    let problem = body(response).await;
    let violations = problem["context"]["field_violations"]
        .as_array()
        .cloned()
        .unwrap_or_default();
    assert_eq!(violations[0]["reason"], "DUPLICATE", "{problem}");
}

