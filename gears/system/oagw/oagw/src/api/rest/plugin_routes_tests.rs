// ── Harness ───────────────────────────────────────────────────────────────

/// Builds the router with the management API and the plugin API over one store.
///
/// Both surfaces are mounted, exactly as the gear registers them, so a test can
/// bind a plugin to an upstream it creates through the same router.
fn harness() -> Router {
    let store = Arc::new(Store::new());
    let svc = Arc::new(Service::new(
        Arc::clone(&store),
        Arc::new(toolkit::ClientHub::new()),
    ));
    let state = Arc::new(PluginApiState {
        plugins: Arc::new(PluginCatalog::new()),
        registry: Arc::new(PluginRegistry::with_builtins(
            Arc::new(UnavailableSecretResolver),
            TokenCacheConfig::new(Duration::from_secs(300), 10_000),
        )),
        store,
    });
    let openapi = OpenApiRegistryImpl::new();
    let router = register_routes(Router::new(), &openapi, svc);
    register_plugin_routes(router, &openapi, state)
}

/// The security context of one tenant, as the gateway middleware would inject.
fn ctx(tenant: Uuid) -> SecurityContext {
    SecurityContext::builder()
        .subject_id(Uuid::now_v7())
        .subject_tenant_id(tenant)
        .build()
        .expect("valid security context")
}

/// Builds a JSON request with the `SecurityContext` injected as an extension.
fn request(method: &str, uri: &str, body: Option<Value>, tenant: Uuid) -> Request<Body> {
    let mut builder = Request::builder().method(method).uri(uri);
    if body.is_some() {
        builder = builder.header("content-type", "application/json");
    }
    let body = match body {
        Some(json) => Body::from(serde_json::to_vec(&json).unwrap()),
        None => Body::empty(),
    };
    let mut req = builder.body(body).unwrap();
    req.extensions_mut().insert(ctx(tenant));
    req
}

/// Deserializes a JSON response body, or `null` for an empty one.
async fn body(response: axum::response::Response) -> Value {
    let bytes = to_bytes(response.into_body(), 1024 * 256).await.unwrap();
    serde_json::from_slice(&bytes).unwrap_or(Value::Null)
}

/// A valid create payload for a transform plugin.
fn plugin_request(name: &str) -> Value {
    serde_json::json!({
        "plugin_type": "transform",
        "name": name,
        "config_schema": { "type": "object" },
        "source_code": "def transform(ctx):\n    return None\n",
    })
}

/// Creates one plugin and returns its stored representation.
async fn create_plugin(router: &Router, tenant: Uuid, name: &str) -> Value {
    let response = router
        .clone()
        .oneshot(request(
            "POST",
            "/oagw/v1/plugins",
            Some(plugin_request(name)),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::CREATED);
    body(response).await
}

// ── Create, read, list ────────────────────────────────────────────────────

#[tokio::test]
async fn create_plugin_returns_201_with_its_gts_identifier() {
    let router = harness();
    let tenant = Uuid::new_v4();

    let created = create_plugin(&router, tenant, "redact_pii").await;
    let id = created["id"].as_str().expect("id").parse::<Uuid>().unwrap();
    assert_ne!(id, Uuid::nil(), "the id is generated by the server");
    assert_eq!(created["name"], "redact_pii");
    assert_eq!(created["plugin_type"], "transform");
    assert_eq!(
        created["plugin_ref"],
        format!("gts.cf.core.oagw.transform_plugin.v1~{id}")
    );
    assert_eq!(
        created["source_code"],
        "def transform(ctx):\n    return None\n"
    );
    assert_eq!(created["config_schema"]["type"], "object");
}

#[tokio::test]
async fn a_plugin_is_readable_by_id_and_by_source_document() {
    let router = harness();
    let tenant = Uuid::new_v4();
    let created = create_plugin(&router, tenant, "redact_pii").await;
    let id = created["id"].as_str().expect("id").to_owned();

    let response = router
        .clone()
        .oneshot(request(
            "GET",
            &format!("/oagw/v1/plugins/{id}"),
            None,
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::OK);
    assert_eq!(body(response).await["plugin_ref"], created["plugin_ref"]);

    let response = router
        .clone()
        .oneshot(request(
            "GET",
            &format!("/oagw/v1/plugins/{id}/source"),
            None,
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::OK);
    let source = body(response).await;
    assert_eq!(source["id"], created["id"]);
    assert_eq!(
        source["source_code"],
        "def transform(ctx):\n    return None\n"
    );

    // An unknown id is a 404.
    let response = router
        .oneshot(request(
            "GET",
            &format!("/oagw/v1/plugins/{}/source", Uuid::new_v4()),
            None,
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::NOT_FOUND);
}

#[tokio::test]
async fn the_list_endpoint_supports_the_odata_parameters() {
    let router = harness();
    let tenant = Uuid::new_v4();
    create_plugin(&router, tenant, "redact_pii").await;
    let guard = serde_json::json!({
        "plugin_type": "guard",
        "name": "deny_paths",
        "source_code": "def guard_request(ctx):\n    return None\n",
    });
    let response = router
        .clone()
        .oneshot(request("POST", "/oagw/v1/plugins", Some(guard), tenant))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::CREATED);

    let response = router
        .clone()
        .oneshot(request("GET", "/oagw/v1/plugins", None, tenant))
        .await
        .unwrap();
    let items = body(response).await.as_array().cloned().unwrap_or_default();
    assert_eq!(items.len(), 2, "the catalog starts empty");

    let response = router
        .clone()
        .oneshot(request(
            "GET",
            "/oagw/v1/plugins?$filter=type%20eq%20'guard'",
            None,
            tenant,
        ))
        .await
        .unwrap();
    let items = body(response).await.as_array().cloned().unwrap_or_default();
    assert_eq!(items.len(), 1);
    assert_eq!(items[0]["name"], "deny_paths");

    let response = router
        .clone()
        .oneshot(request(
            "GET",
            "/oagw/v1/plugins?$orderby=name%20desc&$select=name",
            None,
            tenant,
        ))
        .await
        .unwrap();
    let items = body(response).await.as_array().cloned().unwrap_or_default();
    assert_eq!(items.len(), 2);
    assert_eq!(items[0]["name"], "redact_pii");
    assert!(items[0].get("source_code").is_none(), "`$select` projects");

    // A field the endpoint does not filter on is a 400.
    let response = router
        .oneshot(request(
            "GET",
            "/oagw/v1/plugins?$filter=id%20eq%20'x'",
            None,
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::BAD_REQUEST);
}

