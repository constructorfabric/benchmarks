// ── Immutability ──────────────────────────────────────────────────────────

#[tokio::test]
async fn a_definition_is_immutable_put_patch_and_post_to_id_answer_405() {
    let router = harness();
    let tenant = Uuid::new_v4();
    let created = create_plugin(&router, tenant, "redact_pii").await;
    let id = created["id"].as_str().expect("id").to_owned();

    for method in ["PUT", "PATCH"] {
        let response = router
            .clone()
            .oneshot(request(
                method,
                &format!("/oagw/v1/plugins/{id}"),
                Some(plugin_request("redact_pii")),
                tenant,
            ))
            .await
            .unwrap();
        assert_eq!(
            response.status(),
            StatusCode::METHOD_NOT_ALLOWED,
            "{method} /oagw/v1/plugins/{id}"
        );
    }

    // The collection has no replacement operation either.
    let response = router
        .oneshot(request(
            "PUT",
            "/oagw/v1/plugins",
            Some(plugin_request("x")),
            tenant,
        ))
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::METHOD_NOT_ALLOWED);
}

