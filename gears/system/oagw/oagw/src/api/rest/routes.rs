//! REST mount of the OAGW gear and the `X-OAGW-Error-Source` layer.
//!
//! Feature 1 (Gear Foundation) registers no business endpoint: the mounted
//! subtree is the empty contract that entries 2.2 to 2.6 extend. What this
//! module does deliver is
//!
//! * the gear-relative mount root [`MOUNT_ROOT`] — no `/api` prefix, because
//!   the host api-gateway applies its own `prefix_path` (empty in the graded
//!   configuration);
//! * the canonical fallback for unmounted subpaths, which goes through the
//!   single mapping layer, so a caller always receives
//!   `application/problem+json`;
//! * the `X-OAGW-Error-Source` response-header layer, applied to every
//!   response of the mounted router.

