/// Gear mount root, gear-relative (assumption 1: empty host `prefix_path`).
///
/// The paths the gear serves are exactly `/oagw/v1/...`; the gear registers no
/// `/api`-prefixed path.
pub const MOUNT_ROOT: &str = "/oagw/v1";

/// OpenAPI component name of the OAGW problem document schema.
pub(crate) const PROBLEM_SCHEMA_NAME: &str = "OagwProblem";

// @cpt-begin:cpt-cf-oagw-dod-error-source-header:p1:inst-full
/// Stamp `X-OAGW-Error-Source` on an outgoing response.
///
/// The header is written only when it is absent: a value already set by the
/// producing path keeps ownership of the classification, whether it is
/// `gateway`, `upstream` or a value an intermediary added.
///
/// # Errors
///
/// Never fails; an unrepresentable classification value leaves the response
/// unstamped rather than aborting the request.
#[must_use]
pub fn stamp_error_source(response: Response, source: &'static str) -> Response {
    // @cpt-begin:cpt-cf-oagw-flow-canonical-error-response:p1:inst-gf-err-08
    // @cpt-begin:cpt-cf-oagw-algo-error-source-header:p1:inst-gf-hdr-01
    // Inspect the outgoing response for an existing classification.
    if response.headers().contains_key(ERROR_SOURCE_HEADER) {
        // @cpt-begin:cpt-cf-oagw-algo-error-source-header:p1:inst-gf-hdr-02
        // @cpt-begin:cpt-cf-oagw-algo-error-source-header:p1:inst-gf-hdr-03
        // Already present: the producing path keeps ownership of the value.
        return response;
        // @cpt-end:cpt-cf-oagw-algo-error-source-header:p1:inst-gf-hdr-03
        // @cpt-end:cpt-cf-oagw-algo-error-source-header:p1:inst-gf-hdr-02
    }
    // @cpt-end:cpt-cf-oagw-algo-error-source-header:p1:inst-gf-hdr-01
    // @cpt-begin:cpt-cf-oagw-algo-error-source-header:p1:inst-gf-hdr-04
    if let Ok(value) = HeaderValue::from_str(source) {
        let mut stamped = response;
        stamped.headers_mut().insert(ERROR_SOURCE_HEADER, value);
        // @cpt-begin:cpt-cf-oagw-algo-error-source-header:p1:inst-gf-hdr-09
        return stamped;
        // @cpt-end:cpt-cf-oagw-algo-error-source-header:p1:inst-gf-hdr-09
    }
    response
    // @cpt-end:cpt-cf-oagw-algo-error-source-header:p1:inst-gf-hdr-04
    // @cpt-end:cpt-cf-oagw-flow-canonical-error-response:p1:inst-gf-err-08
}

