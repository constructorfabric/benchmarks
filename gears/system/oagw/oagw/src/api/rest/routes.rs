//! REST route registration of the management API.
//!
//! Twelve gear-relative operations under `/oagw/v1/...` (six for upstreams,
//! six for routes), each documented under the `oagw` OpenAPI tag through
//! [`OperationBuilder`] and layered with the shared `Extension(Arc<Service>)`.
//!
//! Paths are **gear-relative**: the first segment is the gear name and there is
//! no `/api` prefix — the gateway mounts the gear's router itself.

use std::sync::Arc;

use axum::Router;
use axum::http::StatusCode;
use toolkit::api::{OpenApiRegistry, OperationBuilder};

use super::dto::{
    RouteDto, RouteRequestDto, RouteStatusRequestDto, UpstreamDto, UpstreamRequestDto,
    UpstreamStatusRequestDto,
};
use super::handlers;
use crate::domain::service::Service;

/// The single OpenAPI tag of every OAGW management operation.
const TAG: &str = "oagw";

/// Registers every management route of the gear onto `router`, layered with the
/// shared [`Service`] extension.
pub fn register_routes(router: Router, openapi: &dyn OpenApiRegistry, svc: Arc<Service>) -> Router {
    let router = OperationBuilder::post("/oagw/v1/upstreams")
        .operation_id("oagw.create_upstream")
        .summary("Create an upstream")
        .description(
            "Create an upstream owned by the calling tenant. The id is generated by the \
             server; the alias is derived from the endpoint hostnames unless one is provided \
             explicitly.",
        )
        .tag(TAG)
        .authenticated()
        .no_license_required()
        .json_request::<UpstreamRequestDto>(openapi, "Upstream definition")
        .handler(handlers::create_upstream)
        .json_response_with_schema::<UpstreamDto>(openapi, StatusCode::CREATED, "Upstream created")
        .standard_errors(openapi)
        .error_409(openapi)
        .register(router, openapi);

    let router = OperationBuilder::get("/oagw/v1/upstreams")
        .operation_id("oagw.list_upstreams")
        .summary("List upstreams")
        .description("List the upstreams of the calling tenant with `OData` parameters.")
        .tag(TAG)
        .authenticated()
        .no_license_required()
        .query_param(
            "$filter",
            false,
            "Filter expression: a single `<field> eq|ne 'value'` comparison",
        )
        .query_param("$select", false, "Comma-separated fields to project")
        .query_param("$orderby", false, "Sort expression: `<field> [asc|desc]`")
        .query_param("$top", false, "Page size, 50 by default, at most 100")
        .query_param("$skip", false, "Number of leading items to skip")
        .handler(handlers::list_upstreams)
        .json_array_response_with_schema::<UpstreamDto>(openapi, StatusCode::OK, "Upstream page")
        .standard_errors(openapi)
        .register(router, openapi);

    let router = OperationBuilder::get("/oagw/v1/upstreams/{id}")
        .operation_id("oagw.get_upstream")
        .summary("Get an upstream")
        .description("Retrieve one upstream of the calling tenant by id.")
        .tag(TAG)
        .authenticated()
        .no_license_required()
        .path_param("id", "Upstream UUID")
        .handler(handlers::get_upstream)
        .json_response_with_schema::<UpstreamDto>(openapi, StatusCode::OK, "Upstream found")
        .standard_errors(openapi)
        .error_404(openapi)
        .register(router, openapi);

    let router = OperationBuilder::put("/oagw/v1/upstreams/{id}")
        .operation_id("oagw.replace_upstream")
        .summary("Replace an upstream")
        .description(
            "Full replacement of an upstream. The id and the alias are immutable: a payload \
             that would change the alias is rejected with 400, and the upstream has to be \
             deleted and re-created instead.",
        )
        .tag(TAG)
        .authenticated()
        .no_license_required()
        .path_param("id", "Upstream UUID")
        .json_request::<UpstreamRequestDto>(openapi, "Replacement upstream definition")
        .handler(handlers::replace_upstream)
        .json_response_with_schema::<UpstreamDto>(openapi, StatusCode::OK, "Upstream replaced")
        .standard_errors(openapi)
        .error_404(openapi)
        .error_409(openapi)
        .register(router, openapi);

    let router = OperationBuilder::delete("/oagw/v1/upstreams/{id}")
        .operation_id("oagw.delete_upstream")
        .summary("Delete an upstream")
        .description("Delete an upstream of the calling tenant together with its routes.")
        .tag(TAG)
        .authenticated()
        .no_license_required()
        .path_param("id", "Upstream UUID")
        .handler(handlers::delete_upstream)
        .no_content_response(StatusCode::NO_CONTENT, "Upstream deleted")
        .standard_errors(openapi)
        .error_404(openapi)
        .register(router, openapi);

    let router = OperationBuilder::post("/oagw/v1/upstreams/{id}/status")
        .operation_id("oagw.set_upstream_status")
        .summary("Enable or disable an upstream")
        .description(
            "Switch an upstream between accepting (`true`) and refusing (`false`) proxy \
             traffic; a disabled upstream makes the proxy path answer 503.",
        )
        .tag(TAG)
        .authenticated()
        .no_license_required()
        .path_param("id", "Upstream UUID")
        .json_request::<UpstreamStatusRequestDto>(openapi, "Requested enablement state")
        .handler(handlers::set_upstream_status)
        .json_response_with_schema::<UpstreamDto>(openapi, StatusCode::OK, "Upstream updated")
        .standard_errors(openapi)
        .error_404(openapi)
        .register(router, openapi);

    let router = OperationBuilder::post("/oagw/v1/routes")
        .operation_id("oagw.create_route")
        .summary("Create a route")
        .description(
            "Create a route of the calling tenant. `upstream_id` must name an upstream of the \
             same tenant and the match rule must be unique within that upstream.",
        )
        .tag(TAG)
        .authenticated()
        .no_license_required()
        .json_request::<RouteRequestDto>(openapi, "Route definition")
        .handler(handlers::create_route)
        .json_response_with_schema::<RouteDto>(openapi, StatusCode::CREATED, "Route created")
        .standard_errors(openapi)
        .error_404(openapi)
        .error_409(openapi)
        .register(router, openapi);

    let router = OperationBuilder::get("/oagw/v1/routes")
        .operation_id("oagw.list_routes")
        .summary("List routes")
        .description("List the routes of the calling tenant with `OData` parameters.")
        .tag(TAG)
        .authenticated()
        .no_license_required()
        .query_param(
            "$filter",
            false,
            "Filter expression: a single `<field> eq|ne 'value'` comparison",
        )
        .query_param("$select", false, "Comma-separated fields to project")
        .query_param("$orderby", false, "Sort expression: `<field> [asc|desc]`")
        .query_param("$top", false, "Page size, 50 by default, at most 100")
        .query_param("$skip", false, "Number of leading items to skip")
        .handler(handlers::list_routes)
        .json_array_response_with_schema::<RouteDto>(openapi, StatusCode::OK, "Route page")
        .standard_errors(openapi)
        .register(router, openapi);

    let router = OperationBuilder::get("/oagw/v1/routes/{id}")
        .operation_id("oagw.get_route")
        .summary("Get a route")
        .description("Retrieve one route of the calling tenant by id.")
        .tag(TAG)
        .authenticated()
        .no_license_required()
        .path_param("id", "Route UUID")
        .handler(handlers::get_route)
        .json_response_with_schema::<RouteDto>(openapi, StatusCode::OK, "Route found")
        .standard_errors(openapi)
        .error_404(openapi)
        .register(router, openapi);

    let router = OperationBuilder::put("/oagw/v1/routes/{id}")
        .operation_id("oagw.replace_route")
        .summary("Replace a route")
        .description(
            "Full replacement of a route. `upstream_id` is immutable: a payload naming a \
             different upstream is rejected with 400 — move traffic by creating a new route \
             instead.",
        )
        .tag(TAG)
        .authenticated()
        .no_license_required()
        .path_param("id", "Route UUID")
        .json_request::<RouteRequestDto>(openapi, "Replacement route definition")
        .handler(handlers::replace_route)
        .json_response_with_schema::<RouteDto>(openapi, StatusCode::OK, "Route replaced")
        .standard_errors(openapi)
        .error_404(openapi)
        .error_409(openapi)
        .register(router, openapi);

    let router = OperationBuilder::delete("/oagw/v1/routes/{id}")
        .operation_id("oagw.delete_route")
        .summary("Delete a route")
        .description("Delete a route of the calling tenant.")
        .tag(TAG)
        .authenticated()
        .no_license_required()
        .path_param("id", "Route UUID")
        .handler(handlers::delete_route)
        .no_content_response(StatusCode::NO_CONTENT, "Route deleted")
        .standard_errors(openapi)
        .error_404(openapi)
        .register(router, openapi);

    let router = OperationBuilder::post("/oagw/v1/routes/{id}/status")
        .operation_id("oagw.set_route_status")
        .summary("Enable or disable a route")
        .description(
            "Switch a route between participating in (`true`) and being excluded from (`false`) \
             proxy matching.",
        )
        .tag(TAG)
        .authenticated()
        .no_license_required()
        .path_param("id", "Route UUID")
        .json_request::<RouteStatusRequestDto>(openapi, "Requested enablement state")
        .handler(handlers::set_route_status)
        .json_response_with_schema::<RouteDto>(openapi, StatusCode::OK, "Route updated")
        .standard_errors(openapi)
        .error_404(openapi)
        .register(router, openapi);

    router.layer(axum::Extension(svc))
}

