    async fn mounted_router_serves_the_canonical_fallback() {
        let router = register_routes(
            Router::new(),
            &RecordingRegistry::default(),
            Arc::new(crate::infra::storage::OagwStore::new()),
            Arc::new(crate::domain::sharing::FlatHierarchy),
        );
        let response = router
            .oneshot(
                axum::http::Request::builder()
                    .uri("/oagw/v1/does-not-exist")
                    .body(Body::empty())
                    .expect("request builds"),
            )
            .await
            .expect("request serves");

        assert_eq!(response.status(), StatusCode::NOT_FOUND);
        assert_eq!(header_of(&response).as_deref(), Some(ERROR_SOURCE_GATEWAY));
        assert_eq!(
            response
                .headers()
                .get(header::CONTENT_TYPE)
                .and_then(|value| value.to_str().ok()),
            Some("application/problem+json")
        );

        let bytes = Body::new(response)
            .collect()
            .await
            .expect("body collects")
            .to_bytes();
        let document: serde_json::Value =
            serde_json::from_slice(&bytes).expect("body is a problem document");
        assert_eq!(
            document["type"],
            serde_json::json!("gts://gts.cf.core.errors.err.v1~cf.oagw.route.not_found.v1")
        );
        assert_eq!(
            document["instance"],
            serde_json::json!("/oagw/v1/does-not-exist"),
            "the nested fallback reports the full request path"
        );
        assert_eq!(document["path"], serde_json::json!("/oagw/v1/does-not-exist"));
    }

    #[tokio::test]
    async fn no_path_is_served_under_an_api_prefix() {
        let router = register_routes(
            Router::new(),
            &RecordingRegistry::default(),
            Arc::new(crate::infra::storage::OagwStore::new()),
            Arc::new(crate::domain::sharing::FlatHierarchy),
        );
        let response = router
            .oneshot(
                axum::http::Request::builder()
                    .uri("/api/oagw/v1/does-not-exist")
                    .body(Body::empty())
                    .expect("request builds"),
            )
            .await
            .expect("request serves");

        assert_eq!(response.status(), StatusCode::NOT_FOUND);
        // No header and no gear-generated body: the response did not come from
        // the gear, proving the gear registered no `/api`-prefixed path.
        assert!(response.headers().get(ERROR_SOURCE_HEADER).is_none());
        let bytes = Body::new(response)
            .collect()
            .await
            .expect("body collects")
            .to_bytes();
        assert!(bytes.is_empty(), "the host's plain 404 has no problem body");
    }

