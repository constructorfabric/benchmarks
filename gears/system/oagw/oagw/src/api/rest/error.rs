//! REST error rendering: RFC 9457 `application/problem+json`.
//!
//! Every gateway-originated error carries the GTS `type` identifier from
//! the DESIGN §3.3 error table plus the `X-OAGW-Error-Source: gateway`
//! header (ADR 0007). Retriable errors also set `Retry-After`. Upstream
//! passthrough responses are marked `X-OAGW-Error-Source: upstream` in the
//! data plane itself (no body modification).

use axum::body::Body;
use axum::http::header::{CONTENT_TYPE, RETRY_AFTER};
use axum::http::{HeaderMap, HeaderValue, StatusCode};
use axum::response::{IntoResponse, Response};
use serde_json::{Map, Value};

use crate::domain::error::{DomainError, ProblemSpec};

/// Header carrying the error-source distinction (ADR 0007).
pub const ERROR_SOURCE_HEADER: &str = "x-oagw-error-source";

/// Where an error originated (ADR 0007).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ErrorSource {
    /// Generated by OAGW itself (always `application/problem+json`).
    Gateway,
    /// Passed through from the upstream service (body untouched).
    Upstream,
}

impl ErrorSource {
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Gateway => "gateway",
            Self::Upstream => "upstream",
        }
    }
}

/// A gateway problem rendered to a wire response.
#[derive(Debug, Clone)]
pub struct OagwError {
    /// RFC 9457 problem payload.
    pub problem: ProblemSpec,
    /// Error-source header value.
    pub source: ErrorSource,
}

impl OagwError {
    /// Build a gateway-originated problem.
    #[must_use]
    pub fn gateway(problem: ProblemSpec) -> Self {
        Self {
            problem,
            source: ErrorSource::Gateway,
        }
    }

    /// Validation shortcut producing a `400 Validation Error`.
    #[must_use]
    pub fn validation(message: impl Into<String>) -> Self {
        Self::gateway(ProblemSpec {
            gts_type: crate::domain::gts::ERR_VALIDATION,
            status: 400,
            title: "Validation Error",
            detail: message.into(),
            context: Vec::new(),
            retry_after_seconds: None,
        })
    }
}

impl From<DomainError> for OagwError {
    fn from(e: DomainError) -> Self {
        Self::gateway(e.to_problem())
    }
}

impl From<ProblemSpec> for OagwError {
    fn from(problem: ProblemSpec) -> Self {
        Self::gateway(problem)
    }
}

impl IntoResponse for OagwError {
    fn into_response(self) -> Response {
        let problem = self.problem;

        let mut body = Map::new();
        body.insert("type".to_owned(), Value::String(problem.gts_type.to_owned()));
        body.insert("title".to_owned(), Value::String(problem.title.to_owned()));
        body.insert(
            "status".to_owned(),
            Value::Number(serde_json::Number::from(problem.status)),
        );
        body.insert("detail".to_owned(), Value::String(problem.detail.clone()));
        if let Some(secs) = problem.retry_after_seconds {
            body.insert(
                "retry_after_seconds".to_owned(),
                Value::Number(serde_json::Number::from(secs)),
            );
        }
        // Context extension fields (RFC 9457 allows arbitrary members).
        for (key, value) in &problem.context {
            body.insert(key.clone(), Value::String(value.clone()));
        }

        let status = StatusCode::from_u16(problem.status)
            .unwrap_or(StatusCode::INTERNAL_SERVER_ERROR);

        let mut headers = HeaderMap::new();
        headers.insert(
            ERROR_SOURCE_HEADER,
            HeaderValue::from_static(self.source.as_str()),
        );
        headers.insert(CONTENT_TYPE, HeaderValue::from_static("application/problem+json"));
        if let Some(secs) = problem.retry_after_seconds {
            if let Ok(v) = HeaderValue::from_str(&secs.to_string()) {
                headers.insert(RETRY_AFTER, v);
            }
        }

        let bytes = serde_json::to_vec(&Value::Object(body))
            .unwrap_or_else(|_| b"{}".to_vec());
        let mut response = Response::builder()
            .status(status)
            .body(Body::from(bytes))
            .expect("problem response build");
        response.headers_mut().extend(headers);
        response
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use futures_util::FutureExt;
    use crate::domain::gts;

    fn spec() -> ProblemSpec {
        ProblemSpec {
            gts_type: gts::ERR_RATE_LIMIT_EXCEEDED,
            status: 429,
            title: "Rate Limit Exceeded",
            detail: "rate limited".to_owned(),
            context: vec![("alias".to_owned(), "api.example.com".to_owned())],
            retry_after_seconds: Some(5),
        }
    }

    #[test]
    fn renders_rfc9457_problem_with_gts_type_and_headers() {
        let response = OagwError::gateway(spec()).into_response();
        assert_eq!(response.status(), StatusCode::TOO_MANY_REQUESTS);
        assert_eq!(
            response.headers().get(ERROR_SOURCE_HEADER).unwrap(),
            "gateway"
        );
        assert_eq!(
            response.headers().get(CONTENT_TYPE).unwrap(),
            "application/problem+json"
        );
        assert_eq!(response.headers().get(RETRY_AFTER).unwrap(), "5");

        let bytes = axum::body::to_bytes(response.into_body(), 4096)
            .now_or_never()
            .expect("static body")
            .expect("read body");
        let json: Value = serde_json::from_slice(&bytes).unwrap();
        assert_eq!(
            json["type"],
            gts::ERR_RATE_LIMIT_EXCEEDED
        );
        assert_eq!(json["status"], 429);
        assert_eq!(json["detail"], "rate limited");
        assert_eq!(json["alias"], "api.example.com");
        assert_eq!(json["retry_after_seconds"], 5);
    }

    #[test]
    fn domain_error_maps_through_from() {
        let err = DomainError::validation("nope");
        let response = OagwError::from(err).into_response();
        assert_eq!(response.status(), StatusCode::BAD_REQUEST);
        assert_eq!(
            response.headers().get(ERROR_SOURCE_HEADER).unwrap(),
            "gateway"
        );
    }
}
