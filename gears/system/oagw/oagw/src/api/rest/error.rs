    #[test]
    fn document_never_contains_credential_material() {
        // `cpt-cf-oagw-principle-cred-isolation`: only the routing facts of the
        // request context and the error table fields are serialized. A secret
        // reference is never echoed, and the document has no free-form field a
        // credential could land in.
        let document = OagwProblem::new(
            &DomainError::SecretNotFound {
                detail: "secret_ref not found".to_owned(),
            },
            &ErrorContext::for_request("/oagw/v1/pay").with_host("payments.internal:8443"),
        );
        let json = document.into_json();
        let rendered = json.to_string().to_lowercase();
        for banned in ["password", "client_secret", "bearer ", "authorization"] {
            assert!(!rendered.contains(banned), "{banned} leaked: {json}");
        }
        assert_eq!(
            json.as_object().map(|object| object.len()),
            Some(8), // type, title, status, detail, instance, context, host, path
            "{json}"
        );
    }

