//! The single mapping layer: domain error → canonical `application/problem+json`
//! response.
//!
//! This module is the only place where a [`DomainError`] becomes an HTTP body,
//! so entries 2.2 to 2.6 return errors through it instead of re-implementing
//! the error table. The document is built on the platform canonical envelope
//! ([`Problem`] from `toolkit-canonical-errors`) and carries:
//!
//! * the standard RFC 9457 fields `type`, `title`, `status`, `detail`,
//!   `instance` — `type` is the GTS identifier resolved from the error table;
//! * the OAGW extension fields `upstream_id`, `host`, `path` and
//!   `retry_after_seconds` as top-level extension members, emitted only when
//!   the request context provides them;
//! * `trace_id` on the canonical envelope's own top-level member.
//!
//! The document never contains credential material or a resolved secret value
//! (`cpt-cf-oagw-principle-cred-isolation`): only the fields below are ever
//! serialized.

use axum::http::{HeaderValue, StatusCode, header};
use axum::response::{IntoResponse, Response};
use serde_json::{Map, Value};
use toolkit_canonical_errors::problem::APPLICATION_PROBLEM_JSON;
use toolkit_canonical_errors::{Problem, ProblemCategory};
use toolkit_gts::gts_uri;

use crate::api::rest::dto::{
    ErrorContext, EXTENSION_ALIAS, EXTENSION_HOST, EXTENSION_INVALID_VALUE, EXTENSION_PATH,
    EXTENSION_RETRY_AFTER_SECONDS, EXTENSION_UPSTREAM_ID, EXTENSION_VALID_HOSTS,
};
use crate::domain::error::{DomainError, ManagementError};

/// Response header distinguishing gateway-originated from upstream responses.
pub const ERROR_SOURCE_HEADER: &str = "X-OAGW-Error-Source";

/// [`ERROR_SOURCE_HEADER`] value for a response generated by gear code.
pub const ERROR_SOURCE_GATEWAY: &str = "gateway";

/// [`ERROR_SOURCE_HEADER`] value for a response passed through from the
/// upstream (classified by entry 2.4, which owns the proxy path).
pub const ERROR_SOURCE_UPSTREAM: &str = "upstream";

/// Canonical problem document of the OAGW gear.
///
/// Wraps the platform canonical [`Problem`] envelope and adds the OAGW
/// extension members on the wire. Construct it from a [`DomainError`] and the
/// request context; the mapping is total, so no gear-originated failure can
/// leave the transport in a non-problem body format.
#[derive(Debug, Clone)]
pub struct OagwProblem {
    /// Canonical RFC 9457 envelope.
    problem: Problem,
    /// OAGW extension members, in the order the interface contract fixes.
    extensions: Map<String, Value>,
}

impl OagwProblem {
    /// Map a domain error onto the canonical problem document.
    ///
    /// The GTS `type` identifier and the HTTP status come from the error
    /// table, the standard fields come from the error, and the extension
    /// fields come from the request context (omitted when absent).
    #[must_use]
    pub fn new(error: &DomainError, context: &ErrorContext) -> Self {
        Self::project(error, context)
    }

    /// Map a management error onto the canonical problem document.
    ///
    /// Entry 2.2 raises [`ManagementError`], which is either a row of the fixed
    /// table or one of the management-only rejections with its own GTS `type`
    /// identifier. Both project through the same envelope, so a management
    /// failure can never leave the transport in another body format
    /// (`cpt-cf-oagw-dod-error-contract`).
    #[must_use]
    pub fn new_management(error: &ManagementError, context: &ErrorContext) -> Self {
        Self::project(error, context)
    }

    /// The projection shared by both error kinds.
    fn project(error: &impl ErrorTableRow, context: &ErrorContext) -> Self {
        // @cpt-begin:cpt-cf-oagw-flow-canonical-error-response:p1:inst-gf-err-04
        // GTS `type` identifier of the error table row, as a URI reference.
        let problem_type: String = gts_uri!(error.gts_id());

        // @cpt-begin:cpt-cf-oagw-algo-error-mapping:p1:inst-gf-map-02
        // Standard RFC 9457 fields: `type` carries the GTS identifier, `title`
        // the human-readable summary, `status` the HTTP status code, `detail`
        // the occurrence-specific explanation and `instance` the request path.
        let problem = Problem {
            problem_type,
            title: error.title().to_owned(),
            status: error.status(),
            detail: error.detail().to_owned(),
            instance: context.instance.clone(),
            trace_id: context.trace_id.clone(),
            context: Value::Object(Map::new()),
            error_code: None,
            error_domain: None,
        };
        // @cpt-end:cpt-cf-oagw-algo-error-mapping:p1:inst-gf-map-02

        // @cpt-begin:cpt-cf-oagw-algo-error-mapping:p1:inst-gf-map-03
        // @cpt-begin:cpt-cf-oagw-algo-error-mapping:p1:inst-gf-map-06
        // Only the fixed OAGW extension keys are ever emitted, and only from
        // the request context and the error's own retriability: no credential
        // material and no resolved secret value can reach the document, per
        // `cpt-cf-oagw-principle-cred-isolation`. The mapping layer holds no
        // reference to the credential store, so there is no path that copies
        // one in.
        // @cpt-begin:cpt-cf-oagw-algo-error-mapping:p1:inst-gf-map-04
        // OAGW extension fields: attach what the request context provides and
        // omit the rest. `retry_after_seconds` comes from the error, not from
        // the request.
        let mut extensions = Map::new();
        if let Some(upstream_id) = &context.upstream_id {
            extensions.insert(
                EXTENSION_UPSTREAM_ID.to_owned(),
                Value::String(upstream_id.clone()),
            );
        }
        if let Some(host) = &context.host {
            extensions.insert(EXTENSION_HOST.to_owned(), Value::String(host.clone()));
        }
        if let Some(path) = &context.path {
            extensions.insert(EXTENSION_PATH.to_owned(), Value::String(path.clone()));
        }
        if let Some(seconds) = error.retry_after_seconds() {
            extensions.insert(
                EXTENSION_RETRY_AFTER_SECONDS.to_owned(),
                Value::from(i64::from(seconds)),
            );
        }
        // The members an error row carries of its own. Only the `PluginInUse`
        // conflict has any (`cpt-cf-oagw-dod-plugin-in-use-conflict`): it names
        // the referenced definition and every referencing resource, which is
        // where the definition is used and nothing else.
        for (key, value) in error.extension_members() {
            extensions.insert(key, value);
        }
        // The ADR 0007 members of the three target-host errors: `alias`,
        // `valid_hosts` and `invalid_value`. They are emitted only for those
        // rows, so the request context cannot grow the document of another
        // error, and they carry routing facts only.
        if error.is_target_host_error() {
            if let Some(alias) = &context.alias {
                extensions.insert(EXTENSION_ALIAS.to_owned(), Value::String(alias.clone()));
            }
            if let Some(hosts) = &context.valid_hosts {
                extensions.insert(
                    EXTENSION_VALID_HOSTS.to_owned(),
                    Value::Array(hosts.iter().map(|host| Value::String(host.clone())).collect()),
                );
            }
            if let Some(value) = &context.invalid_value {
                extensions.insert(
                    EXTENSION_INVALID_VALUE.to_owned(),
                    Value::String(value.clone()),
                );
            }
        }
        // @cpt-end:cpt-cf-oagw-algo-error-mapping:p1:inst-gf-map-04
        // @cpt-end:cpt-cf-oagw-algo-error-mapping:p1:inst-gf-map-06
        // @cpt-end:cpt-cf-oagw-algo-error-mapping:p1:inst-gf-map-03

        Self {
            problem,
            extensions,
        }
        // @cpt-end:cpt-cf-oagw-flow-canonical-error-response:p1:inst-gf-err-04
    }

    /// HTTP status of the response.
    #[must_use]
    pub const fn status(&self) -> u16 {
        self.problem.status
    }

    /// Name `code` as the machine-readable error code of the document.
    ///
    /// The error table fixes every row's identity, so this carries only the
    /// code a stage records beside its row — REQUIRED_HEADER_MISSING of the
    /// RequiredHeaders guard — and never a second error identity.
    #[must_use]
    pub fn with_error_code(mut self, code: &str) -> Self {
        self.problem.error_code = Some(code.to_owned());
        self
    }

    /// Override the status code of the document.
    ///
    /// The error table fixes every status, so this is only used for the
    /// transport-level rejections of entry 2.2 — a body that never reached the
    /// domain, whose status the HTTP extractor decides (`400` for a malformed
    /// document, `415` for a wrong content type).
    #[must_use]
    pub const fn with_status(mut self, status: u16) -> Self {
        self.problem.status = status;
        self
    }

    /// GTS `type` identifier, in URI form.
    #[must_use]
    pub fn problem_type(&self) -> &str {
        &self.problem.problem_type
    }

    /// Human-readable summary (`title`).
    #[must_use]
    pub fn title(&self) -> &str {
        &self.problem.title
    }

    /// Occurrence-specific explanation (`detail`).
    #[must_use]
    pub fn detail(&self) -> &str {
        &self.problem.detail
    }

    /// URI reference identifying the occurrence (`instance`).
    #[must_use]
    pub fn instance(&self) -> Option<&str> {
        self.problem.instance.as_deref()
    }

    /// Distributed-tracing correlation identifier.
    #[must_use]
    pub fn trace_id(&self) -> Option<&str> {
        self.problem.trace_id.as_deref()
    }

    /// The OAGW extension members the request context provided.
    #[must_use]
    pub fn extensions(&self) -> &Map<String, Value> {
        &self.extensions
    }

    /// Serialize the document, injecting the OAGW extension members.
    ///
    /// The standard fields are exactly the canonical envelope's; the extension
    /// members are added at the top level per RFC 9457's extension rule.
    #[must_use]
    pub fn into_json(self) -> Value {
        let mut object: Map<String, Value> = serde_json::to_value(&self.problem)
            .ok()
            .and_then(|value| value.as_object().cloned())
            .unwrap_or_default();
        for (key, value) in self.extensions {
            object.insert(key, value);
        }
        Value::Object(object)
    }
}

/// The error-table projection the mapping layer reads.
///
/// Both error kinds of entry 2.2 — the fixed table and the management-only
/// rejections — expose exactly these members, so one private projection renders
/// either of them and the mapping stays a single place on the wire.
trait ErrorTableRow {
    /// HTTP status code of the table row.
    fn status(&self) -> u16;
    /// GTS Instance ID of the error type.
    fn gts_id(&self) -> &'static str;
    /// Human-readable summary used as the problem `title`.
    fn title(&self) -> &str;
    /// Occurrence-specific explanation used as the problem `detail`.
    fn detail(&self) -> &str;
    /// Retry guidance in seconds, when the row records it.
    fn retry_after_seconds(&self) -> Option<u32>;
    /// Whether the row is one of the three ADR 0007 target-host errors, whose
    /// document carries the `alias`, `valid_hosts` and `invalid_value`
    /// members.
    fn is_target_host_error(&self) -> bool {
        false
    }
    /// Extension members the row carries of its own, beyond the request
    /// context. Defaulted so only a row that owns extension members overrides
    /// it.
    fn extension_members(&self) -> Vec<(String, Value)> {
        Vec::new()
    }
}

impl ErrorTableRow for DomainError {
    fn status(&self) -> u16 {
        DomainError::status(self)
    }

    fn gts_id(&self) -> &'static str {
        DomainError::gts_id(self)
    }

    fn title(&self) -> &str {
        DomainError::title(self)
    }

    fn detail(&self) -> &str {
        DomainError::detail(self)
    }

    fn retry_after_seconds(&self) -> Option<u32> {
        DomainError::retry_after_seconds(self)
    }

    fn is_target_host_error(&self) -> bool {
        matches!(
            self,
            DomainError::MissingTargetHost { .. }
                | DomainError::InvalidTargetHost { .. }
                | DomainError::UnknownTargetHost { .. }
        )
    }
}

impl ErrorTableRow for ManagementError {
    fn status(&self) -> u16 {
        ManagementError::status(self)
    }

    fn gts_id(&self) -> &'static str {
        ManagementError::gts_id(self)
    }

    fn title(&self) -> &str {
        ManagementError::title(self)
    }

    fn detail(&self) -> &str {
        ManagementError::detail(self)
    }

    fn retry_after_seconds(&self) -> Option<u32> {
        ManagementError::retry_after_seconds(self)
    }

    fn extension_members(&self) -> Vec<(String, Value)> {
        ManagementError::extension_members(self)
    }
}

/// Canonical category with the same HTTP status as the error, when one exists.
///
/// The OAGW table is not a subset of the canonical taxonomy (no canonical
/// category carries 413 or 502), so the projection is partial. It is used to
/// keep the OAGW mapping class-consistent with the platform error taxonomy.
#[must_use]
pub fn canonical_category(error: &DomainError) -> Option<ProblemCategory> {
    match error.status() {
        400 => Some(ProblemCategory::InvalidArgument),
        401 => Some(ProblemCategory::Unauthenticated),
        404 => Some(ProblemCategory::NotFound),
        409 => Some(ProblemCategory::AlreadyExists),
        429 => Some(ProblemCategory::ResourceExhausted),
        500 => Some(ProblemCategory::Internal),
        503 => Some(ProblemCategory::ServiceUnavailable),
        504 => Some(ProblemCategory::DeadlineExceeded),
        // 413 (payload too large) and 502 (downstream/protocol/stream) have no
        // canonical AIP-193 category; the OAGW GTS type stays authoritative.
        _ => None,
    }
}

/// Map a domain error onto the canonical error response for the header layer
/// to stamp.
///
/// Handlers with request context call this; handlers without context can use
/// `?` on a [`DomainError`] (the [`IntoResponse`] impl below).
#[must_use]
pub fn error_response(error: &DomainError, context: &ErrorContext) -> Response {
    // @cpt-begin:cpt-cf-oagw-flow-canonical-error-response:p1:inst-gf-err-02
    // The outcome of gear code: a domain error raised inside the gear, mapped
    // here. An upstream response is not mapped (it is passed through and
    // classified by `classify_upstream` in the routes module).
    OagwProblem::new(error, context).into_response()
    // @cpt-end:cpt-cf-oagw-flow-canonical-error-response:p1:inst-gf-err-02
}

impl IntoResponse for OagwProblem {
    fn into_response(self) -> Response {
        let status = StatusCode::from_u16(self.problem.status)
            .unwrap_or(StatusCode::INTERNAL_SERVER_ERROR);
        let retry_after = self
            .extensions
            .get(EXTENSION_RETRY_AFTER_SECONDS)
            .and_then(Value::as_u64);
        // @cpt-begin:cpt-cf-oagw-algo-error-mapping:p1:inst-gf-map-05
        let body = self.into_json().to_string();

        let mut response = (
            status,
            [(
                header::CONTENT_TYPE,
                HeaderValue::from_static(APPLICATION_PROBLEM_JSON),
            )],
            body,
        )
            .into_response();
        // @cpt-end:cpt-cf-oagw-algo-error-mapping:p1:inst-gf-map-05

        if let Some(seconds) = retry_after {
            let value = HeaderValue::from(seconds);
            response.headers_mut().insert(header::RETRY_AFTER, value);
        }

        // Classify the response as gateway-originated: every response this
        // mapping layer produces is gear code, never an upstream passthrough.
        if let Ok(value) = HeaderValue::from_str(ERROR_SOURCE_GATEWAY) {
            response.headers_mut().insert(ERROR_SOURCE_HEADER, value);
        }

        // @cpt-begin:cpt-cf-oagw-algo-error-mapping:p1:inst-gf-map-07
        response
        // @cpt-end:cpt-cf-oagw-algo-error-mapping:p1:inst-gf-map-07
    }
}

impl IntoResponse for DomainError {
    fn into_response(self) -> Response {
        // Handlers that cannot supply request context still get a canonical
        // problem document, with every extension field omitted.
        OagwProblem::new(&self, &ErrorContext::default()).into_response()
    }
}

// @cpt-begin:cpt-cf-oagw-dod-error-contract:p1:inst-full
impl IntoResponse for ManagementError {
    fn into_response(self) -> Response {
        // The management handlers map their failures through the same
        // single mapping layer: the body format, the GTS `type` identifier and
        // the `gateway` classification are identical for a table row and for a
        // management-only rejection.
        OagwProblem::new_management(&self, &ErrorContext::default()).into_response()
    }
}
