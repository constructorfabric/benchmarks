/// `DELETE /oagw/v1/plugins/{id}` — deletes a plugin.
///
/// A plugin still referenced by an upstream or a route of the caller tenant is
/// not deleted: the request is answered with a `409` problem whose
/// `plugin_id` and `referenced_by` members identify the references.
///
/// # Errors
///
/// Returns a 400 when the identifier is malformed, a 409 when the plugin is
/// still referenced, and a 404 when the caller tenant does not own the plugin.
pub async fn delete_plugin(
    Extension(service): Extension<Arc<ManagementService>>,
    context: Option<Extension<SecurityContext>>,
    Path(id): Path<String>,
) -> Result<StatusCode, GatewayError> {
    let tenant = caller_tenant(context.as_ref());
    let target = parse_resource_id(&id, "plugin")?;
    let record = owned_plugin(service.plugins(), tenant, target)?;
    let (upstreams, routes) = plugin_references(&service, tenant, &record);
    if !upstreams.is_empty() || !routes.is_empty() {
        return Err(plugin_in_use(&record, &upstreams, &routes));
    }

    if service.plugins().delete(tenant, target).is_none() {
        // Lost a race with a concurrent delete: the plugin is gone either way.
        return Err(GatewayError::not_found(format!(
            "no plugin with id {target}"
        )));
    }

    Ok(StatusCode::NO_CONTENT)
}

/// Validates a submitted plugin and builds its stored record.
///
/// # Errors
///
/// Returns a 400 [`GatewayError`] when the name or the source is empty.
fn plugin_record(request: &PluginRequest, tenant: Uuid) -> Result<StoredPlugin, GatewayError> {
    let name = request.name.trim();
    if name.is_empty() {
        return Err(GatewayError::validation(
            "`name` is required and must not be blank",
            "name",
        ));
    }
    if request.source_code.trim().is_empty() {
        return Err(GatewayError::validation(
            "`source_code` is required and must not be blank",
            "source_code",
        ));
    }

    Ok(StoredPlugin {
        id: Uuid::new_v4(),
        tenant_id: tenant,
        name: name.to_owned(),
        description: request.description.clone(),
        kind: request.plugin_type,
        phases: normalize_phases(&request.phases),
        config_schema: request.config_schema.clone(),
        source_code: request.source_code.clone(),
    })
}

/// Normalizes the lifecycle phases: trimmed, lower-cased, de-duplicated.
fn normalize_phases(phases: &[String]) -> Vec<String> {
    let mut normalized: Vec<String> = Vec::with_capacity(phases.len());
    for phase in phases {
        let phase = phase.trim().to_ascii_lowercase();
        if !phase.is_empty() && !normalized.contains(&phase) {
            normalized.push(phase);
        }
    }

    normalized
}

/// The plugin owned by `tenant`, or a `404`.
///
/// # Errors
///
/// Returns a 404 [`GatewayError`] when the tenant does not own the plugin.
fn owned_plugin(
    registry: &PluginRegistry,
    tenant: Uuid,
    id: Uuid,
) -> Result<StoredPlugin, GatewayError> {
    registry
        .find(tenant, id)
        .ok_or_else(|| GatewayError::not_found(format!("no plugin with id {id}")))
}

/// The upstreams and routes of `tenant` that still reference `record`, as their
/// wire identifiers.
///
/// Both lists are always returned (possibly empty), so a client can render the
/// references without inspecting the configuration again.
fn plugin_references(
    service: &ManagementService,
    tenant: Uuid,
    record: &StoredPlugin,
) -> (Vec<String>, Vec<String>) {
    let upstreams = service
        .config()
        .list_upstreams(tenant)
        .iter()
        .filter(|upstream| references_plugin(upstream, record))
        .map(|upstream| gts_upstream_id(upstream.id))
        .collect();
    let routes = service
        .config()
        .list_routes(tenant)
        .iter()
        .filter(|route| route_references_plugin(route, record))
        .map(|route| gts_route_id(route.id))
        .collect();

    (upstreams, routes)
}

/// The `409` problem for a plugin that is still referenced.
fn plugin_in_use(record: &StoredPlugin, upstreams: &[String], routes: &[String]) -> GatewayError {
    GatewayError::plugin_in_use(format!(
        "plugin {} is still referenced by {} upstream(s) and {} route(s); unbind it before \
         deleting it",
        record.gts_id(),
        upstreams.len(),
        routes.len()
    ))
    .with_extension("plugin_id", record.gts_id())
    .with_extension(
        "referenced_by",
        json!({ "upstreams": upstreams, "routes": routes }),
    )
}

/// Whether an upstream binds `record`, through its plugin chain or its auth
/// binding.
fn references_plugin(upstream: &Upstream, record: &StoredPlugin) -> bool {
    upstream
        .config
        .plugins
        .items
        .iter()
        .any(|reference| record.is_referenced_by(reference.as_str()))
        || upstream
            .config
            .auth
            .as_ref()
            .and_then(|auth| auth.plugin_type.as_ref())
            .is_some_and(|reference| record.is_referenced_by(reference.as_str()))
}

/// Whether a route binds `record`, through its plugin chain.
fn route_references_plugin(route: &Route, record: &StoredPlugin) -> bool {
    route
        .config
        .plugins
        .items
        .iter()
        .any(|reference| record.is_referenced_by(reference.as_str()))
}

