/// Renders a list page: `$filter`, then `$orderby`, then `$skip`/`$top`, then
/// `$select`.
///
/// Filtering and sorting read the domain records through `values`, and only the
/// returned page is mapped to its wire document through `render`, so a list item
/// has exactly the shape of the same resource read by id.
///
/// # Errors
///
/// Returns the 400 problems of [`ListQuery::resolve`].
fn page_response<T, S, F, G>(
    items: Vec<T>,
    key: &str,
    allowed: &[&str],
    query: &ListQuery,
    values: F,
    render: G,
) -> Result<Json<Value>, GatewayError>
where
    S: Serialize,
    F: Fn(&T, &str) -> Vec<FilterValue> + Copy,
    G: Fn(T) -> S,
{
    let resolved = query.resolve(allowed)?;
    let matched: Vec<T> = items
        .into_iter()
        .filter(|item| resolved.matches(|field| values(item, field)))
        .collect();
    let mut ordered = matched;
    resolved.sort_items(&mut ordered, values);
    let (page, total) = resolved.page(ordered);
    let documents: Vec<S> = page.into_iter().map(render).collect();

    Ok(Json(list_page(
        documents,
        total,
        key,
        resolved.select.as_deref(),
    )))
}

/// Renders the plugin list page, whose field names differ from the stored
/// record's member names.
///
/// # Errors
///
/// Returns the 400 problems of [`ListQuery::resolve`].
fn plugin_page(
    items: Vec<StoredPlugin>,
    allowed: &[&str],
    query: &ListQuery,
) -> Result<Json<Value>, GatewayError> {
    let resolved = query.resolve(allowed)?;
    let matched: Vec<StoredPlugin> = items
        .into_iter()
        .filter(|record| resolved.matches(|field| plugin_values(record, field)))
        .collect();
    let mut ordered = matched;
    resolved.sort_items(&mut ordered, plugin_values);
    let (page, total) = resolved.page(ordered);
    let documents: Vec<PluginDto> = page
        .iter()
        .map(|record| PluginDto::from(StoredPluginView::from(record)))
        .collect();

    Ok(Json(list_page(
        documents,
        total,
        "plugins",
        resolved.select.as_deref(),
    )))
}

/// The values an upstream carries for a filterable field.
fn upstream_values(upstream: &Upstream, field: &str) -> Vec<FilterValue> {
    match field {
        "id" => vec![FilterValue::id(upstream.id)],
        "tenant_id" => vec![FilterValue::id(upstream.tenant_id)],
        "alias" => vec![FilterValue::text(upstream.config.alias.clone())],
        "enabled" => vec![FilterValue::flag(upstream.config.enabled)],
        "protocol" => vec![FilterValue::text(upstream.config.protocol.as_str())],
        "tags" => upstream
            .config
            .tags
            .iter()
            .map(|tag| FilterValue::text(tag.clone()))
            .collect(),
        _ => Vec::new(),
    }
}

/// The values a route carries for a filterable field.
fn route_values(route: &Route, field: &str) -> Vec<FilterValue> {
    match field {
        "id" => vec![FilterValue::id(route.id)],
        "tenant_id" => vec![FilterValue::id(route.tenant_id)],
        "upstream_id" => vec![FilterValue::id(route.config.upstream_id)],
        "enabled" => vec![FilterValue::flag(route.config.enabled)],
        "priority" => vec![FilterValue::number(u64::from(route.config.priority))],
        "tags" => route
            .config
            .tags
            .iter()
            .map(|tag| FilterValue::text(tag.clone()))
            .collect(),
        _ => Vec::new(),
    }
}

/// The values a plugin carries for a filterable field.
fn plugin_values(record: &StoredPlugin, field: &str) -> Vec<FilterValue> {
    match field {
        "id" => vec![FilterValue::id(record.id)],
        "tenant_id" => vec![FilterValue::id(record.tenant_id)],
        "name" => vec![FilterValue::text(record.name.clone())],
        "description" => record
            .description
            .as_ref()
            .map(|description| vec![FilterValue::text(description.clone())])
            .unwrap_or_default(),
        "plugin_type" => vec![FilterValue::text(record.kind.as_str())],
        "phases" => record
            .phases
            .iter()
            .map(|phase| FilterValue::text(phase.clone()))
            .collect(),
        _ => Vec::new(),
    }
}
