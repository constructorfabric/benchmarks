/// The upstream a submitted route belongs to, which is required.
///
/// # Errors
///
/// Returns a 400 when the member is absent or not a valid identifier.
fn require_upstream_id(raw: Option<&String>) -> Result<Uuid, GatewayError> {
    let Some(raw) = raw
        .map(String::as_str)
        .map(str::trim)
        .filter(|raw| !raw.is_empty())
    else {
        return Err(GatewayError::validation(
            "`upstream_id` is required: a route always belongs to an upstream",
            "upstream_id",
        ));
    };

    parse_resource_id(raw, "upstream")
}

/// Rejects a replacement that would move the route to another upstream.
///
/// # Errors
///
/// Returns a 400 [`GatewayError`] when the submitted `upstream_id` differs from
/// the stored one.
fn enforce_immutable_upstream(
    request: &super::dto::RouteRequest,
    stored: Uuid,
) -> Result<(), GatewayError> {
    let Some(submitted) = request.upstream_id.as_deref() else {
        return Ok(());
    };
    if parse_resource_id(submitted, "upstream")? != stored {
        return Err(GatewayError::validation(
            "`upstream_id` is immutable; delete and re-create the route instead",
            "upstream_id",
        ));
    }

    Ok(())
}

