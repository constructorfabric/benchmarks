/// `PUT /oagw/v1/upstreams/{id}` — replaces an upstream.
///
/// `PUT` is a full replacement: absent members fall back to their defaults. The
/// alias is immutable, so a submission that omits it keeps the stored value and
/// one that would change it is rejected.
///
/// # Errors
///
/// Returns a 400 for server-owned members, a changed alias or invalid
/// configuration, and a 404 when the caller tenant does not own the upstream.
pub async fn replace_upstream(
    Extension(service): Extension<Arc<ManagementService>>,
    context: Option<Extension<SecurityContext>>,
    Path(id): Path<String>,
    JsonDocument(request): JsonDocument<UpstreamRequest>,
) -> Result<Json<UpstreamDto>, GatewayError> {
    reject_server_owned(request.id.as_deref(), request.tenant_id)?;

    let tenant = caller_tenant(context.as_ref());
    let target = parse_resource_id(&id, "upstream")?;
    let existing = service.config().get_upstream(tenant, target)?;
    let alias = request.resolved_alias(existing.alias());
    let upstream = service
        .config()
        .replace_upstream(tenant, target, &request.to_spec(alias))?;

    Ok(Json(UpstreamDto::from(upstream)))
}

