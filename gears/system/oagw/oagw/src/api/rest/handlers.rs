/// `POST /oagw/v1/plugins` — stores a custom plugin (ADR 0002, Appendix A).
///
/// Plugins are immutable, so this is the only write the resource accepts.
///
/// # Errors
///
/// Returns a 400 for server-owned members and an incomplete definition.
pub async fn create_plugin(
    Extension(service): Extension<Arc<ManagementService>>,
    context: Option<Extension<SecurityContext>>,
    JsonDocument(request): JsonDocument<PluginRequest>,
) -> Result<(StatusCode, Json<PluginDto>), GatewayError> {
    reject_server_owned(request.id.as_deref(), request.tenant_id)?;

    let tenant = caller_tenant(context.as_ref());
    let stored = plugin_record(&request, tenant)?;
    service.plugins().insert(stored.clone());

    Ok((
        StatusCode::CREATED,
        Json(PluginDto::from(StoredPluginView::from(&stored))),
    ))
}

