/// Tenant used when a request carries no `SecurityContext` at all.
///
/// The anonymous tenant owns nothing, so a request that never traversed the
/// gateway middleware is answered with an empty list or a `404` instead of
/// another tenant's resources.
pub const ANONYMOUS_TENANT: Uuid = Uuid::nil();

/// The tenant every operation is scoped to (DESIGN.md §3.3 "Tenant Scoping").
///
/// Always taken from the `SecurityContext` the gateway injects; client-supplied
/// tenant input is never used. Ancestors are not visible either, which is why a
/// descendant addressing an ancestor-owned resource gets a `404` and never a
/// `403`.
#[must_use]
pub fn caller_tenant(context: Option<&Extension<SecurityContext>>) -> Uuid {
    context.map_or(ANONYMOUS_TENANT, |Extension(context)| {
        context.subject_tenant_id()
    })
}

/// Rejects a submission that sets a member only the gateway may write
/// (DESIGN.md §3.3 "Immutable fields").
///
/// # Errors
///
/// Returns a 400 [`GatewayError`] when `id` or `tenant_id` is present.
fn reject_server_owned(id: Option<&str>, tenant_id: Option<Uuid>) -> Result<(), GatewayError> {
    if id.is_some() {
        return Err(GatewayError::validation(
            "`id` is generated by the gateway and must not be submitted",
            "id",
        ));
    }
    if tenant_id.is_some() {
        return Err(GatewayError::validation(
            "`tenant_id` is taken from the authenticated caller and must not be submitted",
            "tenant_id",
        ));
    }

    Ok(())
}

