/// `POST /oagw/v1/upstreams` — creates an upstream.
///
/// # Errors
///
/// Returns the validation errors of `validate_upstream` (400) and a 409 when
/// the tenant already owns the alias.
pub async fn create_upstream(
    Extension(service): Extension<Arc<ManagementService>>,
    context: Option<Extension<SecurityContext>>,
    JsonDocument(request): JsonDocument<UpstreamRequest>,
) -> Result<(StatusCode, Json<UpstreamDto>), GatewayError> {
    reject_server_owned(request.id.as_deref(), request.tenant_id)?;

    let tenant = caller_tenant(context.as_ref());
    let upstream = service
        .config()
        .create_upstream(tenant, &request.to_spec(request.alias.clone()))?;

    Ok((StatusCode::CREATED, Json(UpstreamDto::from(upstream))))
}

/// `GET /oagw/v1/upstreams` — lists the caller's upstreams.
///
/// # Errors
///
/// Returns a 400 [`GatewayError`] when a list parameter cannot be honoured.
pub async fn list_upstreams(
    Extension(service): Extension<Arc<ManagementService>>,
    context: Option<Extension<SecurityContext>>,
    query: ListQuery,
) -> Result<Json<Value>, GatewayError> {
    let tenant = caller_tenant(context.as_ref());
    let items = service.config().list_upstreams(tenant);

    page_response(
        items,
        "upstreams",
        UPSTREAM_LIST_FIELDS,
        &query,
        upstream_values,
        |upstream| UpstreamDto::from(&upstream),
    )
}

