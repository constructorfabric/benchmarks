//! Handlers of the OAGW management REST API.
//!
//! One function per operation (the `types-registry` convention): each handler
//! takes the [`ManagementService`] and the [`SecurityContext`] from the request
//! extensions, delegates every rule to the domain layer, and maps the result to
//! the wire document. Nothing is validated here.
//!
//! ## Status codes
//!
//! Only the statuses DESIGN.md §3.3 allows are produced: `200` for reads and
//! replacements, `201` for creations, `204` for deletions, `400` for invalid
//! input, `404` for a resource outside the caller tenant and `409` for
//! conflicts. Every failure is a [`GatewayError`], which renders as an RFC 9457
//! problem document.

use std::sync::Arc;

use axum::Extension;
use axum::Json;
use axum::extract::Path;
use axum::http::StatusCode;
use serde::Serialize;
use serde_json::{Value, json};
use toolkit_security::SecurityContext;
use uuid::Uuid;

