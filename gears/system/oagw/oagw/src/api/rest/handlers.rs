/// `PUT /oagw/v1/routes/{id}` — replaces a route.
///
/// `upstream_id` is immutable: a submission that names a different upstream is
/// rejected instead of being overwritten.
///
/// # Errors
///
/// Returns a 400 for server-owned members, a changed `upstream_id` or an
/// invalid configuration, a 404 when the caller tenant does not own the route,
/// and a 409 on a duplicate match rule.
pub async fn replace_route(
    Extension(service): Extension<Arc<ManagementService>>,
    context: Option<Extension<SecurityContext>>,
    Path(id): Path<String>,
    JsonDocument(request): JsonDocument<RouteRequest>,
) -> Result<Json<RouteDto>, GatewayError> {
    reject_server_owned(request.id.as_deref(), request.tenant_id)?;

    let tenant = caller_tenant(context.as_ref());
    let target = parse_resource_id(&id, "route")?;
    let existing = service.config().get_route(tenant, target)?;
    enforce_immutable_upstream(&request, existing.config.upstream_id)?;
    let route = service.config().replace_route(
        tenant,
        target,
        &request.to_spec(existing.config.upstream_id),
    )?;

    Ok(Json(RouteDto::from(route)))
}

