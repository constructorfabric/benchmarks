    fn declared_length_is_only_reported_for_a_well_formed_content_length() {
        let mut headers = HeaderMap::new();
        headers.insert(http::header::CONTENT_LENGTH, HeaderValue::from_static("7"));
        assert_eq!(
            declared_length(guards::validate_body_headers(&headers).expect("valid framing")),
            Some(7)
        );

        let mut chunked = HeaderMap::new();
        chunked.insert(
            http::header::TRANSFER_ENCODING,
            HeaderValue::from_static("chunked"),
        );
        assert_eq!(
            declared_length(guards::validate_body_headers(&chunked).expect("chunked")),
            None
        );
        assert_eq!(
            declared_length(guards::validate_body_headers(&HeaderMap::new()).expect("absent")),
            None
        );

        // A malformed length is an error, never a silent `None`.
        let mut malformed = HeaderMap::new();
        malformed.insert(
            http::header::CONTENT_LENGTH,
            HeaderValue::from_static("not-a-number"),
        );
        assert!(
            guards::validate_body_headers(&malformed).is_err(),
            "a malformed Content-Length is a 400"
        );
    }

