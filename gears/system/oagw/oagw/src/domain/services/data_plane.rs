//! Data-plane service: proxy execution (DESIGN §3.5, ADR-0001 Appendix A).
//!
//! [`DataPlaneService`] is the *engine* of the proxy: it resolves the alias,
//! matches a route, selects an endpoint, transforms the headers and forwards
//! the request. The decisions themselves live in
//! [`crate::domain::routing`], [`crate::domain::headers`] and
//! [`crate::domain::guards`]; this module only sequences them and maps the
//! transport failures onto the OAGW error surface.
//!
//! Cost model: the service is a cheap `Arc`-heavy handle (`Clone`), owns one
//! shared outbound connection pool for the process, and never buffers a body —
//! request and response bytes stream through unchanged. A WebSocket handshake is
//! the one request that does not end with a body: [`Self::proxy_upgrade`] runs
//! the same decisions and then hands the spliced socket back, so a proxied
//! WebSocket passes every gate an ordinary request passes (ADR-0007).
//!
//! A CORS preflight is *not* one of the decisions sequenced here: the transport
//! answers it through [`DataPlaneService::preflight`], before it requires a
//! `SecurityContext`, because a browser preflight carries no credentials and
//! would otherwise be rejected as unauthenticated on every cross-origin call
//! (ADR-0004 "Preflight Request Handling"). What reaches [`Self::proxy`] is
//! therefore always an authenticated, resolvable request.

