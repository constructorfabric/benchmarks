    #[test]
    fn requires_target_host_is_memoized_per_upstream_id() {
        let service = service(OagwConfig::default());
        // An IP pool with an explicit alias: round-robins, no header required.
        let record = Arc::new(upstream("my-service", &["10.0.1.1", "10.0.1.2"]));

        assert!(!service.requires_target_host(&record));
        assert!(
            !service.requires_target_host(&record),
            "the second call reads the memo"
        );
        assert_eq!(service.requires_target_host.len(), 1);

        // A common-suffix pool needs the header; the memo is keyed by id, so a
        // different record is derived independently.
        let mut pool = upstream("vendor.com", &["us.vendor.com", "eu.vendor.com"]);
        pool.id = Uuid::new_v4();
        assert!(service.requires_target_host(&pool));
        assert_eq!(service.requires_target_host.len(), 2);
    }

    #[test]
    fn the_memo_is_invalidated_when_the_record_is_replaced() {
        let service = service(OagwConfig::default());
        let mut record = upstream("api.vendor.com", &["us.vendor.com"]);
        record.id = Uuid::new_v4();
        record.updated_at = 1;

        assert!(!service.requires_target_host(&record));

        // The same id, a new generation: two hosts that share the derived
        // alias now need the header, and the cache must not serve the old
        // answer.
        let mut replaced = record.clone();
        replaced.updated_at = 2;
        replaced.spec.alias = Some("vendor.com".to_owned());
        replaced.spec.server.endpoints = vec![
            Endpoint {
                scheme: Scheme::Https,
                host: "us.vendor.com".to_owned(),
                port: 443,
            },
            Endpoint {
                scheme: Scheme::Https,
                host: "eu.vendor.com".to_owned(),
                port: 443,
            },
        ];
        replaced.alias = "vendor.com".to_owned();

        assert!(
            service.requires_target_host(&replaced),
            "a replaced record is re-derived"
        );
    }

    #[tokio::test]
    async fn a_response_phase_gateway_error_carries_the_correlation_id() {
        // A plugin that fails on the response phase is a gateway error for a
        // request whose id the transport already minted: the problem document
        // must name *that* id, so the failure joins its audit record.
        let request_id = Uuid::new_v4().to_string();
        let response = gateway_error(
            "/oagw/v1/proxy/api.vendor.com/v1".to_owned(),
            request_id.clone(),
            OagwError::downstream_error("the response guard refused this response"),
        );

        assert_eq!(response.status().as_u16(), 502);
        assert_eq!(
            response
                .headers()
                .get(error_source_header_name())
                .and_then(|value| value.to_str().ok()),
            Some(crate::error::ERROR_SOURCE_GATEWAY),
            "the response phase reports as a gateway error, not an upstream one"
        );

        let bytes = http_body_util::BodyExt::collect(response.into_body())
            .await
            .expect("the body is readable")
            .to_bytes();
        let document: serde_json::Value =
            serde_json::from_slice(&bytes).expect("gateway errors are problem+json");
        assert_eq!(
            document["trace_id"], request_id,
            "the same id the audit record logs, not a freshly minted one"
        );
        assert_eq!(
            document["instance"],
            serde_json::json!("/oagw/v1/proxy/api.vendor.com/v1")
        );
    }

    #[test]
    fn a_rendered_gateway_error_reports_its_kind_to_the_outcome_readers() {
        // A response-phase failure comes back as `Ok` with a rendered problem
        // document; the kind it was stamped with is what both the §4.2 counter
        // and the §4.3 audit record must read.
        let rendered = gateway_error(
            "/oagw/v1/proxy/api.vendor.com/v1".to_owned(),
            "01JOUTCOME".to_owned(),
            OagwError::downstream_error("the response guard refused this response"),
        );
        let outcome: Result<axum::response::Response, OagwError> = Ok(rendered);
        assert_eq!(
            outcome_error_kind(&outcome),
            Some(crate::error::OagwErrorKind::DownstreamError),
            "the extension `gateway_error` inserts is the kind the readers see"
        );

        // A raised gateway error is unchanged, and a forwarded upstream answer is
        // still not a gateway error.
        let raised: Result<axum::response::Response, OagwError> =
            Err(OagwError::payload_too_large("too many bytes"));
        assert_eq!(
            outcome_error_kind(&raised),
            Some(crate::error::OagwErrorKind::PayloadTooLarge)
        );
        let passed_through: Result<axum::response::Response, OagwError> =
            Ok(axum::response::Response::builder()
                .status(503)
                .body(axum::body::Body::empty())
                .expect("a response builds"));
        assert_eq!(outcome_error_kind(&passed_through), None);
    }

