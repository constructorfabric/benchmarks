/// The shared outbound HTTP client: one connection pool for the process.
type OutboundClient = Client<HttpConnector, Body>;

/// What the proxy knows about the request it is about to forward.
///
/// The transport layer (REST handler) fills this in; the domain layer never
/// parses a URL.
#[derive(Debug)]
pub struct ProxyRequest {
    /// The alias as it appeared on the proxy path (not yet normalized).
    pub alias: String,
    /// The request method.
    pub method: Method,
    /// The request path with the proxy prefix and the alias removed.
    pub stripped_path: String,
    /// The raw query string, without the leading `?` (may be empty).
    pub query: String,
    /// The inbound request headers.
    pub headers: HeaderMap,
    /// The inbound request body, streamed.
    pub body: Body,
    /// The full request path as the caller sent it, used for the RFC 9457
    /// `instance` member of gateway errors.
    pub request_path: String,
    /// Correlation id of this request: generated by the transport (the host
    /// provides no inbound correlation header) and carried into every gateway
    /// error and audit record for it.
    pub request_id: String,
}

/// Identity of a proxy request handed to the optional hooks.
///
/// The hooks are the policies of the data plane (rate limiting, CORS, the
/// plugin chain), so the context carries everything a policy may look at and
/// nothing it may change: the request is identified, the resolved
/// configuration is referenced, and the *inbound* headers are read-only — the
/// hook that wants to alter what is forwarded writes into the outbound header
/// map it is handed alongside this context.
#[derive(Debug, Clone)]
pub struct ProxyContext {
    /// Authenticated principal, when known.
    pub subject_id: Uuid,
    /// Calling tenant.
    pub tenant_id: Uuid,
    /// Resolved upstream.
    pub upstream_id: Uuid,
    /// Resolved alias.
    pub alias: String,
    /// Matched route, when one matched.
    pub route_id: Option<Uuid>,
    /// Request method.
    pub method: String,
    /// Stripped request path.
    pub path: String,
    /// Correlation id of the request ([`ProxyRequest::request_id`]).
    pub request_id: String,
    /// The authenticated caller, as the host's security context. A policy that
    /// resolves tenant-scoped material (a `cred://` reference, say) presents
    /// *this* context, so the authorization decision is the caller's own.
    pub security: SecurityContext,
    /// Client address of the request, as [`rate_limit_client_ip`] read it:
    /// the leftmost `X-Forwarded-For` entry, or `None` when the caller sent
    /// none (ADR-0003).
    pub client_ip: Option<IpAddr>,
    /// The resolved upstream, with its own configuration.
    pub upstream: Arc<Upstream>,
    /// The matched route, when one matched.
    pub route: Option<Arc<Route>>,
    /// The headers the caller sent, before any transformation. A guard checks
    /// *this* map: the outbound map starts from the passthrough policy, so a
    /// header the caller sent and the policy dropped would be invisible in it.
    pub inbound_headers: HeaderMap,
}

/// Rate-limiting seam (ADR-0003).
///
/// The data plane folds the effective limit (ADR-0003 "3. Inheritance") and
/// hands it over; the hook owns the counter. A decision that is not `allowed`
/// short-circuits the request with a 429 that carries the decision's
/// `X-RateLimit-*` and `Retry-After` headers; an allowed one is stamped with the
/// decision's budget state after the upstream answered, so the upstream never
/// sees or produces either.
pub trait RateLimitHook: Send + Sync {
    /// Take the request's cost from the bucket of its counter key.
    ///
    /// # Errors
    /// Implementations may fail the request with their own error kind.
    fn check(
        &self,
        context: &ProxyContext,
        limit: &EffectiveRateLimit,
    ) -> Result<RateLimitDecision, OagwError>;
}

/// CORS seam (ADR-0004): a built-in handler of the proxy, not a plugin.
pub trait CorsHook: Send + Sync {
    /// Answer a preflight request without resolving anything (ADR-0004
    /// "Preflight Request Handling").
    ///
    /// `None` leaves the request to the ordinary path; `Some` short-circuits it
    /// before the tenant is resolved, the rate limiter runs or a plugin is
    /// called.
    fn preflight(&self, preflight: &CorsPreflight) -> Option<PreflightResponse>;

    /// Validate an actual cross-origin request and produce the headers its
    /// response must carry.
    ///
    /// The data plane folds the effective configuration (the same fold
    /// [`Self::effective_cors`] performs for the rate limit) and hands it over;
    /// `None` means no CORS configuration applies, and the hook is not called.
    ///
    /// # Errors
    /// A 403 for a disallowed origin or method (ADR-0004 "Error Responses").
    fn validate(
        &self,
        context: &ProxyContext,
        config: &CorsConfig,
        request: &CorsRequest,
    ) -> Result<HeaderMap, OagwError>;
}

/// Plugin engine seam (ADR-0002): auth, then guards, then transforms.
///
/// The chain itself — upstream plugins before route plugins — is resolved by
/// the implementation; the data plane only hands it the request context and the
/// header map to work on.
#[async_trait]
pub trait PluginEngine: Send + Sync {
    /// Run the request-side chain.
    ///
    /// # Errors
    /// An implementation may fail the request.
    async fn on_request(
        &self,
        context: &ProxyContext,
        headers: &mut HeaderMap,
    ) -> Result<(), OagwError>;
    /// Run the response-side chain.
    ///
    /// # Errors
    /// An implementation may fail the request.
    async fn on_response(
        &self,
        context: &ProxyContext,
        headers: &mut HeaderMap,
    ) -> Result<(), OagwError>;
}

/// The optional extension points a later slice can register.
#[derive(Clone, Default)]
pub struct ProxyHooks {
    rate_limit: Option<Arc<dyn RateLimitHook>>,
    cors: Option<Arc<dyn CorsHook>>,
    plugins: Option<Arc<dyn PluginEngine>>,
}

impl ProxyHooks {
    /// The hooks the gear installs: rate limiting, CORS, the plugin chain
    /// (ADR-0002, ADR-0003, ADR-0004).
    ///
    /// `None` leaves that policy out entirely: the request is then never
    /// throttled, never validated for CORS and forwarded without plugins — the
    /// seam is the slice's, and the gear decides what it is filled with.
    #[must_use]
    pub fn new(
        rate_limit: Option<Arc<dyn RateLimitHook>>,
        cors: Option<Arc<dyn CorsHook>>,
        plugins: Option<Arc<dyn PluginEngine>>,
    ) -> Self {
        Self {
            rate_limit,
            cors,
            plugins,
        }
    }
}

impl std::fmt::Debug for ProxyHooks {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("ProxyHooks")
            .field("rate_limit", &self.rate_limit.is_some())
            .field("cors", &self.cors.is_some())
            .field("plugins", &self.plugins.is_some())
            .finish()
    }
}

/// Proxy engine: alias resolution, routing, endpoint selection and forwarding.
#[derive(Clone)]
pub struct DataPlaneService {
    config: OagwConfig,
    control_plane: Arc<ControlPlaneService>,
    upstreams: Arc<UpstreamStore>,
    routes: Arc<RouteStore>,
    hierarchy: Option<Arc<dyn TenantHierarchy>>,
    client: OutboundClient,
    round_robin: DashMap<Uuid, Arc<AtomicUsize>>,
    /// Memoized `Upstream::requires_target_host` per upstream id.
    ///
    /// The decision re-derives the public-suffix alias of the endpoint pool,
    /// which is far too expensive to repeat per request; the cached value is
    /// keyed by the record's `updated_at`, so a configuration replace
    /// recomputes it (see [`Self::requires_target_host`]).
    requires_target_host: DashMap<Uuid, (u64, bool)>,
    hooks: ProxyHooks,
    metrics: OagwMetrics,
}

impl std::fmt::Debug for DataPlaneService {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("DataPlaneService")
            .field("proxy_timeout_secs", &self.config.proxy_timeout_secs)
            .field("upstreams", &self.upstreams.len())
            .field("routes", &self.routes.len())
            .field("tenant_hierarchy", &self.hierarchy.is_some())
            .field("hooks", &self.hooks)
            .field("metrics", &self.metrics)
            .finish()
    }
}

impl DataPlaneService {
    /// Build a service over the control plane's stores.
    ///
    /// The stores are shared with the control plane, so a configuration change
    /// is visible to the very next request; no cache is involved (DESIGN §3.5
    /// "no response caching", and no configuration caching either).
    #[must_use]
    pub fn new(
        config: OagwConfig,
        control_plane: Arc<ControlPlaneService>,
        upstreams: Arc<UpstreamStore>,
        routes: Arc<RouteStore>,
    ) -> Self {
        Self {
            client: outbound_client(),
            round_robin: DashMap::new(),
            requires_target_host: DashMap::new(),
            hierarchy: None,
            hooks: ProxyHooks::default(),
            // With no meter provider installed the global meter is a no-op, so
            // this default costs nothing and the gear installs its own scope
            // over it (DESIGN §4.2: the *host* owns the provider).
            metrics: OagwMetrics::from_global(DEFAULT_METER_SCOPE),
            config,
            control_plane,
            upstreams,
            routes,
        }
    }

    /// Install the tenant-hierarchy source.
    ///
    /// Without one the proxy degrades to the calling tenant only: still
    /// correct, just without inherited configuration (see
    /// [`TenantHierarchy::chain`]).
    #[must_use]
    pub fn with_tenant_hierarchy(mut self, hierarchy: Arc<dyn TenantHierarchy>) -> Self {
        self.hierarchy = Some(hierarchy);
        self
    }

    /// Install the optional extension hooks (rate limiting, CORS, plugins).
    #[must_use]
    pub fn with_hooks(mut self, hooks: ProxyHooks) -> Self {
        self.hooks = hooks;
        self
    }

    /// Install the metric instruments the proxy records (DESIGN §4.2).
    ///
    /// Without one the service records through the global meter, which is a
    /// no-op until the host installs a provider.
    #[must_use]
    pub fn with_metrics(mut self, metrics: OagwMetrics) -> Self {
        self.metrics = metrics;
        self
    }

    /// Gear configuration.
    #[must_use]
    pub const fn config(&self) -> &OagwConfig {
        &self.config
    }

    /// Answer a preflight without authenticating the caller (ADR-0004
    /// "Preflight Request Handling").
    ///
    /// A browser preflight carries no credentials (WHATWG Fetch), so the
    /// transport asks for the answer *before* it requires a `SecurityContext`.
    /// The reply is permissive and carries no data beyond the echo of the
    /// request's own `Access-Control-Request-*` headers: it vouches for no
    /// origin and resolves no configuration, so answering it unauthenticated
    /// buys a caller nothing. `None` when the request is not a preflight, or
    /// when no CORS hook is installed.
    #[must_use]
    pub fn preflight(
        &self,
        method: &Method,
        headers: &HeaderMap,
    ) -> Option<axum::response::Response> {
        if !is_preflight(method, headers) {
            return None;
        }
        let hook = self.hooks.cors.as_ref()?;
        hook.preflight(&CorsPreflight::from_headers(headers))
            .map(PreflightResponse::into_response)
    }

    /// The control-plane service this proxy resolves configuration through.
    #[must_use]
    pub const fn control_plane(&self) -> &Arc<ControlPlaneService> {
        &self.control_plane
    }

    /// Upstream store shared with the control plane.
    #[must_use]
    pub fn upstreams(&self) -> &Arc<UpstreamStore> {
        &self.upstreams
    }

    /// Route store shared with the control plane.
    #[must_use]
    pub fn routes(&self) -> &Arc<RouteStore> {
        &self.routes
    }

    /// Resolve a proxy request end to end and return the upstream response.
    ///
    /// Gateway failures are returned as [`OagwError`] and rendered by the
    /// transport; a *successful* resolution always yields a response with
    /// `X-OAGW-Error-Source: upstream`, whatever its status.
    ///
    /// Exactly one structured audit record is written for the request, whether
    /// it is forwarded or rejected (DESIGN §4.3); the record carries no body,
    /// query string, header or credential.
    ///
    /// # Errors
    /// Every kind in the data-plane section of the error table
    /// (DESIGN §3.3): 401, 404, 400, 413, 502, 503, 504.
    pub async fn proxy(
        &self,
        security: &SecurityContext,
        caller: &CallerContext,
        request: ProxyRequest,
    ) -> Result<axum::response::Response, OagwError> {
        let started = Instant::now();
        // Copied out before the request is moved: they are the identity of the
        // audit record, whatever the outcome.
        let identity = RequestIdentity {
            request_id: request.request_id.clone(),
            method: request.method.as_str().to_owned(),
            alias: request.alias.clone(),
            path: request.stripped_path.clone(),
            subject_id: caller.subject_id(),
        };
        // The gauge must be taken at entry, not after resolution, but the alias
        // as requested is request data and must not become a label: before
        // resolution runs the `host` label is the fixed sentinel (see
        // `metrics`).
        let in_flight = self.metrics.in_flight(OagwMetrics::UNRESOLVED_HOST);
        let mut audit = RequestAudit::default();

        let result = self
            .execute(&mut audit, security, caller, request, None)
            .await;

        self.record_outcome(&identity, &audit, &result, started.elapsed());
        log_request(&identity, &audit, &result, started.elapsed());
        drop(in_flight);
        result
    }

    /// Run a WebSocket handshake through the proxy and splice the connections
    /// (PRD §5.4 `cpt-cf-oagw-fr-streaming`, DESIGN §3.3 "Proxy API", ADR-0007).
    ///
    /// The handshake is a *request* like any other first: the alias is resolved,
    /// the route is matched, the endpoint is selected, the caller is throttled,
    /// the guards and the plugin chain run. Only after all of that does the
    /// gateway forward it as an upgrade. Three outcomes are possible:
    ///
    /// * the upstream answers `101` and the two connections are spliced — the
    ///   caller gets the `101` the gateway signed, and everything past it is
    ///   [`crate::streaming::splice`]'s business;
    /// * the upstream answers anything else, which is passed through unchanged,
    ///   so the caller's WebSocket client fails the handshake on its own (RFC
    ///   6455 §4.1 allows any error status for a rejected handshake);
    /// * a gateway decision rejects the request, which is an [`OagwError`] and
    ///   renders as an ordinary problem+json document.
    ///
    /// `upgrade` is the transport's handle on the caller's socket. The gateway
    /// signs the handshake with it (`Sec-WebSocket-Accept` from the caller's own
    /// `Sec-WebSocket-Key`), so the handshake the caller sees is this gateway's,
    /// and it is consistent because the key it is signed from travelled to the
    /// upstream unchanged.
    ///
    /// # Errors
    /// Every kind in the data-plane section of the error table (DESIGN §3.3),
    /// exactly as [`Self::proxy`] produces them for an ordinary request.
    pub async fn proxy_upgrade(
        &self,
        security: &SecurityContext,
        caller: &CallerContext,
        request: ProxyRequest,
        upgrade: WebSocketUpgrade,
    ) -> Result<axum::response::Response, OagwError> {
        let started = Instant::now();
        let identity = RequestIdentity {
            request_id: request.request_id.clone(),
            method: request.method.as_str().to_owned(),
            alias: request.alias.clone(),
            path: request.stripped_path.clone(),
            subject_id: caller.subject_id(),
        };
        // Same guard, same reasoning: a handshake that panics mid-splice must
        // not leave the in-flight gauge ratcheted up, and the same sentinel
        // stands in for the alias until resolution has run (see `proxy`).
        let in_flight = self.metrics.in_flight(OagwMetrics::UNRESOLVED_HOST);
        let mut audit = RequestAudit::default();

        let result = self
            .execute(&mut audit, security, caller, request, Some(upgrade))
            .await;

        self.record_outcome(&identity, &audit, &result, started.elapsed());
        log_request(&identity, &audit, &result, started.elapsed());
        drop(in_flight);
        result
    }

    /// Write the request's metric measurements (DESIGN §4.2).
    ///
    /// Called from the wrappers, where the final `Result` is known, so a
    /// gateway error and a forwarded response are both counted exactly once and
    /// under the same labels. `execute` stays the single place that resolves
    /// configuration; this is the single place that records the outcome, next to
    /// the one place that logs it.
    ///
    /// `host` is the resolved upstream alias when the request got that far, and
    /// the fixed sentinel [`OagwMetrics::UNRESOLVED_HOST`] otherwise — never the
    /// alias as requested, which is request data and unbounded cardinality (see
    /// `metrics`); `route` is the matched route's pattern, or the empty string
    /// when nothing matched.
    fn record_outcome(
        &self,
        identity: &RequestIdentity,
        audit: &RequestAudit,
        result: &Result<axum::response::Response, OagwError>,
        total: Duration,
    ) {
        // Borrowed, not copied: `execute` has returned, so nothing else reads
        // the audit record and the metric methods take `&str`.
        let host = audit
            .upstream_alias
            .as_deref()
            .unwrap_or(OagwMetrics::UNRESOLVED_HOST);
        let route = audit.route_pattern.as_deref().unwrap_or_default();
        let status = match result {
            Ok(response) => response.status().as_u16(),
            Err(error) => error.status().as_u16(),
        };

        self.metrics
            .request_outcome(host, &identity.method, route, status);
        self.metrics
            .request_duration(host, route, RequestPhase::Total, total);
        if let Some(kind) = outcome_error_kind(result) {
            self.metrics.error(host, route, kind.gts_type_id());
        }
    }

    /// The body of [`Self::proxy`]: resolve, transform, forward.
    ///
    /// Everything it learns about the request is written into `audit`, so the
    /// caller can log a complete record for either outcome. `handshake` is
    /// `Some` for a WebSocket upgrade, which changes only what a handshake
    /// genuinely needs to be different (see `UPGRADE` below); every decision —
    /// alias, route, endpoint, rate limit, CORS, guards, plugins — is taken
    /// once, here, for both kinds of request.
    async fn execute(
        &self,
        audit: &mut RequestAudit,
        security: &SecurityContext,
        caller: &CallerContext,
        request: ProxyRequest,
        handshake: Option<WebSocketUpgrade>,
    ) -> Result<axum::response::Response, OagwError> {
        // A preflight never reaches this method: the transport answers it before
        // it requires a `SecurityContext` (ADR-0004 "Preflight Request
        // Handling"), because a browser preflight carries no credentials and
        // would otherwise be a 401 on every cross-origin call. What is left to
        // do here is the *actual* request, whose origin and method are enforced
        // below, once the upstream is known.
        let tenant_id = self.control_plane.tenant_of(caller)?;
        audit.tenant_id = Some(tenant_id);
        let chain = self.tenant_chain(security, tenant_id).await;

        let mut error_context = ErrorContext {
            request_path: request.request_path.clone(),
            request_id: request.request_id.clone(),
            alias: request.alias.clone(),
            upstream: None,
            endpoint: None,
            forwarded_path: None,
        };

        let upstream = match routing::resolve_alias(&chain, &request.alias, |tenant, alias| {
            self.upstreams.get_by_alias(tenant, alias)
        }) {
            routing::AliasResolution::Found(upstream) => upstream,
            // The alias is unknown to the whole chain.
            routing::AliasResolution::NotFound => {
                return Err(error_context.apply(not_found(&request.alias)));
            }
            // The nearest owner disabled it: report 503 instead of serving the
            // ancestor's upstream (see `resolve_alias`).
            routing::AliasResolution::Disabled(upstream) => {
                error_context.alias = upstream.alias.clone();
                error_context.upstream = Some(Arc::clone(&upstream));
                return Err(error_context.apply(disabled_error(&upstream)));
            }
        };
        error_context.alias = upstream.alias.clone();
        error_context.upstream = Some(Arc::clone(&upstream));
        audit.upstream_id = Some(upstream.id);
        audit.upstream_alias = Some(upstream.alias.clone());

        if !is_http_upstream(&upstream) {
            return Err(error_context.apply(not_found(&request.alias)));
        }

        // The path is forwarded verbatim, so it must not be able to mean
        // something else to the upstream than it meant to the router that
        // matched it (dot segments, empty segments, encoded separators).
        validate_path_segments(&request.stripped_path)
            .map_err(|error| error_context.apply(error))?;

        let candidates = route_candidates(&chain, upstream.id, |tenant, upstream_id| {
            self.routes.list_by_upstream(tenant, upstream_id)
        });

        let query_keys = query_keys(&request.query);
        let matched = match_route(
            &candidates,
            &request.method,
            &request.stripped_path,
            &query_keys,
        )
        .map_err(|error| error_context.apply(error))?;
        error_context.forwarded_path = Some(matched.forwarded_path.clone());
        audit.route_id = Some(matched.route.id);
        // The metrics label `http.route` is the *pattern*, never the raw path:
        // a pattern is a configured string, so a thousand distinct request
        // paths land on one label value (DESIGN §4.2 "Cardinality management").
        audit.route_pattern = Some(route_pattern(&matched.route));
        // The pattern of the matched route, as the metrics label it: one
        // binding for the rest of the request, so the rate-limit `path` and the
        // `http.route` of the upstream leg cannot drift apart.
        let route_path = audit.route_pattern.clone().unwrap_or_default();

        let target_host = target_host(&request.headers);
        // Read before the value is moved into `select`: it is what decides
        // whether the pin metric is written.
        let pinned_by_header = target_host.is_some();
        let selected = self
            .select(upstream.clone(), target_host)
            .map_err(|error| error_context.apply(error))?;
        let endpoint = selected.endpoint;
        error_context.endpoint = Some(endpoint.clone());
        audit.endpoint_host = Some(endpoint.host.clone());
        audit.endpoint_port = Some(endpoint.port);
        audit.selection_method = Some(selected.method);
        self.metrics
            .routing_endpoint_selected(upstream.id, &endpoint.host, selected.method);
        if pinned_by_header {
            // Recorded only here, after the pin succeeded, so `endpoint_host` is
            // always a *configured* host: an unparsable header value must not
            // become a metric label (see `metrics`).
            self.metrics
                .routing_target_host_used(upstream.id, &endpoint.host);
        }

        // Plaintext is a configuration decision, not a transport accident: the
        // gate is checked where the endpoint is chosen, before any socket is
        // opened (DESIGN §2.2 HTTPS-only, `allow_http_upstream`).
        if endpoint.scheme == Scheme::Http && !self.config.allows_http_upstream() {
            return Err(error_context.apply(http_scheme_not_allowed_error()));
        }

        let context = ProxyContext {
            subject_id: caller.subject_id(),
            tenant_id,
            upstream_id: upstream.id,
            alias: upstream.alias.clone(),
            route_id: Some(matched.route.id),
            method: request.method.as_str().to_owned(),
            path: request.stripped_path.clone(),
            request_id: request.request_id.clone(),
            security: security.clone(),
            client_ip: rate_limit_client_ip(&request.headers),
            upstream: Arc::clone(&upstream),
            route: Some(Arc::clone(&matched.route)),
            // Read only by the guard plugins, and only when one is installed.
            inbound_headers: match self.hooks.plugins.as_ref() {
                Some(_) => request.headers.clone(),
                None => HeaderMap::new(),
            },
        };

        // Rate limiting runs before anything else that can reject the request:
        // a disallowed origin or a missing header still spends a token from the
        // caller's bucket (ADR-0003 "1. Algorithm").
        let mut rate_limit_headers = HeaderMap::new();
        if let Some(limit) = self.effective_rate_limit(&chain, &upstream, Some(&matched.route))
            && let Some(hook) = self.hooks.rate_limit.as_ref()
        {
            let decision = hook.check(&context, &limit)?;
            // Both rate-limit instruments use the route's *pattern* as `path`:
            // the raw request path is unbounded cardinality, which is what the
            // §4.2 cardinality rule forbids (see `metrics`).
            if !decision.allowed {
                self.metrics
                    .rate_limit_exceeded(&upstream.alias, &route_path);
                if let Some(ratio) =
                    rate_limit_usage_ratio(decision.limit_value, decision.remaining)
                {
                    self.metrics
                        .rate_limit_usage(&upstream.alias, &route_path, ratio);
                }
                return Err(error_context.apply(
                    OagwError::rate_limit_exceeded(
                        "rate limit exceeded for this upstream",
                        decision.retry_after_secs,
                    )
                    .with_rate_limit_state(
                        &decision.limit,
                        decision.remaining,
                        decision.reset_unix_secs,
                    ),
                ));
            }
            if let Some(ratio) = rate_limit_usage_ratio(decision.limit_value, decision.remaining) {
                self.metrics
                    .rate_limit_usage(&upstream.alias, &route_path, ratio);
            }
            // The budget state travels with an *allowed* response too: a caller
            // that only learns it is out of budget has to retry blind. The
            // headers are the gateway's, never the upstream's (ADR-0003
            // "Response Headers"), and there is no `Retry-After` without a 429.
            rate_limit_headers.insert(
                RATE_LIMIT_LIMIT_HEADER,
                HeaderValue::from_str(&decision.limit).map_err(|error| {
                    error_context.apply(OagwError::internal(format!(
                        "the rate-limit header is not a header value: {error}"
                    )))
                })?,
            );
            rate_limit_headers.insert(
                RATE_LIMIT_REMAINING_HEADER,
                HeaderValue::from(decision.remaining),
            );
            if decision.reset_unix_secs > 0 {
                rate_limit_headers.insert(
                    RATE_LIMIT_RESET_HEADER,
                    HeaderValue::from(decision.reset_unix_secs),
                );
            }
        }

        // CORS is enforced once the upstream is known: its effective
        // configuration decides, and the answer is 403, not a passthrough
        // (ADR-0004 "Error Responses"). A request without an `Origin` is not a
        // CORS request, so it is validated like any other.
        let cors = self.effective_cors(&chain, &upstream);
        let cors_headers = match (self.hooks.cors.as_ref(), cors.as_ref()) {
            (Some(hook), Some(config)) => hook
                .validate(
                    &context,
                    config,
                    &CorsRequest {
                        origin: header_value(&request.headers, "origin"),
                        method: request.method.as_str().to_owned(),
                    },
                )
                .map_err(|error| error_context.apply(error))?,
            // No configuration, or no hook installed: the response carries no
            // CORS header at all.
            _ => HeaderMap::new(),
        };

        // One read of the framing headers decides the forwarded `Content-Length`,
        // the audit size and the streaming check, so a malformed header can
        // never be validated twice with different outcomes. The error is raised
        // here and nowhere else: nothing downstream re-reads the framing.
        //
        // A WebSocket handshake is validated too — a caller that sent a
        // `Content-Length` it does not match is rejected like any other — but it
        // carries no body, so its declared length is never forwarded and never
        // audited as a size.
        let declared = guards::validate_body_headers(&request.headers)
            .map_err(|error| error_context.apply(error))?;
        let declared_size = match handshake.is_some() {
            true => None,
            false => declared_length(declared),
        };
        audit.request_size = declared_size;

        let mut outbound_headers = transform_request_headers(
            &request.headers,
            upstream
                .spec
                .headers
                .as_ref()
                .and_then(|h| h.request.as_ref()),
            &endpoint,
            declared_size,
        );

        // `passthrough: none` drops every inbound header, and `Connection` /
        // `Upgrade` are hop-by-hop in every mode; a handshake needs both back, so
        // it is re-instated after the policy and the operator's rules. The
        // plugin chain then still sees the handshake headers, which is what lets
        // an auth plugin add its own credential to an upgraded request too.
        if handshake.is_some() {
            restore_websocket_handshake(&mut outbound_headers, &request.headers);
        }

        if let Some(hook) = self.hooks.plugins.as_ref() {
            hook.on_request(&context, &mut outbound_headers)
                .await
                .map_err(|error| error_context.apply(error))?;
        }

        let uri = forwarded_uri(&endpoint, &matched.forwarded_path, &request.query)?;
        // The size guard watches the body that is forwarded. A handshake has
        // none — it is sent empty — so there is nothing for the guard to check,
        // and reading the inbound body's size hint would be measuring bytes the
        // gateway never forwards.
        if handshake.is_none() {
            guards::check_declared_size(declared, || {
                let hint = request.body.size_hint();
                // Only an exact, known size can be checked before forwarding.
                match hint.upper() {
                    Some(upper) if upper == hint.lower() => Some(upper),
                    _ => None,
                }
            })
            .map_err(|error| error_context.apply(error))?;
        }
        let request_path = request.request_path.clone();
        // The guard watches the outbound body stream; a rule it breaks can only
        // surface as a transport failure, so it reports through `guard` and the
        // error is raised here, with its own status and type (see `forward`).
        let guard = BodyGuard::default();
        let outbound = http::Request::builder()
            .method(request.method.clone())
            .uri(uri)
            .body(match handshake {
                // RFC 6455 §4.1: a handshake request carries no body.
                Some(_) => Body::empty(),
                None => Body::new(guarded_body(request.body, declared, guard.clone())),
            })
            .map(|mut outbound| {
                // The transformed header map *is* the outbound header set: the
                // passthrough policy, the configured rules, `Host` and the
                // framing header were all decided above.
                *outbound.headers_mut() = outbound_headers;
                outbound
            })
            .map_err(|error| {
                OagwError::internal(format!("proxy request could not be framed: {error}"))
            })?;

        // `phase = "upstream"` is exactly the leg `proxy_timeout_secs` bounds:
        // measured here, around the outbound call, so a slow plugin or guard
        // cannot be booked against the upstream (see `metrics`).
        let response = match self.forward(outbound, &upstream.alias, &route_path).await {
            Ok(response) => response,
            Err(error) => {
                // The body guard may have failed the request mid-flight; that
                // is the actual cause, not the transport symptom it produced.
                return Err(match guard.take() {
                    Some(guarded) => error_context.apply(guarded),
                    None => error_context.apply(error),
                });
            }
        };

        // The guard can also fail a body *after* the headers arrived (the
        // upstream answered while we were still streaming): what it captured is
        // still the real outcome, and the response is never passed through.
        if let Some(guarded) = guard.take() {
            return Err(error_context.apply(guarded));
        }

        // An agreed upgrade is not an ordinary response: the socket has to come
        // out of it before the response is rendered, and what the caller gets
        // back is the gateway's own handshake, not the upstream's.
        if let Some(upgrade) = handshake
            && response.status() == StatusCode::SWITCHING_PROTOCOLS
        {
            // The accept the upstream must answer with (RFC 6455 §4.2.2), derived
            // here, where the caller's request headers are still in hand. The key
            // travelled to the upstream verbatim, so this is the one value that
            // proves the upstream agreed to *this* handshake — and tungstenite
            // will never check it on its own, because the gateway builds the
            // upstream leg with `from_raw_socket`, which declares the handshake
            // already complete.
            let expected_accept = request
                .headers
                .get(http::header::SEC_WEBSOCKET_KEY)
                .and_then(|key| key.to_str().ok())
                .map(crate::streaming::expected_accept);

            return self
                .switch_protocols(
                    response,
                    &upstream,
                    &context,
                    request_path,
                    expected_accept,
                    cors_headers,
                    rate_limit_headers,
                    upgrade,
                )
                .await;
        }

        audit.response_size = response_size(&response);

        Ok(self
            .respond(
                response,
                &upstream,
                &context,
                request_path,
                cors_headers,
                rate_limit_headers,
            )
            .await)
    }

    /// Send the request and map transport failures onto the error surface.
    ///
    /// The future resolves when the upstream *headers* arrive, so
    /// `proxy_timeout_secs` bounds connect + send + time-to-first-byte; the
    /// body then streams without a deadline.
    async fn forward(
        &self,
        request: http::Request<Body>,
        host: &str,
        route: &str,
    ) -> Result<http::Response<Body>, OagwError> {
        let started = Instant::now();
        let attempt =
            tokio::time::timeout(self.config.proxy_timeout(), self.client.request(request));

        let result = match attempt.await {
            Ok(Ok(response)) => Ok(response.map(Body::new)),
            Ok(Err(error)) => Err(transport_error(error, self.config.proxy_timeout())),
            Err(_elapsed) => Err(OagwError::connection_timeout(format!(
                "the upstream did not respond within {}s",
                self.config.proxy_timeout_secs
            ))
            .with_extension(
                "timeout_seconds",
                serde_json::json!(self.config.proxy_timeout_secs),
            )),
        };

        // A timeout and a transport failure are measurements of the upstream leg
        // too, so they are recorded as well: an upstream that is slow to *fail*
        // is exactly what an operator needs to see in the histogram.
        self.metrics
            .request_duration(host, route, RequestPhase::Upstream, started.elapsed());
        result
    }

    /// Build the response returned to the caller.
    ///
    /// Every upstream response — including 4xx and 5xx — is passed through with
    /// its status, its body and `X-OAGW-Error-Source: upstream` (ADR-0007):
    /// the gateway must not rewrite an upstream payload into a problem
    /// document, because that would hide what the upstream actually said.
    ///
    /// `cors_headers` are the headers the CORS policy computed for this request
    /// (ADR-0004); they are added *here*, after the upstream answered, so the
    /// upstream never sees or produces them.
    ///
    /// `rate_limit_headers` are the budget state of the caller's bucket
    /// (ADR-0003 "Response Headers"), for the same reason and never forwarded.
    async fn respond(
        &self,
        response: http::Response<Body>,
        upstream: &Upstream,
        context: &ProxyContext,
        request_path: String,
        cors_headers: HeaderMap,
        rate_limit_headers: HeaderMap,
    ) -> axum::response::Response {
        let (mut parts, body) = response.into_parts();

        if let Err(error) = self
            .stamp_response_headers(
                &mut parts.headers,
                upstream,
                context,
                cors_headers,
                rate_limit_headers,
            )
            .await
        {
            // A failure this late is still a gateway error for *this* request, so
            // it carries the same correlation id the audit record logs; the
            // request-path errors were stamped by `ErrorContext::apply`, and this
            // is the response-phase equivalent.
            return gateway_error(request_path, context.request_id.clone(), error);
        }

        axum::response::Response::from_parts(parts, body)
    }

    /// The header treatment every upstream answer receives, `101` included.
    ///
    /// Split out of [`Self::respond`] so the switched-protocol path can apply it
    /// to a response it takes a socket out of: an upgraded `101` is an upstream
    /// answer like any other, so ADR-0007's marker, the CORS answer and the
    /// caller's budget state reach it too, and the plugin chain is called with
    /// it.
    ///
    /// # Errors
    /// A response-phase plugin failure, which the caller renders as a gateway
    /// error for the same request.
    async fn stamp_response_headers(
        &self,
        headers: &mut HeaderMap,
        upstream: &Upstream,
        context: &ProxyContext,
        cors_headers: HeaderMap,
        rate_limit_headers: HeaderMap,
    ) -> Result<(), OagwError> {
        transform_response_headers(
            headers,
            upstream
                .spec
                .headers
                .as_ref()
                .and_then(|h| h.response.as_ref()),
        );

        if let Some(hook) = self.hooks.plugins.as_ref() {
            hook.on_response(context, headers).await?;
        }
        for (name, value) in cors_headers.iter().chain(rate_limit_headers.iter()) {
            headers.insert(name, value.clone());
        }

        headers.insert(
            error_source_header_name(),
            HeaderValue::from_static(ERROR_SOURCE_UPSTREAM),
        );

        Ok(())
    }

    /// Take the upstream's socket out of an agreed `101` and splice it onto the
    /// caller's (PRD §5.4 `cpt-cf-oagw-fr-streaming`, ADR-0007).
    ///
    /// The caller's handshake is signed *here*, from the caller's own
    /// `Sec-WebSocket-Key`, so the handshake it sees is this gateway's. Before it
    /// is signed, the upstream's own answer is verified against that same key
    /// (RFC 6455 §4.2.2, [`crate::streaming::expected_accept`]): `from_raw_socket`
    /// declares the upstream leg's handshake complete without tungstenite ever
    /// checking it, so this is the one place a non-conformant upstream can be
    /// stopped from getting a `101` countersigned.
    ///
    /// The upstream's `101` headers that are not framing are still passed through
    /// — including the subprotocol the upstream picked, which is echoed through
    /// `set_selected_protocol` so the choice is both on the wire and visible to
    /// the splice — and the ADR-0007 marker and the policy headers are stamped
    /// exactly as they are on any other upstream response.
    ///
    /// `expected_accept` is the accept derived from the caller's key, computed by
    /// the caller of this method while it still held the request headers. `None`
    /// means the gateway never had a key to derive one from, which the transport
    /// prevents (the extractor rejects a handshake without one) and which is
    /// therefore treated as unverifiable rather than as a pass.
    ///
    /// `proxy_timeout_secs` bounds only the header phase, which has already
    /// ended: [`Self::forward`] resolved before this was called, and nothing
    /// below holds a deadline. The spliced connection lives as long as the two
    /// peers do.
    ///
    /// # Errors
    /// An upstream `101` that does not carry the accept the caller's key derives,
    /// or carries none at all: the `101` has not reached the caller yet, so this
    /// is a gateway error document and not a post-upgrade socket teardown
    /// (ADR-0007). Nothing else here is an error — once the handshake is signed,
    /// a failure is a closed socket, not a document.
    #[allow(clippy::too_many_arguments)]
    async fn switch_protocols(
        &self,
        response: http::Response<Body>,
        upstream: &Upstream,
        context: &ProxyContext,
        request_path: String,
        expected_accept: Option<String>,
        cors_headers: HeaderMap,
        rate_limit_headers: HeaderMap,
        upgrade: WebSocketUpgrade,
    ) -> Result<axum::response::Response, OagwError> {
        let (mut parts, _) = response.into_parts();

        // The accept is checked before the socket is claimed and before anything
        // is stamped: an upstream that cannot prove it agreed to the protocol
        // gets no headers stamped, no plugin chain run and no handshake signed.
        if let Some(accepted) = expected_accept.as_deref() {
            let offered = parts
                .headers
                .get(http::header::SEC_WEBSOCKET_ACCEPT)
                .map(|value| value.as_bytes());
            let verified = offered.is_some_and(|offered| offered == accepted.as_bytes());
            if !verified {
                // The detail names the *fact*, never a header value: the accept
                // is derived from the caller's key and the key is not a secret,
                // but a value this gateway did not compute is still not ours to
                // repeat.
                let detail = match offered {
                    Some(_) => {
                        "the upstream's Sec-WebSocket-Accept does not match the one the \
                                caller's key derives, so its handshake cannot be signed"
                    }
                    None => "the upstream's 101 carries no Sec-WebSocket-Accept",
                };
                return Err(unresolved_handshake(
                    context,
                    request_path,
                    OagwError::downstream_error(detail),
                ));
            }
        }

        // The upgrade handle is claimed before anything else: it is the only
        // reference to the socket hyper is holding for this response.
        //
        // This arm is defensive: hyper's client puts an `OnUpgrade` extension on
        // every `101` it reads off a socket, whatever the request asked for, so a
        // `101` that reaches this method always carries one. There is no transport
        // that yields a `101` without it — which is why the branch below does not
        // have a test of its own, and why it must stay: `execute` routes here on
        // the status code alone, and a future upstream transport (HTTP/2 extended
        // `CONNECT`, a pooled connection that answers differently) is exactly the
        // kind of change that would otherwise turn a missing socket into a
        // `101` the caller waits on forever.
        let Some(pending) = parts.extensions.remove::<hyper::upgrade::OnUpgrade>() else {
            return Err(unresolved_handshake(
                context,
                request_path,
                OagwError::downstream_error(
                    "the upstream agreed to switch protocols but did not hand over a connection",
                ),
            ));
        };

        if let Err(error) = self
            .stamp_response_headers(
                &mut parts.headers,
                upstream,
                context,
                cors_headers,
                rate_limit_headers,
            )
            .await
        {
            // A response-phase failure is reported the way [`Self::respond`]
            // reports it: the document is the answer, and it is rendered here
            // rather than raised, because the request has already been answered
            // by an upstream.
            return Ok(gateway_error(
                request_path,
                context.request_id.clone(),
                error,
            ));
        }
        // Framing the gateway's own HTTP stack owns is not the upstream's to
        // dictate, and an extension the splice cannot honour is never echoed.
        strip_switched_protocol_framing(&mut parts.headers);
        // The subprotocol is echoed through the gateway's handshake, so it is
        // not also appended below.
        let protocol = parts.headers.remove(http::header::SEC_WEBSOCKET_PROTOCOL);
        let forwarded = parts.headers;

        let mut upgrade = upgrade;
        if let Some(protocol) = protocol {
            upgrade.set_selected_protocol(protocol);
        }

        // Copied out of `context`, which the spawned task outlives: only the
        // correlation id travels into the spliced session, and nothing else the
        // context holds is needed there (and must not be — a proxied WebSocket
        // is the caller's channel, not the request's).
        let request_id = context.request_id.clone();

        let mut response = upgrade
            .on_failed_upgrade({
                let request_id = request_id.clone();
                move |error| {
                    // The default would swallow this; a handshake the gateway
                    // offered and could not complete is worth one line, and no
                    // payload.
                    tracing::warn!(
                        target: "oagw.audit",
                        event = "oagw.ws_upgrade_failed",
                        request_id = %request_id,
                        error = %error,
                    );
                }
            })
            .on_upgrade(move |client| async move {
                // The upstream leg is established here, in the task that owns it,
                // rather than in the request path: the `101` must reach the
                // caller as soon as it is known, whether or not the socket has
                // arrived yet.
                let upgraded = match pending.await {
                    Ok(upgraded) => TokioIo::new(upgraded),
                    Err(error) => {
                        tracing::warn!(
                            target: "oagw.audit",
                            event = "oagw.ws_upgrade_failed",
                            request_id = %request_id,
                            error = %error,
                        );
                        return;
                    }
                };
                let upstream_socket =
                    WebSocketStream::from_raw_socket(upgraded, Role::Client, None).await;
                crate::streaming::splice(client, upstream_socket, &request_id).await;
            });

        for (name, value) in forwarded.iter() {
            // The gateway signs its own handshake: `Sec-WebSocket-Accept` is
            // derived from the same key, so the value is identical, but the one
            // the caller verifies is the one this gateway computed.
            if name == http::header::SEC_WEBSOCKET_ACCEPT {
                continue;
            }
            response.headers_mut().append(name, value.clone());
        }

        Ok(response)
    }

    /// Endpoint selection with the process-wide round-robin counters.
    ///
    /// Returns the endpoint *and* how it was chosen, because that is a fact
    /// about the request the routing metrics need (`selection_method`, §4.2)
    /// and `select` is the only place that knows it.
    fn select(
        &self,
        upstream: Arc<Upstream>,
        target_host: Option<String>,
    ) -> Result<Selected, OagwError> {
        let requires_target_host = self.requires_target_host(&upstream);

        // Decided *before* the choice is made, so the report matches the branch
        // that actually ran; `requires_target_host` can only turn a round-robin
        // selection into an error, never the other way round.
        let method = match target_host.as_deref() {
            Some(_) => EndpointSelectionMethod::ExplicitHeader,
            None if upstream.endpoints().len() > 1 => EndpointSelectionMethod::RoundRobin,
            None => EndpointSelectionMethod::Default,
        };

        let endpoint = if let Some(target_host) = target_host.as_deref() {
            routing::select_endpoint_with_policy(
                &upstream,
                requires_target_host,
                Some(target_host),
                &mut || 0,
            )
            .cloned()
            .map_err(|error| error.with_extension("upstream_id", json_id(upstream.as_ref())))?
        } else {
            let counter = self
                .round_robin
                .entry(upstream.id)
                .or_insert_with(|| Arc::new(AtomicUsize::new(0)))
                .clone();
            let turn = counter.fetch_add(1, Ordering::Relaxed);
            drop(counter);

            routing::select_endpoint_with_policy(&upstream, requires_target_host, None, &mut || {
                turn
            })
            .cloned()
            .map_err(|error| error.with_extension("upstream_id", json_id(&upstream)))?
        };

        Ok(Selected { endpoint, method })
    }

    /// Whether proxying `upstream` needs `X-OAGW-Target-Host`, memoized per
    /// upstream id.
    ///
    /// [`Upstream::requires_target_host`] re-derives the pool's public-suffix
    /// alias, and this is called on every request, so the answer is cached and
    /// invalidated by `updated_at`: a configuration replace recomputes it, and
    /// a record that was never replaced keeps its first (equally valid) answer.
    fn requires_target_host(&self, upstream: &Upstream) -> bool {
        self.requires_target_host
            .entry(upstream.id)
            .and_modify(|cached| {
                if cached.0 != upstream.updated_at {
                    *cached = (upstream.updated_at, upstream.requires_target_host());
                }
            })
            .or_insert_with(|| (upstream.updated_at, upstream.requires_target_host()))
            .1
    }

    /// The ancestor chain of `tenant_id`, nearest first and including it.
    async fn tenant_chain(&self, security: &SecurityContext, tenant_id: Uuid) -> Vec<Uuid> {
        match self.hierarchy.as_ref() {
            Some(hierarchy) => hierarchy.chain(security, tenant_id).await,
            None => vec![tenant_id],
        }
    }

    /// Fold the rate limit that applies to this request (ADR-0003 "3.
    /// Inheritance"): the strictest of the enforced ancestors' limits, the
    /// upstream's own and the route's.
    ///
    /// `None` when nothing in that set configures a limit, which means the
    /// request is not throttled at all.
    fn effective_rate_limit(
        &self,
        chain: &[Uuid],
        upstream: &Upstream,
        route: Option<&Route>,
    ) -> Option<EffectiveRateLimit> {
        crate::domain::policy::rate_limit::effective_rate_limit(
            chain,
            upstream,
            route,
            |tenant, alias| self.upstreams.get_by_alias(tenant, alias),
        )
    }

    /// Fold the CORS configuration that applies to this request (ADR-0004
    /// "Effective Configuration"): the selected upstream's own, amended by the
    /// ancestor upstreams that share its alias.
    ///
    /// `RouteSpec` declares no `cors` field in the schema this crate is bound
    /// to, so a route contributes nothing; the seam keeps the same shape as
    /// [`Self::effective_rate_limit`], so a route layer can be added without
    /// touching the callers.
    ///
    /// `None` when neither the upstream nor any enforced ancestor configures
    /// CORS, which means the request is validated like any other and its
    /// response carries no CORS header.
    fn effective_cors(&self, chain: &[Uuid], upstream: &Upstream) -> Option<CorsConfig> {
        crate::domain::policy::cors::effective_cors(chain, upstream, |tenant, alias| {
            self.upstreams.get_by_alias(tenant, alias)
        })
    }
}

/// The value of a request header, if it is a valid UTF-8 string.
fn header_value(headers: &HeaderMap, name: &str) -> Option<String> {
    headers
        .get(name)
        .and_then(|value| value.to_str().ok())
        .map(str::to_owned)
}

/// The outbound connection pool (DESIGN §3.5 "Forwarding").
///
/// `HttpConnector` dials plaintext; no TLS client is configured in this slice,
/// so a `https` endpoint is reported as a 502 rather than silently downgraded.
fn outbound_client() -> OutboundClient {
    Client::builder(TokioExecutor::new())
        .pool_timer(TokioTimer::new())
        .build_http()
}

/// The declared body length of the request, for the `Content-Length` header of
/// the forwarded request.
///
/// `None` for a chunked or unknown-length body: hyper then frames the forwarded
/// request itself.
///
/// This is a *projection* of an already-validated [`DeclaredLength`], not a
/// second opinion: the one place the framing is read is
/// [`guards::validate_body_headers`], whose error the caller raises, so a
/// malformed or conflicting `Content-Length` can neither be silently dropped
/// into a `None` nor validated twice.
fn declared_length(declared: DeclaredLength) -> Option<u64> {
    match declared {
        DeclaredLength::Exact(length) => Some(length),
        DeclaredLength::Chunked | DeclaredLength::Unknown => None,
    }
}

/// A slot for an error that can only be discovered while streaming the
/// outbound body.
///
/// The body guard runs *inside* the outbound request; hyper reports the failure
/// it causes as a transport error, which would otherwise be mislabeled as a
/// 502. The guard records the real [`OagwError`] here and [`Self::take`]
/// raises it instead of the transport symptom.
#[derive(Debug, Clone, Default)]
struct BodyGuard {
    error: Arc<OnceLock<OagwError>>,
}

impl BodyGuard {
    /// Record `error` as the reason the body could not be forwarded.
    fn capture(&self, error: OagwError) {
        let _ = self.error.set(error);
    }

    /// The captured error, if any.
    fn take(&self) -> Option<OagwError> {
        self.error.get().cloned()
    }
}

/// Stream `body` through the length guards.
///
/// The request body is never buffered: each frame is counted and checked
/// against the ceiling and the declared `Content-Length` as it passes through,
/// so an oversized or lying body fails mid-flight instead of after a full read.
/// The error that stops the stream is also recorded in `guard`, because the
/// transport only sees the aborted write.
fn guarded_body(body: Body, declared: DeclaredLength, guard: BodyGuard) -> Body {
    // `Box::pin` gives the stream an owned, `'static` handle on the body.
    let mut body = Box::pin(body);
    let observed = AtomicUsize::new(0);

    let counted = stream::poll_fn(move |context| {
        let Some(frame) = std::task::ready!(body.as_mut().poll_frame(context)) else {
            return std::task::Poll::Ready(None);
        };

        let frame = match frame {
            Ok(frame) => frame,
            Err(error) => {
                let error = OagwError::downstream_error(format!(
                    "reading the request body failed: {error}"
                ));
                guard.capture(error.clone());
                return std::task::Poll::Ready(Some(Err(error)));
            }
        };

        // Trailers are dropped: they are hop-by-hop framing, not payload.
        let Some(data) = frame.data_ref() else {
            return std::task::Poll::Ready(None);
        };

        let seen = observed.fetch_add(data.len(), Ordering::Relaxed) + data.len();
        if let Err(error) = guards::check_observed_length(declared, seen as u64) {
            guard.capture(error.clone());
            return std::task::Poll::Ready(Some(Err(error)));
        }

        std::task::Poll::Ready(Some(Ok(data.clone())))
    });

    Body::from_stream(counted)
}

/// The URI forwarded to `endpoint`.
///
/// # Errors
/// [`OagwErrorKind::DownstreamError`](crate::error::OagwErrorKind) when the
/// endpoint scheme cannot be dialed, or
/// [`OagwErrorKind::ValidationError`](crate::error::OagwErrorKind) when the
/// path or query cannot be parsed as a URI.
fn forwarded_uri(endpoint: &Endpoint, forwarded_path: &str, query: &str) -> Result<Uri, OagwError> {
    if endpoint.scheme != Scheme::Http {
        return Err(unsupported_scheme_error(endpoint.scheme));
    }

    let authority = headers::host_authority(endpoint);
    let path_and_query = match query.is_empty() {
        true => forwarded_path.to_owned(),
        false => format!("{forwarded_path}?{query}"),
    };

    Uri::builder()
        .scheme("http")
        .authority(authority.as_str())
        .path_and_query(path_and_query.as_str())
        .build()
        .map_err(|error| {
            OagwError::validation(format!("the proxied request is not a valid URI: {error}"))
        })
}

/// Parse the query string into the parameter names the route allowlist checks.
///
/// Repeated parameters are reported once; the value is irrelevant to the
/// allowlist.
fn query_keys(query: &str) -> Vec<String> {
    form_urlencoded::parse(query.as_bytes())
        .map(|(key, _)| key.into_owned())
        .collect()
}

/// The `X-OAGW-Target-Host` value of the request, if any.
fn target_host(headers: &HeaderMap) -> Option<String> {
    headers
        .get(TARGET_HOST_HEADER)
        .and_then(|value| value.to_str().ok())
        .map(str::to_owned)
}

/// Map a hyper transport failure onto the OAGW error surface.
fn transport_error(error: hyper_util::client::legacy::Error, timeout: Duration) -> OagwError {
    transport_failure(error.is_connect(), error.to_string(), timeout)
}

/// The error for an outbound transport failure.
///
/// A failure *establishing* the connection means the upstream link is down, not
/// that the upstream answered badly: it is a retriable 503
/// (`LinkUnavailable`, DESIGN §3.3). A failure mid-request — the connection
/// broke while the request or response was in flight — stays a 502, because the
/// caller cannot tell whether the upstream acted on the request.
fn transport_failure(connect: bool, cause: String, timeout: Duration) -> OagwError {
    if connect {
        return OagwError::link_unavailable(format!(
            "the upstream connection could not be established: {cause}"
        ))
        .with_retry_after_secs(CONNECT_RETRY_AFTER_SECS);
    }

    OagwError::downstream_error(format!(
        "the upstream request failed: {cause} ({timeout:?} budget)"
    ))
}

/// `Retry-After` guidance for a connection that could not be established: a
/// short, client-friendly backoff for a link that is usually back within a
/// second.
const CONNECT_RETRY_AFTER_SECS: u64 = 1;

/// The 404 for an alias the caller cannot resolve.
///
/// `alias`, `instance` and `trace_id` are attached by [`ErrorContext::apply`].
fn not_found(alias: &str) -> OagwError {
    OagwError::upstream_not_found(format!(
        "no enabled upstream with alias '{alias}' is reachable for this tenant"
    ))
}

/// The 503 for a disabled upstream.
fn disabled_error(upstream: &Upstream) -> OagwError {
    OagwError::link_unavailable(format!("upstream '{}' is disabled", upstream.alias))
        .with_extension("upstream_id", json_id(upstream))
        .with_retry_after_secs(30)
}

/// The `upstream_id` extension value of an upstream.
fn json_id(upstream: &Upstream) -> serde_json::Value {
    serde_json::json!(upstream.gts_id())
}

/// Request identity attached to a gateway error.
struct ErrorContext {
    request_path: String,
    request_id: String,
    alias: String,
    upstream: Option<Arc<Upstream>>,
    endpoint: Option<Endpoint>,
    forwarded_path: Option<String>,
}

impl ErrorContext {
    /// Add the request identity a gateway error must carry (DESIGN §3.3).
    ///
    /// Every gateway-produced error is stamped with the request's correlation
    /// id, so the problem document's `trace_id` joins it to its audit record.
    fn apply(&self, mut error: OagwError) -> OagwError {
        error = error
            .with_instance(self.request_path.clone())
            .with_trace_id(self.request_id.clone())
            .with_extension("alias", serde_json::json!(self.alias));
        if let Some(upstream) = self.upstream.as_ref() {
            error = error.with_extension("upstream_id", json_id(upstream.as_ref()));
        }
        if let Some(endpoint) = self.endpoint.as_ref() {
            error = error.with_extension("host", serde_json::json!(endpoint.host));
        }
        if let Some(path) = self.forwarded_path.as_ref() {
            error = error.with_extension("path", serde_json::json!(path));
        }
        error
    }
}

/// Who sent the request: the part of the audit record known before it is
/// resolved.
struct RequestIdentity {
    request_id: String,
    method: String,
    alias: String,
    path: String,
    subject_id: Uuid,
}

/// What one proxy request did, as far as it got (DESIGN §4.3 audit fields).
///
/// The execution fills it in as it progresses, so a *rejected* request is
/// logged with exactly the context it reached: an unknown alias reports no
/// upstream, a connect failure reports the endpoint it failed on.
#[derive(Debug, Default)]
struct RequestAudit {
    tenant_id: Option<Uuid>,
    upstream_id: Option<Uuid>,
    upstream_alias: Option<String>,
    route_id: Option<Uuid>,
    /// The matched route's configured path pattern, as the metrics label
    /// `http.route` (never the raw request path; see `metrics`).
    route_pattern: Option<String>,
    endpoint_host: Option<String>,
    endpoint_port: Option<u16>,
    /// How the endpoint was chosen, as the metrics label `selection_method`.
    selection_method: Option<EndpointSelectionMethod>,
    request_size: Option<u64>,
    response_size: Option<u64>,
}

/// The endpoint [`DataPlaneService::select` chose, and how it chose it.
#[derive(Debug, Clone)]
struct Selected {
    endpoint: Endpoint,
    method: EndpointSelectionMethod,
}

/// The configured path pattern a route matched on.
///
/// [`RouteMatch`](crate::domain::types::RouteMatch) carries one of an HTTP or a
/// gRPC match; the pattern of an HTTP match is its `path`, and of a gRPC match
/// the fully qualified service it names. Both are configuration, so either is a
/// bounded metric label; a route with neither cannot exist (the wire schema
/// requires exactly one).
fn route_pattern(route: &Route) -> String {
    match route.spec.match_rules.http.as_ref() {
        Some(http) => http.path.clone(),
        None => match route.spec.match_rules.grpc.as_ref() {
            Some(grpc) => grpc.service.clone(),
            None => String::new(),
        },
    }
}

/// The `Content-Length` of a response, when its framing declares one.
///
/// Streaming responses are not buffered to be counted: the audit record reports
/// the size only when the upstream announced it.
fn response_size(response: &http::Response<Body>) -> Option<u64> {
    let length = response.headers().get(http::header::CONTENT_LENGTH)?;
    let length = length.to_str().ok()?;
    length.parse().ok()
}

/// Render a gateway-generated error response (ADR-0007: source `gateway`).
///
/// `request_id` is the correlation id of the request the failure belongs to: it
/// becomes the problem document's `trace_id`, so a response-phase failure joins
/// the same audit record as a request-phase one (DESIGN §3.3).
///
/// The error's *kind* is inserted into the response's extensions, next to that
/// `trace_id`. This is how a gateway error that was rendered instead of raised
/// (a failure after the upstream answered, see [`DataPlaneService::respond`])
/// still reports its kind to [`DataPlaneService::record_outcome`] and
/// [`log_request`], which read the final outcome: without it such a request
/// would be counted in `oagw_requests_total` and never in `oagw_errors_total`
/// (DESIGN §4.2). The extension is not rendered — no header and no body member
/// comes from it.
fn gateway_error(
    request_path: String,
    request_id: String,
    error: OagwError,
) -> axum::response::Response {
    let kind = error.kind();
    let mut response = error
        .with_instance(request_path)
        .with_trace_id(request_id)
        .to_response();
    response.extensions_mut().insert(kind);
    let stamped = gateway_error_headers();
    for name in stamped.keys() {
        if let Some(value) = stamped.get(name) {
            response.headers_mut().insert(name, value.clone());
        }
    }
    response
}

/// The gateway error of a request whose alias and upstream were already resolved,
/// as an [`OagwError`] rather than a rendered response.
///
/// `switch_protocols` reports its failures through `Err`, so the wrapper logs and
/// records them like any other gateway decision and the transport renders the
/// document. What it loses on the way is the identity `gateway_error` attaches
/// before rendering, so it is attached here, from the context that is still in
/// hand — the same fields [`ErrorContext::apply`] writes for a request that got
/// as far as resolving its upstream.
fn unresolved_handshake(
    context: &ProxyContext,
    request_path: String,
    error: OagwError,
) -> OagwError {
    error
        .with_instance(request_path)
        .with_trace_id(context.request_id.clone())
        .with_extension("alias", serde_json::json!(context.alias))
        .with_extension("upstream_id", json_id(context.upstream.as_ref()))
}

/// The error kind of a request's outcome, when the gateway rejected it.
///
/// `None` when it did not: an upstream answer keeps its own status and is never
/// a gateway error (ADR-0007). An `Err` carries its kind with it; a gateway
/// error that was *rendered* instead — a response-phase failure — carries it in
/// the response's extensions, where [`gateway_error`] put it. Reading both forms
/// through one function is what keeps the §4.2 counter and the §4.3 audit
/// record in agreement for the same request.
fn outcome_error_kind(
    result: &Result<axum::response::Response, OagwError>,
) -> Option<OagwErrorKind> {
    match result {
        Ok(response) => response.extensions().get::<OagwErrorKind>().copied(),
        Err(error) => Some(error.kind()),
    }
}

/// Write the ONE audit record of a proxy request (DESIGN §4.3).
///
/// Success and failure both land here. The record carries request identity
/// (`request_id`, `tenant_id`, `principal_id`), what was resolved (`alias`,
/// `upstream_id`, `route_id`, `host`), the outcome (`status`, `error_type`) and
/// the cost (`duration_ms`, `request_size`, `response_size`). It carries **no**
/// body, no query string, no header and no credential: the query and the
/// headers are where caller data lives, and the path logged is the stripped
/// path only.
///
/// A field the request never reached (the `upstream_id` of an unknown alias,
/// the `host` of a request rejected before endpoint selection) is logged as an
/// empty string, and a size the framing did not declare is logged as `0`: the
/// proxy streams, so it never buffers a body just to count it.
fn log_request(
    identity: &RequestIdentity,
    audit: &RequestAudit,
    result: &Result<axum::response::Response, OagwError>,
    duration: Duration,
) {
    let status = match result {
        Ok(response) => response.status().as_u16(),
        Err(error) => error.status().as_u16(),
    };
    // The same read `record_outcome` makes, so a gateway error that was rendered
    // rather than raised still names its type here (DESIGN §4.3 "What is
    // Logged").
    let error_type =
        outcome_error_kind(result).map_or_else(String::new, |kind| kind.gts_type_id().to_owned());
    let upstream_id = audit
        .upstream_id
        .map_or_else(String::new, |id| id.to_string());
    let route_id = audit.route_id.map_or_else(String::new, |id| id.to_string());
    let tenant_id = audit
        .tenant_id
        .map_or_else(String::new, |id| id.to_string());
    let host = match (audit.endpoint_host.as_deref(), audit.endpoint_port) {
        (Some(host), Some(port)) => format!("{host}:{port}"),
        (Some(host), None) => host.to_owned(),
        _ => String::new(),
    };

    macro_rules! audit_record {
        ($level:ident) => {
            tracing::$level!(
                target: "oagw.audit",
                event = "oagw.proxy",
                request_id = %identity.request_id,
                tenant_id = %tenant_id,
                principal_id = %identity.subject_id,
                method = %identity.method,
                alias = %identity.alias,
                upstream_id = %upstream_id,
                route_id = %route_id,
                host = %host,
                path = %identity.path,
                status = status,
                duration_ms = duration.as_millis() as u64,
                request_size = audit.request_size.unwrap_or(0),
                response_size = audit.response_size.unwrap_or(0),
                error_type = %error_type,
            );
        };
    }

    // DESIGN §4.3 "Log Levels": `ERROR` for upstream failures, timeouts and
    // auth failures, `WARN` for rate limits, validation rejections and the
    // other 4xx, `INFO` for the requests the gateway served or passed through.
    if status >= 500 || status == 401 {
        audit_record!(error);
    } else if status >= 400 {
        audit_record!(warn);
    } else {
        audit_record!(info);
    }
}

