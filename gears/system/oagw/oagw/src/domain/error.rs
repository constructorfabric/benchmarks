//! Domain error type and its mapping onto the documented problem documents.
//!
//! Every gateway-generated error is one of these, rendered by
//! [`crate::api::rest::error::GatewayProblem`] as `application/problem+json`
//! with the GTS `type` identifier from `docs/DESIGN.md` and the
//! `X-OAGW-Error-Source: gateway` header.

use crate::gts_helpers;

/// The error cases OAGW can produce, one per row of the error table.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ErrorKind {
    /// General request or configuration validation failure.
    Validation,
    /// `X-OAGW-Target-Host` required but absent.
    MissingTargetHost,
    /// `X-OAGW-Target-Host` is not a bare host or IP.
    InvalidTargetHost,
    /// `X-OAGW-Target-Host` names no configured endpoint.
    UnknownTargetHost,
    /// Inbound authentication failed or is missing.
    AuthFailed,
    /// The caller is authenticated but lacks the required permission.
    Unauthorized,
    /// The caller is authenticated and permitted in general, but this
    /// particular action is not theirs to take.
    Forbidden,
    /// No route matches, or the alias resolves to nothing in scope.
    RouteNotFound,
    /// The requested management resource does not exist.
    ResourceNotFound,
    /// The derived or supplied alias is already taken in this tenant.
    AliasConflict,
    /// The resource is referenced by another resource.
    ResourceInUse,
    /// Deleting a plugin that is bound to a route.
    PluginInUse,
    /// A bound plugin identifier is not in the catalog.
    PluginNotFound,
    /// Request payload exceeds the configured limit.
    PayloadTooLarge,
    /// Rate limit exhausted.
    RateLimitExceeded,
    /// A referenced secret does not exist.
    SecretNotFound,
    /// Protocol-level failure talking to the upstream.
    Protocol,
    /// Upstream service error generated by the gateway itself.
    Downstream,
    /// Streaming connection aborted mid-flight.
    StreamAborted,
    /// Upstream link unavailable.
    LinkUnavailable,
    /// Circuit breaker open.
    CircuitBreakerOpen,
    /// Connection to the upstream timed out.
    ConnectionTimeout,
    /// Overall request timeout.
    RequestTimeout,
    /// Idle timeout on a stream.
    IdleTimeout,
    /// CORS: the origin is not allowed.
    CorsOriginNotAllowed,
    /// CORS: the method is not allowed.
    CorsMethodNotAllowed,
    /// Invalid gear configuration.
    Config,
    /// Anything else.
    Internal,
}

/// A domain error: which case it is plus a human-readable detail.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("{kind:?}: {detail}")]
pub struct DomainError {
    kind: ErrorKind,
    detail: String,
    retry_after_secs: Option<u64>,
}

impl DomainError {
    /// Build an error of `kind` with `detail`.
    #[must_use]
    pub const fn new(kind: ErrorKind, detail: String) -> Self {
        Self {
            kind,
            detail,
            retry_after_secs: None,
        }
    }

    /// Which case this is.
    #[must_use]
    pub const fn kind(&self) -> ErrorKind {
        self.kind
    }

    /// Human-readable explanation specific to this occurrence.
    #[must_use]
    pub fn detail(&self) -> &str {
        &self.detail
    }

    /// HTTP status for this case.
    #[must_use]
    pub const fn http_status(&self) -> http::StatusCode {
        match self.kind {
            ErrorKind::Validation
            | ErrorKind::MissingTargetHost
            | ErrorKind::InvalidTargetHost
            | ErrorKind::UnknownTargetHost
            | ErrorKind::CorsOriginNotAllowed
            | ErrorKind::CorsMethodNotAllowed => http::StatusCode::BAD_REQUEST,
            ErrorKind::AuthFailed | ErrorKind::Unauthorized => http::StatusCode::UNAUTHORIZED,
            ErrorKind::Forbidden => http::StatusCode::FORBIDDEN,
            ErrorKind::RouteNotFound | ErrorKind::ResourceNotFound => http::StatusCode::NOT_FOUND,
            ErrorKind::AliasConflict | ErrorKind::ResourceInUse | ErrorKind::PluginInUse => {
                http::StatusCode::CONFLICT
            }
            ErrorKind::PayloadTooLarge => http::StatusCode::PAYLOAD_TOO_LARGE,
            ErrorKind::RateLimitExceeded => http::StatusCode::TOO_MANY_REQUESTS,
            ErrorKind::SecretNotFound | ErrorKind::Config | ErrorKind::Internal => {
                http::StatusCode::INTERNAL_SERVER_ERROR
            }
            ErrorKind::Protocol | ErrorKind::Downstream | ErrorKind::StreamAborted => {
                http::StatusCode::BAD_GATEWAY
            }
            ErrorKind::LinkUnavailable
            | ErrorKind::CircuitBreakerOpen
            | ErrorKind::PluginNotFound => http::StatusCode::SERVICE_UNAVAILABLE,
            ErrorKind::ConnectionTimeout | ErrorKind::RequestTimeout | ErrorKind::IdleTimeout => {
                http::StatusCode::GATEWAY_TIMEOUT
            }
        }
    }

    /// GTS `type` identifier for this case.
    #[must_use]
    pub fn gts_type(&self) -> &'static str {
        match self.kind {
            ErrorKind::MissingTargetHost => gts_helpers::ERR_MISSING_TARGET_HOST,
            ErrorKind::InvalidTargetHost => gts_helpers::ERR_INVALID_TARGET_HOST,
            ErrorKind::UnknownTargetHost => gts_helpers::ERR_UNKNOWN_TARGET_HOST,
            ErrorKind::AuthFailed | ErrorKind::Unauthorized | ErrorKind::Forbidden => {
                gts_helpers::ERR_AUTH_FAILED
            }
            ErrorKind::RouteNotFound | ErrorKind::ResourceNotFound => {
                gts_helpers::ERR_ROUTE_NOT_FOUND
            }
            ErrorKind::AliasConflict | ErrorKind::ResourceInUse | ErrorKind::Validation => {
                gts_helpers::ERR_VALIDATION
            }
            ErrorKind::PluginInUse => gts_helpers::ERR_PLUGIN_IN_USE,
            ErrorKind::PayloadTooLarge => gts_helpers::ERR_PAYLOAD_TOO_LARGE,
            ErrorKind::RateLimitExceeded => gts_helpers::ERR_RATE_LIMIT_EXCEEDED,
            ErrorKind::SecretNotFound => gts_helpers::ERR_SECRET_NOT_FOUND,
            ErrorKind::Protocol => gts_helpers::ERR_PROTOCOL,
            ErrorKind::Downstream | ErrorKind::Config | ErrorKind::Internal => {
                gts_helpers::ERR_DOWNSTREAM
            }
            ErrorKind::StreamAborted => gts_helpers::ERR_STREAM_ABORTED,
            ErrorKind::LinkUnavailable => gts_helpers::ERR_LINK_UNAVAILABLE,
            ErrorKind::CircuitBreakerOpen => gts_helpers::ERR_CIRCUIT_BREAKER_OPEN,
            ErrorKind::PluginNotFound => gts_helpers::ERR_PLUGIN_NOT_FOUND,
            ErrorKind::ConnectionTimeout => gts_helpers::ERR_CONNECTION_TIMEOUT,
            ErrorKind::RequestTimeout => gts_helpers::ERR_REQUEST_TIMEOUT,
            ErrorKind::IdleTimeout => gts_helpers::ERR_IDLE_TIMEOUT,
            ErrorKind::CorsOriginNotAllowed => gts_helpers::ERR_CORS_ORIGIN_NOT_ALLOWED,
            ErrorKind::CorsMethodNotAllowed => gts_helpers::ERR_CORS_METHOD_NOT_ALLOWED,
        }
    }

    /// Human-readable summary, used as the problem `title`.
    #[must_use]
    pub fn title(&self) -> &'static str {
        match self.kind {
            ErrorKind::Validation => "Validation failed",
            ErrorKind::MissingTargetHost => "Target host required",
            ErrorKind::InvalidTargetHost => "Invalid target host",
            ErrorKind::UnknownTargetHost => "Unknown target host",
            ErrorKind::AuthFailed => "Authentication failed",
            ErrorKind::Unauthorized => "Not authorized",
            ErrorKind::Forbidden => "Forbidden",
            ErrorKind::RouteNotFound => "Route not found",
            ErrorKind::ResourceNotFound => "Resource not found",
            ErrorKind::AliasConflict => "Alias already in use",
            ErrorKind::ResourceInUse => "Resource in use",
            ErrorKind::PluginInUse => "Plugin in use",
            ErrorKind::PluginNotFound => "Plugin not found",
            ErrorKind::PayloadTooLarge => "Payload too large",
            ErrorKind::RateLimitExceeded => "Rate limit exceeded",
            ErrorKind::SecretNotFound => "Secret not found",
            ErrorKind::Protocol => "Protocol error",
            ErrorKind::Downstream => "Downstream error",
            ErrorKind::StreamAborted => "Stream aborted",
            ErrorKind::LinkUnavailable => "Upstream link unavailable",
            ErrorKind::CircuitBreakerOpen => "Circuit breaker open",
            ErrorKind::ConnectionTimeout => "Connection timeout",
            ErrorKind::RequestTimeout => "Request timeout",
            ErrorKind::IdleTimeout => "Idle timeout",
            ErrorKind::CorsOriginNotAllowed => "Origin not allowed",
            ErrorKind::CorsMethodNotAllowed => "Method not allowed",
            ErrorKind::Config => "Configuration error",
            ErrorKind::Internal => "Internal error",
        }
    }

    /// Whether a client may retry the request unchanged.
    #[must_use]
    pub const fn retriable(&self) -> bool {
        matches!(
            self.kind,
            ErrorKind::RateLimitExceeded
                | ErrorKind::LinkUnavailable
                | ErrorKind::CircuitBreakerOpen
                | ErrorKind::ConnectionTimeout
                | ErrorKind::RequestTimeout
                | ErrorKind::IdleTimeout
        )
    }

    /// `Retry-After` hint in seconds, when this case carries one.
    #[must_use]
    pub fn retry_after(&self) -> Option<u64> {
        self.retry_after_secs.or(match self.kind {
            ErrorKind::RateLimitExceeded
            | ErrorKind::ConnectionTimeout
            | ErrorKind::RequestTimeout
            | ErrorKind::IdleTimeout
            | ErrorKind::LinkUnavailable
            | ErrorKind::CircuitBreakerOpen => Some(1),
            _ => None,
        })
    }

    /// A validation failure.
    #[must_use]
    pub fn validation(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::Validation, detail.into())
    }

    /// A missing `X-OAGW-Target-Host`.
    #[must_use]
    pub fn missing_target_host(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::MissingTargetHost, detail.into())
    }

    /// A malformed `X-OAGW-Target-Host`.
    #[must_use]
    pub fn invalid_target_host(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::InvalidTargetHost, detail.into())
    }

    /// An `X-OAGW-Target-Host` outside the configured pool.
    #[must_use]
    pub fn unknown_target_host(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::UnknownTargetHost, detail.into())
    }

    /// Authentication failure.
    #[must_use]
    pub fn auth_failed(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::AuthFailed, detail.into())
    }

    /// Missing or insufficient permission.
    #[must_use]
    pub fn unauthorized(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::Unauthorized, detail.into())
    }

    /// An action the caller is not the one to take, even though they are
    /// authenticated and otherwise permitted.
    pub fn forbidden(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::Forbidden, detail.into())
    }

    /// No route matched.
    #[must_use]
    pub fn route_not_found(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::RouteNotFound, detail.into())
    }

    /// A management resource does not exist.
    #[must_use]
    pub fn not_found(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::ResourceNotFound, detail.into())
    }

    /// An alias collision.
    #[must_use]
    pub fn alias_conflict(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::AliasConflict, detail.into())
    }

    /// A resource referenced elsewhere.
    #[must_use]
    pub fn resource_in_use(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::ResourceInUse, detail.into())
    }

    /// A plugin bound to a route.
    #[must_use]
    pub fn plugin_in_use(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::PluginInUse, detail.into())
    }

    /// A binding whose plugin has no implementation.
    #[must_use]
    pub fn plugin_not_found(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::PluginNotFound, detail.into())
    }

    /// Rate limit exhausted, with a retry hint.
    #[must_use]
    pub fn rate_limit_exceeded(detail: impl Into<String>, retry_after_secs: u64) -> Self {
        Self::new(ErrorKind::RateLimitExceeded, detail.into()).with_retry_after(retry_after_secs)
    }

    /// A referenced secret is missing.
    #[must_use]
    pub fn secret_not_found(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::SecretNotFound, detail.into())
    }

    /// Protocol-level upstream failure.
    #[must_use]
    pub fn protocol(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::Protocol, detail.into())
    }

    /// Upstream service error.
    #[must_use]
    pub fn downstream(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::Downstream, detail.into())
    }

    /// Streaming connection aborted.
    #[must_use]
    pub fn stream_aborted(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::StreamAborted, detail.into())
    }

    /// Upstream link unavailable.
    #[must_use]
    pub fn link_unavailable(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::LinkUnavailable, detail.into())
    }

    /// The request payload exceeds the configured limit.
    #[must_use]
    pub fn payload_too_large(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::PayloadTooLarge, detail.into())
    }

    /// Connection timed out.
    #[must_use]
    pub fn connection_timeout(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::ConnectionTimeout, detail.into())
    }

    /// Overall request timed out.
    #[must_use]
    pub fn request_timeout(detail: impl Into<String>) -> Self {
        Self::new(ErrorKind::RequestTimeout, detail.into())
    }

    /// Attach a retry hint, carried in the error detail for rendering.
    #[must_use]
    pub const fn with_retry_after(mut self, secs: u64) -> Self {
        self.retry_after_secs = Some(secs);
        self
    }
}

impl From<anyhow::Error> for DomainError {
    fn from(err: anyhow::Error) -> Self {
        Self::new(ErrorKind::Internal, err.to_string())
    }
}

impl From<std::io::Error> for DomainError {
    fn from(err: std::io::Error) -> Self {
        Self::new(ErrorKind::Internal, err.to_string())
    }
}

impl axum::response::IntoResponse for DomainError {
    fn into_response(self) -> axum::response::Response {
        crate::api::rest::error::GatewayProblem::from(self).into_response()
    }
}

#[cfg(test)]
mod error_tests {
    #![allow(clippy::unwrap_used, clippy::expect_used)]
    use super::*;

    #[test]
    fn status_matches_the_documented_error_table() {
        let cases: &[(ErrorKind, http::StatusCode)] = &[
            (ErrorKind::Validation, http::StatusCode::BAD_REQUEST),
            (ErrorKind::MissingTargetHost, http::StatusCode::BAD_REQUEST),
            (ErrorKind::InvalidTargetHost, http::StatusCode::BAD_REQUEST),
            (ErrorKind::UnknownTargetHost, http::StatusCode::BAD_REQUEST),
            (
                ErrorKind::CorsOriginNotAllowed,
                http::StatusCode::BAD_REQUEST,
            ),
            (
                ErrorKind::CorsMethodNotAllowed,
                http::StatusCode::BAD_REQUEST,
            ),
            (ErrorKind::AuthFailed, http::StatusCode::UNAUTHORIZED),
            (ErrorKind::RouteNotFound, http::StatusCode::NOT_FOUND),
            (ErrorKind::ResourceNotFound, http::StatusCode::NOT_FOUND),
            (ErrorKind::AliasConflict, http::StatusCode::CONFLICT),
            (ErrorKind::PluginInUse, http::StatusCode::CONFLICT),
            (
                ErrorKind::PayloadTooLarge,
                http::StatusCode::PAYLOAD_TOO_LARGE,
            ),
            (
                ErrorKind::RateLimitExceeded,
                http::StatusCode::TOO_MANY_REQUESTS,
            ),
            (
                ErrorKind::SecretNotFound,
                http::StatusCode::INTERNAL_SERVER_ERROR,
            ),
            (ErrorKind::Protocol, http::StatusCode::BAD_GATEWAY),
            (ErrorKind::Downstream, http::StatusCode::BAD_GATEWAY),
            (ErrorKind::StreamAborted, http::StatusCode::BAD_GATEWAY),
            (
                ErrorKind::LinkUnavailable,
                http::StatusCode::SERVICE_UNAVAILABLE,
            ),
            (
                ErrorKind::CircuitBreakerOpen,
                http::StatusCode::SERVICE_UNAVAILABLE,
            ),
            (
                ErrorKind::PluginNotFound,
                http::StatusCode::SERVICE_UNAVAILABLE,
            ),
            (
                ErrorKind::ConnectionTimeout,
                http::StatusCode::GATEWAY_TIMEOUT,
            ),
            (ErrorKind::RequestTimeout, http::StatusCode::GATEWAY_TIMEOUT),
            (ErrorKind::IdleTimeout, http::StatusCode::GATEWAY_TIMEOUT),
            (ErrorKind::Internal, http::StatusCode::INTERNAL_SERVER_ERROR),
        ];
        for (kind, expected) in cases {
            let err = DomainError::new(*kind, "detail".to_owned());
            assert_eq!(err.http_status(), *expected, "{kind:?} status");
        }
    }

    #[test]
    fn gts_types_match_the_documented_identifiers() {
        assert_eq!(
            DomainError::new(ErrorKind::Validation, "d".into()).gts_type(),
            "gts.cf.core.errors.err.v1~cf.oagw.validation.error.v1"
        );
        assert_eq!(
            DomainError::new(ErrorKind::RouteNotFound, "d".into()).gts_type(),
            "gts.cf.core.errors.err.v1~cf.oagw.route.not_found.v1"
        );
        assert_eq!(
            DomainError::new(ErrorKind::MissingTargetHost, "d".into()).gts_type(),
            "gts.cf.core.errors.err.v1~cf.oagw.routing.missing_target_host.v1"
        );
        assert_eq!(
            DomainError::new(ErrorKind::PluginInUse, "d".into()).gts_type(),
            "gts.cf.core.errors.err.v1~cf.oagw.plugin.in_use.v1"
        );
        assert_eq!(
            DomainError::new(ErrorKind::SecretNotFound, "d".into()).gts_type(),
            "gts.cf.core.errors.err.v1~cf.oagw.secret.not_found.v1"
        );
    }

    #[test]
    fn only_documented_cases_are_retriable() {
        for kind in [
            ErrorKind::RateLimitExceeded,
            ErrorKind::LinkUnavailable,
            ErrorKind::CircuitBreakerOpen,
            ErrorKind::ConnectionTimeout,
            ErrorKind::RequestTimeout,
            ErrorKind::IdleTimeout,
        ] {
            assert!(DomainError::new(kind, "d".into()).retriable(), "{kind:?}");
        }
        for kind in [
            ErrorKind::Validation,
            ErrorKind::RouteNotFound,
            ErrorKind::SecretNotFound,
            ErrorKind::AuthFailed,
        ] {
            assert!(!DomainError::new(kind, "d".into()).retriable(), "{kind:?}");
        }
    }

    #[test]
    fn rate_limit_error_carries_retry_after() {
        let err = DomainError::rate_limit_exceeded("too many", 7);
        assert_eq!(err.retry_after(), Some(7));
        assert_eq!(err.http_status(), http::StatusCode::TOO_MANY_REQUESTS);
    }

    #[test]
    fn anyhow_maps_to_internal() {
        let err = DomainError::from(anyhow::anyhow!("boom"));
        assert_eq!(err.kind(), ErrorKind::Internal);
        assert_eq!(err.detail(), "boom");
        assert_eq!(err.title(), "Internal error");
    }
}
