//! Central domain error model for the OAGW gear (feature
//! `cpt-cf-oagw-feature-error-semantics`).
//!
//! [`DomainError`] carries the full GTS instance catalog from the DESIGN error
//! table (§3.3): every variant maps to exactly one
//! `gts.cf.core.errors.err.v1~cf.oagw.*.v1` instance with its documented HTTP
//! status and retriability classification (DoD
//! `cpt-cf-oagw-dod-error-semantics-catalog`,
//! `cpt-cf-oagw-dod-error-semantics-retriability`, algorithm
//! `cpt-cf-oagw-algo-error-semantics-classify-retry`).
//!
//! The error-source distinction (DoD `cpt-cf-oagw-dod-error-semantics-source`)
//! is modelled by [`ErrorSource`]: every [`DomainError`] originates from the
//! gateway; upstream-originated responses are passed through unchanged and
//! labelled `upstream` at the transport layer, never surfacing as a
//! [`DomainError`] (algorithm `cpt-cf-oagw-algo-error-semantics-attach-source`).
//! The instance builder (algorithm `cpt-cf-oagw-algo-error-semantics-build-instance`)
//! and the request-id propagation contract (DoD
//! `cpt-cf-oagw-dod-error-semantics-request-id`, algorithm
//! `cpt-cf-oagw-algo-error-semantics-propagate-request-id`) are delivered by
//! [`crate::infra::error_envelope`].

use std::time::Duration;

use thiserror::Error;
use toolkit_macros::domain_model;

use crate::domain::entity::ReferencedBy;

type BoxError = Box<dyn std::error::Error + Send + Sync + 'static>;

/// Origin of a response for the `X-OAGW-Error-Source` header contract.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ErrorSource {
    /// The response was generated by the OAGW gateway itself.
    Gateway,
    /// The response was produced by the upstream service and passed through
    /// unchanged by the gateway.
    Upstream,
}

impl ErrorSource {
    /// The exact header value for the `X-OAGW-Error-Source` header.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Gateway => "gateway",
            Self::Upstream => "upstream",
        }
    }
}

/// Retriability classification of a gateway error instance.
///
/// Surfaced to callers via the error `type` GTS identifier so clients can
/// implement correct retry behaviour (DoD
/// `cpt-cf-oagw-dod-error-semantics-retriability`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Retriability {
    /// The operation may be retried (optionally paced by `retry_after`).
    Retriable,
    /// Retrying the operation is not expected to succeed.
    NonRetriable,
    /// Whether retrying helps depends on the caller / upstream semantics
    /// (only `downstream.error`).
    Depends,
}

/// The OAGW domain error — every variant is an entry of the DESIGN error
/// catalog (see [`DomainError::instance`]).
#[domain_model]
#[derive(Debug, Error)]
#[non_exhaustive]
pub enum DomainError {
    /// General route / request validation error (400).
    #[error("request validation failed: {detail}")]
    Validation {
        detail: String,
        /// The offending request field, when known (used for canonical field
        /// violations at the API layer).
        field: Option<&'static str>,
    },
    /// `X-OAGW-Target-Host` header required for a multi-endpoint upstream with
    /// a common-suffix alias (400).
    #[error("target host missing: {detail}")]
    MissingTargetHost { detail: String },
    /// `X-OAGW-Target-Host` header format invalid (must be hostname or IP,
    /// no port/path/special chars) (400).
    #[error("invalid target host: {detail}")]
    InvalidTargetHost {
        detail: String,
        /// The offending header value, when available.
        host: Option<String>,
    },
    /// `X-OAGW-Target-Host` value matches no configured endpoint (400).
    #[error("unknown target host: {host}")]
    UnknownTargetHost { host: String },
    /// Authentication to the upstream failed (401).
    #[error("authentication failed: {detail}")]
    AuthenticationFailed { detail: String },
    /// No matching route found (404).
    #[error("route not found: {detail}")]
    RouteNotFound { detail: String },
    /// A plugin is still referenced and cannot be deleted (409).
    #[error("plugin in use: {name}")]
    PluginInUse {
        name: String,
        /// The upstream/route bindings referencing the plugin (the
        /// `referenced_by` shape of the RFC 9457 envelope).
        referenced_by: Vec<ReferencedBy>,
    },
    /// Request payload exceeds the configured body limit (413).
    #[error("request payload exceeds limit")]
    PayloadTooLarge {
        /// The enforced maximum body size in bytes, when known.
        max_bytes: Option<u64>,
    },
    /// Rate limit exceeded (429).
    #[error("rate limit exceeded: {detail}")]
    RateLimitExceeded {
        detail: String,
        /// Retry guidance exposed as `retry_after_seconds` on the envelope.
        retry_after: Option<Duration>,
    },
    /// A referenced `cred://` secret was not found (500).
    #[error("referenced secret not found: {detail}")]
    SecretNotFound { detail: String },
    /// Protocol-level error talking to the upstream (502).
    #[error("protocol error: {detail}")]
    ProtocolError {
        detail: String,
        #[source]
        cause: Option<BoxError>,
    },
    /// The upstream service itself returned an error (502, retriability
    /// depends on the caller).
    #[error("upstream service error: {detail}")]
    DownstreamError {
        detail: String,
        #[source]
        cause: Option<BoxError>,
    },
    /// The stream connection was aborted (502).
    #[error("stream connection aborted: {detail}")]
    StreamAborted { detail: String },
    /// Upstream link unavailable (503).
    #[error("upstream link unavailable: {detail}")]
    LinkUnavailable { detail: String },
    /// Circuit breaker open — upstream is being shed (503).
    #[error("circuit breaker open: {detail}")]
    CircuitBreakerOpen { detail: String },
    /// Referenced plugin could not be resolved (503).
    #[error("plugin not found: {detail}")]
    PluginNotFound { detail: String },
    /// Upstream connection timeout (504).
    #[error("connection timeout: {detail}")]
    ConnectionTimeout { detail: String },
    /// Upstream request timeout (504).
    #[error("request timeout: {detail}")]
    RequestTimeout { detail: String },
    /// Upstream idle timeout (504).
    #[error("idle timeout: {detail}")]
    IdleTimeout { detail: String },
    /// The `(tenant_id, alias)` pair is already taken by another upstream
    /// (409; management API, algorithm
    /// `cpt-cf-oagw-algo-control-plane-api-validate-alias`, step
    /// `inst-cp-alias-conflict`).
    #[error("upstream alias conflict: alias '{alias}' already exists within the tenant")]
    AliasConflict { alias: String },
    /// Two enabled routes under one upstream collide on
    /// `(path_prefix, priority)` for a shared method (409; management API,
    /// algorithm `cpt-cf-oagw-algo-control-plane-api-validate-match-rule`).
    #[error("route match-rule conflict: {detail}")]
    RouteConflict { detail: String },
    /// The `(tenant_id, plugin name)` pair is already taken (409; management
    /// API, plugin create flow step `inst-cp-plugin-create-conflict`).
    #[error("plugin name conflict: {name}")]
    PluginConflict { name: String },
    /// The caller lacks the GTS permission for a management operation (403;
    /// management API, algorithm
    /// `cpt-cf-oagw-algo-control-plane-api-authorize`, step
    /// `inst-cp-authz-deny`).
    #[error("access denied: {detail}")]
    AccessDenied {
        detail: String,
        #[source]
        cause: Option<BoxError>,
    },
    /// A dependency of the authorization path (or the authorization
    /// evaluation itself) failed; the operation cannot be completed (503;
    /// management API, algorithm
    /// `cpt-cf-oagw-algo-control-plane-api-authorize`).
    #[error("service unavailable: {detail}")]
    ServiceUnavailable {
        detail: String,
        retry_after: Option<Duration>,
        #[source]
        cause: Option<BoxError>,
    },
    /// The request `Origin` is not in the effective allowed set (403; CORS
    /// actual-request enforcement, ADR 0004 — data plane, algorithm
    /// `cpt-cf-oagw-algo-cors-handling-validate-origin`).
    #[error("origin not allowed: {detail}")]
    CorsOriginNotAllowed { detail: String },
    /// The request method is not in the effective allowed set (403; CORS
    /// actual-request enforcement, ADR 0004 — data plane, algorithm
    /// `cpt-cf-oagw-algo-cors-handling-validate-method`).
    #[error("method not allowed: {detail}")]
    CorsMethodNotAllowed { detail: String },
}

