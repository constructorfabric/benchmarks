    #[test]
    fn rate_limit_exceeded_carries_retry_after() {
        let err =
            DomainError::rate_limit_exceeded("limited".to_owned(), Some(Duration::from_secs(30)));
        assert_eq!(err.retry_after(), Some(Duration::from_secs(30)));
        // Non-retriable variants never expose retry guidance.
        let other = DomainError::RouteNotFound {
            detail: "x".to_owned(),
        };
        assert_eq!(other.retry_after(), None);
    }

    #[test]
    fn plugin_in_use_carries_referenced_by() {
        let err = DomainError::PluginInUse {
            name: "apikey".to_owned(),
            referenced_by: vec![ReferencedBy {
                resource: crate::domain::entity::ReferencedByResource::Upstream,
                id: uuid::Uuid::from_u128(7),
            }],
        };
        assert_eq!(err.referenced_by().len(), 1);
        assert_eq!(err.status(), 409);
        assert_eq!(
            err.instance(),
            "gts.cf.core.errors.err.v1~cf.oagw.plugin.in_use.v1"
        );
        // Non-in-use variants expose an empty `referenced_by`.
        let other = DomainError::RouteNotFound {
            detail: "x".to_owned(),
        };
        assert!(other.referenced_by().is_empty());
    }

