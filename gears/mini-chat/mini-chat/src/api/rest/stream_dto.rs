/// Payload of `stream_started`.
#[derive(Debug, Clone, PartialEq, Eq)]
#[toolkit_macros::api_dto(response)]
pub struct StreamStartedData {
    /// Resolved turn correlation key.
    pub request_id: Uuid,
    /// Pre-allocated (new turn) or persisted (replay) assistant message id.
    pub message_id: Uuid,
    /// `true` for a live generation, `false` for an idempotent replay.
    pub is_new_turn: bool,
    /// Present when a thread summary is part of the context of the turn.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub thread_summary_applied: Option<ThreadSummaryApplied>,
}

/// The thread summary that was included in the context of a turn.
#[derive(Debug, Clone, PartialEq, Eq)]
#[toolkit_macros::api_dto(response)]
pub struct ThreadSummaryApplied {
    /// Estimated size of the summary in tokens.
    pub token_estimate: u64,
}

