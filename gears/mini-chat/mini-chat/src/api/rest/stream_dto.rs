/// `OpenAPI` description of one SSE event: `event: <name>` plus `data: <payload>`.
#[derive(Debug, Clone, PartialEq, Eq)]
#[toolkit_macros::api_dto(response)]
#[serde(tag = "event", content = "data")]
pub enum MiniChatSseEvent {
    /// First event of every stream.
    StreamStarted(StreamStartedData),
    /// Keep-alive.
    Ping(PingData),
    /// Answer text.
    Delta(DeltaData),
    /// Tool activity.
    Tool(ToolData),
    /// Source references.
    Citations(CitationsData),
    /// Terminal: success.
    Done(DoneData),
    /// Terminal: failure.
    Error(ErrorData),
}

impl From<ToolPhase> for ToolPhaseDto {
    fn from(phase: ToolPhase) -> Self {
        match phase {
            ToolPhase::Start => Self::Start,
            ToolPhase::Done => Self::Done,
        }
    }
}

impl From<Citation> for CitationDto {
    fn from(citation: Citation) -> Self {
        Self {
            source: match citation.source {
                CitationSource::File => CitationSourceDto::File,
                CitationSource::Web => CitationSourceDto::Web,
            },
            title: citation.title,
            url: citation.url,
            attachment_id: citation.attachment_id,
            snippet: citation.snippet,
            span: citation.span.map(|(start, end)| TextSpan { start, end }),
        }
    }
}

impl From<DoneEvent> for DoneData {
    fn from(done: DoneEvent) -> Self {
        Self {
            usage: Usage {
                input_tokens: done.input_tokens,
                output_tokens: done.output_tokens,
            },
            effective_model: done.effective_model,
            selected_model: done.selected_model,
            quota_decision: match done.quota_decision {
                QuotaDecision::Allow => QuotaDecisionKind::Allow,
                QuotaDecision::Downgrade => QuotaDecisionKind::Downgrade,
            },
            downgrade_from: done.downgrade_from,
            downgrade_reason: done.downgrade_reason,
            quota_warnings: done
                .quota_warnings
                .map(|warnings| warnings.into_iter().map(Into::into).collect()),
        }
    }
}

impl From<StreamEvent> for MiniChatSseEvent {
    fn from(event: StreamEvent) -> Self {
        match event {
            StreamEvent::Started {
                request_id,
                message_id,
                is_new_turn,
                thread_summary_applied,
            } => Self::StreamStarted(StreamStartedData {
                request_id,
                message_id,
                is_new_turn,
                thread_summary_applied: thread_summary_applied
                    .map(|token_estimate| ThreadSummaryApplied { token_estimate }),
            }),
            StreamEvent::Ping => Self::Ping(PingData {}),
            StreamEvent::Delta(content) => Self::Delta(DeltaData {
                kind: DeltaKind::Text,
                content,
            }),
            StreamEvent::Tool {
                phase,
                name,
                details,
            } => Self::Tool(ToolData {
                phase: phase.into(),
                name,
                details,
            }),
            StreamEvent::Citations(items) => Self::Citations(CitationsData {
                items: items.into_iter().map(Into::into).collect(),
            }),
            StreamEvent::Done(done) => Self::Done(done.into()),
            StreamEvent::Error { code, message } => Self::Error(ErrorData { code, message }),
        }
    }
}

impl MiniChatSseEvent {
    /// The SSE frame: `event: <name>` and the JSON payload as `data`.
    pub fn into_sse_event(self) -> Event {
        let (name, payload) = match self {
            Self::StreamStarted(data) => ("stream_started", serde_json::to_string(&data)),
            Self::Ping(data) => ("ping", serde_json::to_string(&data)),
            Self::Delta(data) => ("delta", serde_json::to_string(&data)),
            Self::Tool(data) => ("tool", serde_json::to_string(&data)),
            Self::Citations(data) => ("citations", serde_json::to_string(&data)),
            Self::Done(data) => ("done", serde_json::to_string(&data)),
            Self::Error(data) => ("error", serde_json::to_string(&data)),
        };
        match payload {
            Ok(payload) => Event::default().event(name).data(payload),
            Err(error) => {
                tracing::error!(%error, event = name, "SSE payload does not serialize");
                Event::default().event("error").data(
                    r#"{"code":"stream_interrupted","message":"the event could not be encoded"}"#,
                )
            }
        }
    }
}

