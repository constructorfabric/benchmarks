/// Turn state as the Turn Status API reports it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[toolkit_macros::api_dto(response)]
pub enum TurnStatusState {
    /// Generation in progress.
    Running,
    /// Completed.
    Done,
    /// Failed.
    Error,
    /// Cancelled.
    Cancelled,
}

/// Response of `GET /v1/chats/{id}/turns/{request_id}`.
#[derive(Debug, Clone, PartialEq, Eq)]
#[toolkit_macros::api_dto(response)]
pub struct TurnStatusResponse {
    /// Turn correlation key.
    pub request_id: Uuid,
    /// Turn state.
    pub state: TurnStatusState,
    /// Terminal error code (state `error` only).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub error_code: Option<String>,
    /// Persisted assistant message.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub assistant_message_id: Option<Uuid>,
    /// Last state change.
    #[serde(with = "time::serde::rfc3339")]
    pub updated_at: OffsetDateTime,
}

impl From<TurnView> for TurnStatusResponse {
    fn from(view: TurnView) -> Self {
        Self {
            request_id: view.request_id,
            state: match view.state {
                TurnStatus::Running => TurnStatusState::Running,
                TurnStatus::Done => TurnStatusState::Done,
                TurnStatus::Error => TurnStatusState::Error,
                TurnStatus::Cancelled => TurnStatusState::Cancelled,
            },
            error_code: view.error_code,
            assistant_message_id: view.assistant_message_id,
            updated_at: view.updated_at,
        }
    }
}
