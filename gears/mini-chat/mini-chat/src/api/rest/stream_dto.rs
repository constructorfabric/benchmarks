//! DTOs of the streaming endpoint and the Turn Status API (`OpenAPI` names
//! `StreamMessageRequest`, `WebSearchConfig`, `MiniChatSseEvent`,
//! `StreamStartedData`, `PingData`, `DeltaData`, `DeltaKind`, `ToolData`,
//! `ToolPhase`, `CitationsData`, `Citation`, `CitationSource`, `TextSpan`,
//! `DoneData`, `Usage`, `QuotaDecisionKind`, `ErrorData`, `TurnStatusResponse`,
//! `TurnStatusState`).
//!
//! The wire form carries internal identifiers only: no provider id, vector
//! store id or provider model name ever appears here (DESIGN 3.3 "Provider
//! identifier non-exposure invariant").

use axum::response::sse::Event;
use time::OffsetDateTime;
use uuid::Uuid;

use super::quota_dto::QuotaWarning;
use crate::domain::streaming::{
    Citation, CitationSource, DoneEvent, QuotaDecision, SendMessageCommand, StreamEvent, ToolPhase,
};
use crate::domain::turns::{TurnStatus, TurnView};

// ── request ─────────────────────────────────────────────────────────────────

/// Web search toggle of one turn.
#[derive(Debug, Clone, PartialEq, Eq)]
#[toolkit_macros::api_dto(request)]
pub struct WebSearchConfig {
    /// Include the `web_search` tool in the provider request.
    pub enabled: bool,
}

/// Request body of `POST /v1/chats/{id}/messages:stream`.
#[derive(Debug, Clone, PartialEq, Eq)]
#[toolkit_macros::api_dto(request)]
pub struct StreamMessageRequest {
    /// Message content (must be non-empty).
    pub content: String,
    /// Idempotency key: any UUID; generated by the server when omitted.
    #[serde(default)]
    pub request_id: Option<Uuid>,
    /// Attachment IDs to link to the message.
    #[serde(default)]
    pub attachment_ids: Option<Vec<Uuid>>,
    /// Web search configuration.
    #[serde(default)]
    pub web_search: Option<WebSearchConfig>,
}

impl From<StreamMessageRequest> for SendMessageCommand {
    fn from(body: StreamMessageRequest) -> Self {
        Self {
            content: body.content,
            request_id: body.request_id,
            attachment_ids: body.attachment_ids.unwrap_or_default(),
            web_search: body.web_search.is_some_and(|config| config.enabled),
        }
    }
}

/// Request body of `PATCH /v1/chats/{id}/turns/{request_id}`.
#[derive(Debug, Clone, PartialEq, Eq)]
#[toolkit_macros::api_dto(request)]
pub struct EditTurnRequest {
    /// The new user message content (must be non-empty after trim; stored
    /// verbatim).
    pub content: String,
}

