/// Response DTO for a message in the list endpoint.
#[toolkit_macros::api_dto(response)]
pub struct MiniChatMessageDto {
    pub id: Uuid,
    pub request_id: Uuid,
    pub role: MessageRoleDto,
    pub content: String,
    pub attachments: Vec<AttachmentSummaryDto>,
    /// The caller's reaction to this message; `null` when there is none.
    pub my_reaction: Option<ReactionKindDto>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub model: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub input_tokens: Option<i64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub output_tokens: Option<i64>,
    #[serde(with = "time::serde::rfc3339")]
    pub created_at: OffsetDateTime,
}

impl MiniChatMessageDto {
    /// # Errors
    /// A stored message without `request_id` is an internal error.
    pub fn try_from_view(v: MessageView) -> Result<Self, crate::domain::error::DomainError> {
        let m = v.message;
        let request_id = m
            .request_id
            .ok_or_else(|| crate::domain::error::DomainError::internal("message without request_id"))?;
        let role = match m.role.as_str() {
            "assistant" => MessageRoleDto::Assistant,
            "system" => MessageRoleDto::System,
            _ => MessageRoleDto::User,
        };
        Ok(Self {
            id: m.id,
            request_id,
            role,
            content: m.content,
            attachments: v.attachments.iter().map(AttachmentSummaryDto::from).collect(),
            my_reaction: v.my_reaction.as_deref().map(|r| if r == "dislike" { ReactionKindDto::Dislike } else { ReactionKindDto::Like }),
            model: if role == MessageRoleDto::Assistant { m.model } else { None },
            input_tokens: (m.input_tokens > 0).then_some(m.input_tokens),
            output_tokens: (m.output_tokens > 0).then_some(m.output_tokens),
            created_at: m.created_at,
        })
    }
}

