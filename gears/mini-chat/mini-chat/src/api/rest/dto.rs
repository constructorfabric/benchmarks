/// Full attachment details returned by the GET attachment endpoint.
#[derive(Debug, Clone)]
#[toolkit_macros::api_dto(response)]
pub struct AttachmentDetailDto {
    pub id: Uuid,
    pub filename: String,
    pub content_type: String,
    pub size_bytes: i64,
    pub status: AttachmentStatusDto,
    pub kind: AttachmentKindDto,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub error_code: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub doc_summary: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub img_thumbnail: Option<ImgThumbnailDto>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub summary_updated_at: Option<DateTime<Utc>>,
    pub created_at: DateTime<Utc>,
}

impl From<attachments::Model> for AttachmentDetailDto {
    fn from(a: attachments::Model) -> Self {
        let thumb = crate::domain::services::messages::thumbnail_of(&a).map(Into::into);
        let failed = a.status == "failed";
        Self {
            id: a.id,
            filename: a.filename,
            content_type: a.content_type,
            size_bytes: a.size_bytes,
            status: status_of(&a.status),
            kind: kind_of(&a.attachment_kind),
            error_code: if failed { a.error_code } else { None },
            doc_summary: None,
            img_thumbnail: thumb,
            summary_updated_at: None,
            created_at: a.created_at,
        }
    }
}

