/// One SSE event of the `messages:stream`, retry and edit responses: sent as
/// `event: <name>` and `data: <payload>` (JSON). This type documents the wire
/// format only.
#[derive(Debug, Clone)]
#[toolkit_macros::api_dto(response)]
#[serde(tag = "event", content = "data")]
pub enum MiniChatSseEvent {
    StreamStarted(StreamStartedData),
    Ping(PingData),
    Delta(DeltaData),
    Tool(ToolData),
    Citations(CitationsData),
    Done(DoneData),
    Error(ErrorData),
}

/// SSE event name and JSON payload of a domain stream event.
#[must_use]
pub fn sse_parts(ev: &StreamEvent) -> (&'static str, serde_json::Value) {
    (ev.name(), ev.data())
}
