/// Turn state as reported by the turn status endpoint.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[toolkit_macros::api_dto(response)]
pub enum TurnStatusState {
    Running,
    Done,
    Error,
    Cancelled,
}

/// Response DTO for `GET /chats/{id}/turns/{request_id}`.
#[derive(Debug, Clone)]
#[toolkit_macros::api_dto(response)]
pub struct TurnStatusResponse {
    pub request_id: Uuid,
    pub state: TurnStatusState,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub error_code: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub assistant_message_id: Option<Uuid>,
    pub updated_at: DateTime<Utc>,
}

impl From<TurnStatusView> for TurnStatusResponse {
    fn from(v: TurnStatusView) -> Self {
        let state = match v.state.api_state() {
            "done" => TurnStatusState::Done,
            "error" => TurnStatusState::Error,
            "cancelled" => TurnStatusState::Cancelled,
            _ => TurnStatusState::Running,
        };
        Self {
            request_id: v.request_id,
            state,
            error_code: v.error_code,
            assistant_message_id: v.assistant_message_id,
            updated_at: v.updated_at,
        }
    }
}

