/// Response DTO for a message in the list endpoint.
///
/// Aliased to `MiniChatMessageDto` in the `OpenAPI` schema: other gears may
/// also expose a `MessageDto`, and all gears register into the same
/// api-gateway `OpenAPI` registry, so the bare ident would collide in
/// `components.schemas`.
#[toolkit_macros::api_dto(response)]
#[schema(as = MiniChatMessageDto)]
pub struct MessageDto {
    pub id: Uuid,
    pub request_id: Uuid,
    pub role: MessageRoleDto,
    pub content: String,
    pub attachments: Vec<AttachmentSummaryDto>,
    /// The caller's reaction to this message; `null` when there is none.
    #[schema(required)]
    pub my_reaction: Option<ReactionKindDto>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub model: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub input_tokens: Option<i64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub output_tokens: Option<i64>,
    #[schema(format = DateTime)]
    pub created_at: String,
}

impl From<MessageView> for MessageDto {
    fn from(m: MessageView) -> Self {
        Self {
            id: m.id,
            request_id: m.request_id,
            role: match m.role.as_str() {
                "assistant" => MessageRoleDto::Assistant,
                "system" => MessageRoleDto::System,
                _ => MessageRoleDto::User,
            },
            content: m.content,
            attachments: m.attachments.into_iter().map(Into::into).collect(),
            my_reaction: m.my_reaction.as_deref().map(reaction_dto),
            model: m.model,
            input_tokens: m.input_tokens,
            output_tokens: m.output_tokens,
            created_at: ts(m.created_at),
        }
    }
}

