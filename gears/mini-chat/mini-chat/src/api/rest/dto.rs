/// Successful stream completion.
#[toolkit_macros::api_dto(response)]
pub struct DoneData {
    pub usage: Usage,
    pub effective_model: String,
    pub selected_model: String,
    pub quota_decision: QuotaDecisionKind,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub downgrade_from: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub downgrade_reason: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub quota_warnings: Option<Vec<QuotaWarning>>,
}

fn quota_tier(tier: &str) -> QuotaTier {
    if tier == "premium" {
        QuotaTier::Premium
    } else {
        QuotaTier::Total
    }
}

fn quota_period(period: &str) -> QuotaPeriod {
    if period == "daily" {
        QuotaPeriod::Daily
    } else {
        QuotaPeriod::Monthly
    }
}

impl From<DoneView> for DoneData {
    fn from(d: DoneView) -> Self {
        Self {
            usage: Usage {
                input_tokens: d.input_tokens,
                output_tokens: d.output_tokens,
            },
            effective_model: d.effective_model,
            selected_model: d.selected_model,
            quota_decision: if d.downgrade {
                QuotaDecisionKind::Downgrade
            } else {
                QuotaDecisionKind::Allow
            },
            downgrade_from: d.downgrade_from,
            downgrade_reason: d.downgrade_reason,
            quota_warnings: d.quota_warnings.map(|ws| {
                ws.into_iter()
                    .map(|w| QuotaWarning {
                        tier: quota_tier(w.tier),
                        period: quota_period(w.period),
                        remaining_percentage: w.remaining_percentage,
                        warning: w.warning,
                        exhausted: w.exhausted,
                        next_reset: w.next_reset.map(rfc3339_seconds),
                    })
                    .collect()
            }),
        }
    }
}

/// Stream error (terminal).
#[toolkit_macros::api_dto(response)]
pub struct ErrorData {
    pub code: String,
    pub message: String,
}

impl From<StreamEvent> for MiniChatSseEvent {
    fn from(ev: StreamEvent) -> Self {
        match ev {
            StreamEvent::StreamStarted {
                request_id,
                message_id,
                is_new_turn,
                thread_summary_tokens,
            } => Self::StreamStarted(StreamStartedData {
                request_id,
                message_id,
                is_new_turn,
                thread_summary_applied: thread_summary_tokens.map(|t| ThreadSummaryInfo {
                    token_estimate: u32::try_from(t).unwrap_or(u32::MAX),
                }),
            }),
            StreamEvent::Ping => Self::Ping(PingData {}),
            StreamEvent::Delta { kind, content } => Self::Delta(DeltaData {
                r#type: match kind {
                    DeltaKind::Text => DeltaKindDto::Text,
                    DeltaKind::Reasoning => DeltaKindDto::Reasoning,
                },
                content,
            }),
            StreamEvent::Tool {
                phase,
                name,
                details,
            } => Self::Tool(ToolData {
                phase: if phase == "start" {
                    ToolPhase::Start
                } else {
                    ToolPhase::Done
                },
                name,
                details,
            }),
            StreamEvent::Citations(items) => Self::Citations(CitationsData {
                items: items.into_iter().map(Into::into).collect(),
            }),
            StreamEvent::Done(d) => Self::Done(d.into()),
            StreamEvent::Error { code, message } => Self::Error(ErrorData { code, message }),
        }
    }
}

/// SSE event name and JSON payload of a stream event.
#[must_use]
pub fn sse_payload(ev: StreamEvent) -> (&'static str, String) {
    fn json<T: Serialize>(v: &T) -> String {
        serde_json::to_string(v).unwrap_or_else(|_| "{}".to_owned())
    }
    match MiniChatSseEvent::from(ev) {
        MiniChatSseEvent::StreamStarted(d) => ("stream_started", json(&d)),
        MiniChatSseEvent::Ping(d) => ("ping", json(&d)),
        MiniChatSseEvent::Delta(d) => ("delta", json(&d)),
        MiniChatSseEvent::Tool(d) => ("tool", json(&d)),
        MiniChatSseEvent::Citations(d) => ("citations", json(&d)),
        MiniChatSseEvent::Done(d) => ("done", json(&d)),
        MiniChatSseEvent::Error(d) => ("error", json(&d)),
    }
}

