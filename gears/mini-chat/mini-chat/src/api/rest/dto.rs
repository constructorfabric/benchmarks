/// Quota tier classification.
#[derive(Debug, Clone, Copy)]
#[toolkit_macros::api_dto(response)]
pub enum QuotaTier {
    Premium,
    Total,
}

/// Quota period classification.
#[derive(Debug, Clone, Copy)]
#[toolkit_macros::api_dto(response)]
pub enum QuotaPeriod {
    Daily,
    Monthly,
}

#[toolkit_macros::api_dto(response)]
pub struct QuotaPeriodStatus {
    pub period: QuotaPeriod,
    pub limit_credits_micro: i64,
    pub used_credits_micro: i64,
    pub remaining_credits_micro: i64,
    pub remaining_percentage: u32,
    #[schema(format = DateTime)]
    pub next_reset: String,
    pub warning: bool,
    pub exhausted: bool,
}

#[toolkit_macros::api_dto(response)]
pub struct QuotaTierStatus {
    pub tier: QuotaTier,
    pub periods: Vec<QuotaPeriodStatus>,
}

#[toolkit_macros::api_dto(response)]
pub struct QuotaStatusResponse {
    pub tiers: Vec<QuotaTierStatus>,
    pub warning_threshold_pct: u32,
}

fn rfc3339_seconds(t: OffsetDateTime) -> String {
    t.format(&time::format_description::well_known::Rfc3339)
        .unwrap_or_default()
}

impl From<QuotaStatusView> for QuotaStatusResponse {
    fn from(v: QuotaStatusView) -> Self {
        let mut tiers: Vec<QuotaTierStatus> = Vec::new();
        for s in v.periods {
            let tier = quota_tier(s.tier);
            let period = QuotaPeriodStatus {
                period: quota_period(s.period),
                limit_credits_micro: s.limit,
                used_credits_micro: s.used,
                remaining_credits_micro: s.remaining,
                remaining_percentage: s.remaining_percentage,
                next_reset: rfc3339_seconds(s.next_reset),
                warning: s.warning,
                exhausted: s.exhausted,
            };
            match tiers.iter_mut().find(|t| {
                matches!(
                    (t.tier, tier),
                    (QuotaTier::Premium, QuotaTier::Premium) | (QuotaTier::Total, QuotaTier::Total)
                )
            }) {
                Some(t) => t.periods.push(period),
                None => tiers.push(QuotaTierStatus {
                    tier,
                    periods: vec![period],
                }),
            }
        }
        Self {
            tiers,
            warning_threshold_pct: u32::from(v.warning_threshold_pct),
        }
    }
}

