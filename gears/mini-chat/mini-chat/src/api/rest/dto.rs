impl From<&PeriodStatus> for QuotaPeriodStatus {
    fn from(p: &PeriodStatus) -> Self {
        Self {
            period: period_of(p.period),
            limit_credits_micro: p.limit,
            used_credits_micro: p.used,
            remaining_credits_micro: p.remaining,
            remaining_percentage: p.remaining_percentage,
            next_reset: p.next_reset,
            warning: p.warning,
            exhausted: p.exhausted,
        }
    }
}

#[toolkit_macros::api_dto(response)]
pub struct QuotaTierStatus {
    pub tier: QuotaTier,
    pub periods: Vec<QuotaPeriodStatus>,
}

#[toolkit_macros::api_dto(response)]
pub struct QuotaStatusResponse {
    pub tiers: Vec<QuotaTierStatus>,
    pub warning_threshold_pct: u32,
}

impl From<QuotaStatusView> for QuotaStatusResponse {
    fn from(v: QuotaStatusView) -> Self {
        Self {
            tiers: v
                .tiers
                .iter()
                .map(|(tier, periods)| QuotaTierStatus { tier: tier_of(tier), periods: periods.iter().map(QuotaPeriodStatus::from).collect() })
                .collect(),
            warning_threshold_pct: u32::from(v.warning_threshold_pct),
        }
    }
}

