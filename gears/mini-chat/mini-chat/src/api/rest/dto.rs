    use crate::domain::stream::{CitationView, DeltaKind, DoneView, QuotaWarningView, StreamEvent};

    fn payload(ev: StreamEvent) -> (&'static str, Value) {
        let (name, data) = sse_payload(ev);
        (name, serde_json::from_str(&data).unwrap())
    }

    #[test]
    fn stream_started_and_simple_events() {
        let rid = Uuid::from_u128(1);
        let mid = Uuid::from_u128(2);
        let (n, v) = payload(StreamEvent::StreamStarted {
            request_id: rid,
            message_id: mid,
            is_new_turn: true,
            thread_summary_tokens: None,
        });
        assert_eq!(n, "stream_started");
        assert_eq!(
            v,
            json!({"request_id": rid, "message_id": mid, "is_new_turn": true})
        );
        let (_, v) = payload(StreamEvent::StreamStarted {
            request_id: rid,
            message_id: mid,
            is_new_turn: false,
            thread_summary_tokens: Some(42),
        });
        assert_eq!(v["thread_summary_applied"], json!({"token_estimate": 42}));
        assert_eq!(payload(StreamEvent::Ping), ("ping", json!({})));
        assert_eq!(
            payload(StreamEvent::Delta {
                kind: DeltaKind::Text,
                content: "hi".into()
            }),
            ("delta", json!({"type": "text", "content": "hi"}))
        );
        assert_eq!(
            payload(StreamEvent::Delta {
                kind: DeltaKind::Reasoning,
                content: "r".into()
            })
            .1["type"],
            "reasoning"
        );
        assert_eq!(
            payload(StreamEvent::Tool {
                phase: "start",
                name: "web_search".into(),
                details: json!({})
            }),
            (
                "tool",
                json!({"phase": "start", "name": "web_search", "details": {}})
            )
        );
        assert_eq!(
            payload(StreamEvent::error("provider_error", "boom")),
            (
                "error",
                json!({"code": "provider_error", "message": "boom"})
            )
        );
    }

    #[test]
    fn citations_omit_absent_fields() {
        let aid = Uuid::from_u128(9);
        let (n, v) = payload(StreamEvent::Citations(vec![
            CitationView {
                source: "web",
                title: "T".into(),
                url: Some("https://e.com".into()),
                attachment_id: None,
                snippet: "s".into(),
                span: Some((1, 4)),
            },
            CitationView {
                source: "file",
                title: "doc.pdf".into(),
                url: None,
                attachment_id: Some(aid),
                snippet: String::new(),
                span: None,
            },
        ]));
        assert_eq!(n, "citations");
        assert_eq!(
            v["items"][0],
            json!({"source": "web", "title": "T", "url": "https://e.com", "snippet": "s", "span": {"start": 1, "end": 4}})
        );
        assert_eq!(
            v["items"][1],
            json!({"source": "file", "title": "doc.pdf", "attachment_id": aid, "snippet": ""})
        );
    }

    #[test]
    fn done_payload() {
        let base = DoneView {
            input_tokens: 5,
            output_tokens: 7,
            effective_model: "m".into(),
            selected_model: "m".into(),
            downgrade: false,
            downgrade_from: None,
            downgrade_reason: None,
            quota_warnings: None,
        };
        let (n, v) = payload(StreamEvent::Done(base.clone()));
        assert_eq!(n, "done");
        assert_eq!(
            v,
            json!({"usage": {"input_tokens": 5, "output_tokens": 7}, "effective_model": "m", "selected_model": "m", "quota_decision": "allow"})
        );
        let (_, v) = payload(StreamEvent::Done(DoneView {
            effective_model: "small".into(),
            selected_model: "big".into(),
            downgrade: true,
            downgrade_from: Some("big".into()),
            downgrade_reason: Some("premium_quota_exhausted".into()),
            quota_warnings: Some(vec![
                QuotaWarningView {
                    tier: "total",
                    period: "daily",
                    remaining_percentage: 10,
                    warning: true,
                    exhausted: false,
                    next_reset: Some(datetime!(2026-10-04 0:00 UTC)),
                },
                QuotaWarningView {
                    tier: "premium",
                    period: "daily",
                    remaining_percentage: 90,
                    warning: false,
                    exhausted: false,
                    next_reset: None,
                },
            ]),
            ..base
        }));
        assert_eq!(v["quota_decision"], "downgrade");
        assert_eq!(v["downgrade_from"], "big");
        assert_eq!(v["downgrade_reason"], "premium_quota_exhausted");
        assert_eq!(v["quota_warnings"][0]["next_reset"], "2026-10-04T00:00:00Z");
        assert!(v["quota_warnings"][1].get("next_reset").is_none());
    }

    #[test]
    fn timestamps_have_microsecond_precision() {
        assert_eq!(
            ts(datetime!(2026-10-03 10:46:54.447749123 UTC)),
            "2026-10-03T10:46:54.447749Z"
        );
    }
