/// Mini Chat SSE event. Each event is sent as `event: <name>` and `data: <payload>` (JSON).
#[toolkit_macros::api_dto(response)]
#[serde(tag = "event", content = "data")]
pub enum MiniChatSseEvent {
    StreamStarted(StreamStartedData),
    Ping(PingData),
    Delta(DeltaData),
    Tool(ToolData),
    Citations(CitationsData),
    Done(DoneData),
    Error(ErrorData),
}

/// Render a domain event as `(event name, JSON data)`.
#[must_use]
pub fn render_event(ev: SseEvent) -> (&'static str, Value) {
    let to = |v: Result<Value, serde_json::Error>| v.unwrap_or(Value::Null);
    match ev {
        SseEvent::StreamStarted { request_id, message_id, is_new_turn, thread_summary_applied } => (
            "stream_started",
            to(serde_json::to_value(StreamStartedData {
                request_id,
                message_id,
                is_new_turn,
                thread_summary_applied: thread_summary_applied
                    .map(|t| ThreadSummaryInfo { token_estimate: u32::try_from(t.max(0)).unwrap_or(u32::MAX) }),
            })),
        ),
        SseEvent::Ping => ("ping", serde_json::json!({})),
        SseEvent::Delta { kind, content } => (
            "delta",
            to(serde_json::to_value(DeltaData {
                kind: if kind == "reasoning" { DeltaKind::Reasoning } else { DeltaKind::Text },
                content,
            })),
        ),
        SseEvent::Tool { phase, name, details } => (
            "tool",
            to(serde_json::to_value(ToolData {
                phase: if phase == "done" { ToolPhase::Done } else { ToolPhase::Start },
                name,
                details,
            })),
        ),
        SseEvent::Citations(items) => (
            "citations",
            to(serde_json::to_value(CitationsData { items: items.into_iter().map(Citation::from).collect() })),
        ),
        SseEvent::Done(d) => ("done", to(serde_json::to_value(DoneData::from(d)))),
        SseEvent::Error { code, message } => ("error", to(serde_json::to_value(ErrorData { code, message }))),
    }
}
