def ub(value):
    """UUID string -> 16-byte BLOB as stored by the gear on SQLite."""
    return uuid.UUID(str(value)).bytes


def as_uuid(blob):
    if isinstance(blob, (bytes, bytearray)) and len(blob) == 16:
        return str(uuid.UUID(bytes=bytes(blob)))
    return blob


class DB:
    def __init__(self, stack):
        self.stack = stack

    def query(self, sql, params=()):
        conn = sqlite3.connect(f"file:{self.stack.db_path}?mode=ro", uri=True, timeout=10)
        try:
            conn.row_factory = sqlite3.Row
            for _ in range(20):
                try:
                    return [{k: as_uuid(r[k]) for k in r.keys()} for r in conn.execute(sql, params)]
                except sqlite3.OperationalError as exc:
                    if "locked" not in str(exc):
                        raise
                    time.sleep(0.1)
            raise RuntimeError("database stayed locked")
        finally:
            conn.close()

    def one(self, sql, params=()):
        rows = self.query(sql, params)
        assert len(rows) == 1, rows
        return rows[0]

    def turn(self, chat_id, request_id):
        return self.one("SELECT * FROM chat_turns WHERE chat_id = ? AND request_id = ?",
                        (ub(chat_id), ub(request_id)))

    def attachment(self, attachment_id):
        return self.one("SELECT * FROM attachments WHERE id = ?", (ub(attachment_id),))

    def outbox_bodies(self, payload_type=None):
        rows = self.query("SELECT id, payload, payload_type FROM toolkit_outbox_body ORDER BY id")
        out = []
        for r in rows:
            if payload_type and r["payload_type"] != payload_type:
                continue
            try:
                r["json"] = json.loads(r["payload"])
            except (TypeError, ValueError):
                r["json"] = None
            out.append(r)
        return out

    def quota_rows(self, user_id=USER_A):
        return self.query("SELECT * FROM quota_usage WHERE user_id = ?", (ub(user_id),))


