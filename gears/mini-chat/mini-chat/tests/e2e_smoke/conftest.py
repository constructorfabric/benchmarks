# --------------------------------------------------------------------------- problems
def problem_type(category):
    return f"gts://gts.cf.core.errors.err.v1~cf.core.err.{category}.v1~"


def assert_problem(resp_or_json, status, category, field=None, reason=None, ctx_reason=None,
                   resource_type=None, violation=None, resource_name=None):
    """Assert an RFC 9457 canonical Problem. Returns the problem JSON."""
    if isinstance(resp_or_json, dict):
        body, http = resp_or_json, resp_or_json.get("status")
    else:
        http = resp_or_json.status_code
        assert "json" in resp_or_json.headers.get("content-type", ""), resp_or_json.text
        body = resp_or_json.json()
    assert http == status, body
    assert body.get("status") == status, body
    assert body.get("type") == problem_type(category), body
    assert "code" not in body, body
    ctx = body.get("context") or {}
    if reason is not None:
        fv = ctx.get("field_violations") or []
        assert any(v.get("reason") == reason and (field is None or v.get("field") == field) for v in fv), body
    if ctx_reason is not None:
        assert ctx.get("reason") == ctx_reason, body
    if resource_type is not None:
        assert ctx.get("resource_type") == resource_type, body
    if resource_name is not None:
        assert ctx.get("resource_name") == resource_name, body
    if violation is not None:
        vs = ctx.get("violations") or []
        assert any(all(v.get(k) == val for k, val in violation.items()) for v in vs), body
    return body


def assert_no_provider_ids(text):
    if isinstance(text, (bytes, bytearray)):
        text = text.decode("utf-8", "replace")
    if not isinstance(text, str):
        text = json.dumps(text)
    m = PROVIDER_ID_RE.search(text)
    assert m is None, f"provider identifier leaked: {m.group(0)!r} in {text[:500]}"


