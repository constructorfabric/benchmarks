class Client:
    def __init__(self, token):
        self.token = token
        self.s = requests.Session()
        if token:
            self.s.headers["Authorization"] = f"Bearer {token}"

    def url(self, path):
        return path if path.startswith("http") else BASE + path

    def request(self, method, path, **kw):
        kw.setdefault("timeout", 60)
        return self.s.request(method, self.url(path), **kw)

    def get(self, path, **kw):
        return self.request("GET", path, **kw)

    def post(self, path, **kw):
        return self.request("POST", path, **kw)

    def patch(self, path, **kw):
        return self.request("PATCH", path, **kw)

    def put(self, path, **kw):
        return self.request("PUT", path, **kw)

    def delete(self, path, **kw):
        return self.request("DELETE", path, **kw)

    # api-gateway rate limit on create_chat is 10/s per IP: retry gateway 429s.
    def post_chat(self, body=None, **kw):
        for _ in range(20):
            r = self.post("/chats", json=body if body is not None else {}, **kw)
            if r.status_code != 429:
                return r
            time.sleep(0.3)
        return r

    def create_chat(self, **body):
        r = self.post_chat(body)
        assert r.status_code == 201, r.text
        return r.json()

    def stream(self, chat_id, content, **kw):
        body = {"content": content}
        for key in ("request_id", "attachment_ids", "web_search"):
            if key in kw:
                body[key] = kw.pop(key)
        return sse_request(self, "POST", f"/chats/{chat_id}/messages:stream", body, **kw)

    def turn(self, chat_id, content="hello", **kw):
        """Run one turn and assert it ends with `done`."""
        res = self.stream(chat_id, content, **kw)
        assert res.status == 200, res.problem
        assert res.terminal_name == "done", res.events
        return res

    def upload(self, chat_id, filename, data, content_type, field="file"):
        return self.post(f"/chats/{chat_id}/attachments",
                         files={field: (filename, data, content_type)}, timeout=60)


