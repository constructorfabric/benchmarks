# --------------------------------------------------------------------------- processes
class Stack:
    """Mock provider + server, both owned through Popen objects."""

    def __init__(self):
        self.workdir = Path(tempfile.mkdtemp(prefix="mc-e2e-", dir="/tmp"))
        self.mock_proc = None
        self.server_proc = None
        self.variant = None
        self.home = None
        self.server_log = None
        self._starts = 0

    # mock --------------------------------------------------------------
    def start_mock(self):
        _wait_port_free(MOCK_PORT)
        log = open(self.workdir / "mock.log", "wb")
        self.mock_proc = subprocess.Popen(
            [sys.executable, str(HERE / "mock_provider.py"), str(MOCK_PORT)],
            stdout=log, stderr=subprocess.STDOUT,
        )
        (self.workdir / "mock.pid").write_text(str(self.mock_proc.pid))
        deadline = time.time() + 15
        while time.time() < deadline:
            if self.mock_proc.poll() is not None:
                raise RuntimeError(f"mock provider exited early, see {self.workdir / 'mock.log'}")
            try:
                requests.get(f"{MOCK}/_mock/requests", timeout=1)
                return
            except requests.RequestException:
                time.sleep(0.2)
        raise RuntimeError("mock provider did not come up")

    # server ------------------------------------------------------------
    def ensure(self, variant):
        if self.variant == variant and self.server_proc and self.server_proc.poll() is None:
            return
        self.stop_server()
        self.start_server(variant)

    def start_server(self, variant, wait=True):
        _wait_port_free(API_PORT)
        self._starts += 1
        self.home = self.workdir / f"home-{self._starts}-{variant}"
        self.home.mkdir(parents=True)
        cfg = self.workdir / f"config-{self._starts}-{variant}.yaml"
        subprocess.run(
            [sys.executable, str(HERE / "make_config.py"), str(cfg), str(self.home), str(API_PORT),
             str(MOCK_PORT), *VARIANTS[variant]],
            check=True,
        )
        self.server_log = self.workdir / f"server-{self._starts}-{variant}.log"
        log = open(self.server_log, "wb")
        self.server_proc = subprocess.Popen(
            [str(BIN), "--config", str(cfg), "run"], stdout=log, stderr=subprocess.STDOUT, cwd=str(ROOT),
        )
        (self.workdir / "server.pid").write_text(str(self.server_proc.pid))
        self.variant = variant
        if not wait:
            return
        self._wait_ready()
        requests.post(f"{MOCK}/_mock/config", json={"index_status": "completed", "file_upload_status": 200,
                                                     "stall_secs": 6}, timeout=5)

    def _wait_ready(self):
        deadline = time.time() + 120
        healthy = False
        while time.time() < deadline:
            if self.server_proc.poll() is not None:
                raise RuntimeError(f"server exited with {self.server_proc.returncode}, see {self.server_log}")
            if not healthy:
                try:
                    healthy = requests.get(f"http://{HOST}:{API_PORT}/health", timeout=1).status_code == 200
                except requests.RequestException:
                    pass
            if healthy:
                text = self.server_log.read_text(errors="replace")
                # "mini-chat gear started" is logged after the outbox and the workers are up.
                # Requests sent before it may race the outbox start (see README, known issues).
                if ("OAGW upstream provisioned provider=mock" in text
                        and "mini-chat gear started" in text):
                    return
            time.sleep(0.3)
        raise RuntimeError(f"server not ready within 120s, see {self.server_log}")

    def stop_server(self):
        proc, self.server_proc = self.server_proc, None
        self.variant = None
        if proc and proc.poll() is None:
            proc.terminate()
            try:
                proc.wait(timeout=20)
            except subprocess.TimeoutExpired:
                proc.kill()
                proc.wait(timeout=10)

    def stop(self):
        self.stop_server()
        proc, self.mock_proc = self.mock_proc, None
        if proc and proc.poll() is None:
            proc.terminate()
            try:
                proc.wait(timeout=10)
            except subprocess.TimeoutExpired:
                proc.kill()
                proc.wait(timeout=10)

    @property
    def db_path(self):
        return self.home / "mini-chat" / "mini_chat.db"


def _port_open(port):
    import socket

    with socket.socket() as sock:
        sock.settimeout(0.5)
        return sock.connect_ex((HOST, port)) == 0


def _wait_port_free(port, timeout=20):
    deadline = time.time() + timeout
    while time.time() < deadline:
        if not _port_open(port):
            return
        time.sleep(0.25)
    raise RuntimeError(f"port {port} is still in use by another process; refusing to run against it")


