async fn check_failed_and_cancelled_turns_can_be_mutated(op: Op) {
    for terminal_state in ["failed", "cancelled"] {
        let (env, user, chat) = env_user_chat().await;
        let request_id = Uuid::new_v4();
        if terminal_state == "failed" {
            enqueue_chat(&env, failed_script("boom", None));
            send_with_id(&env, &user, &chat, "Q-ONE", request_id).await;
        } else {
            let stream =
                live::start_hung_turn(&env, &user, &chat, request_id, "Q-ONE", &["par"]).await;
            live::disconnect_and_wait_cancelled(&env, &chat, request_id, stream).await;
        }
        assert_eq!(
            turn_detail(&env, &chat, request_id).await.state,
            terminal_state
        );
        prepare(&env, op);

        let resp = mutate(&env, &user, &chat, request_id, op).await;

        expect_mutated(&resp, op);
        let old = turn_detail(&env, &chat, request_id).await;
        assert!(old.deleted, "{terminal_state}: the turn is soft-deleted");
        assert!(
            message_of(&env, &chat, request_id, "user").await.deleted,
            "{terminal_state}: its user message is soft-deleted"
        );
    }
}
