//! Turn mutations: retry, edit and delete of the latest turn (DESIGN sections 3.6 "Retry / edit
//! variant", 3.9 "Turn Mutation Rules (P1)" with the API contracts and the audit events, 3.3
//! "Idempotency Rules", 5.7 "Unstarted retry/edit turn", ADR-0009).
//!
//! The endpoints are `POST /v1/chats/{id}/turns/{request_id}/retry`, `PATCH ...` (edit, body
//! `{content}`) and `DELETE ...` (204). Retry and edit answer with the same event stream as
//! `messages:stream`; delete answers `204`. A rejection in the read-only mutation preview or the
//! preflight leaves everything as it was; a failure after the mutation commit marks the new turn
//! `failed` and returns a JSON error.
//!
//! The tests of "the same rule for all three operations" run once per operation (`retry`, `edit`,
//! `delete` modules generated by `per_op!`).

