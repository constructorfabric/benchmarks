async fn check_a_running_mutation_turn(op: Op) {
    let c = two_turns().await;
    let old = c.last().request_id;
    enqueue_chat(&c.env, hang_script(&["par"]));
    let mut stream = open_mutation(&c.env, &c.user, &c.chat, old, op).await;
    assert_eq!(stream.status, StatusCode::OK);
    let events = live::read_until(&mut stream, "delta").await;
    let new = new_request_id(&events);

    let status = get(&c.env, &c.user, &turn_path(&c.chat, &new.to_string())).await;
    assert_eq!(status.json()["state"], json!("running"));
    assert!(status.json().get("assistant_message_id").is_none());
    assert_eq!(
        running_turns(&c.env, &c.chat).await.len(),
        1,
        "at most one running turn"
    );
    let turn = turn_row(&c.env, &c.chat, new).await.unwrap();
    assert!(
        !turn.has_completed_at,
        "a running turn has no completion time"
    );
    assert_not_found(
        &get(&c.env, &c.user, &turn_path(&c.chat, &old.to_string())).await,
        TURN_RESOURCE_TYPE,
    );

    // While it runs: the new turn cannot be mutated (running), the old request id is gone, and
    // nothing else can start.
    for other in [Op::Retry, Op::Edit, Op::Delete] {
        assert_target_running(&mutate(&c.env, &c.user, &c.chat, new, other).await);
        assert_not_latest(&mutate(&c.env, &c.user, &c.chat, old, other).await);
    }
    let parallel = send_text(&c.env, &c.user, &c.chat, "parallel").await;
    assert_aborted(&parallel, "turn_already_running");
    assert_eq!(running_turns(&c.env, &c.chat).await.len(), 1);
    stream.disconnect();
}
