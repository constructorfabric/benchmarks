    assert_eq!(total_reserved(&c.env).await, 0);
    let old_turn = turn_detail(&c.env, &c.chat, old).await;
    assert!(old_turn.deleted, "the previous turn is already replaced");
    assert_eq!(old_turn.replaced_by, Some(new));
    // The new turn does not block the chat and is visible through the status API.
    assert!(running_turns(&c.env, &c.chat).await.is_empty());
    let status = get(&c.env, &c.user, &turn_path(&c.chat, &new.to_string())).await;
