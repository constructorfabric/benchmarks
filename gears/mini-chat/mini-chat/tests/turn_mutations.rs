async fn two_turns() -> Conversation {
    conversation(&[("Q-ONE", "A-ONE"), ("Q-TWO", "A-TWO")]).await
}

/// What a completed retry or edit of the latest turn of `two_turns()` produced.
struct Replaced {
    c: Conversation,
    old: Uuid,
    new: Uuid,
    events: Vec<mini_chat::test_support::SseEvent>,
}

async fn replace_last(op: Op) -> Replaced {
    assert!(op.replaces());
    let c = two_turns().await;
    let old = c.last().request_id;
    enqueue_text(&c.env, &[NEW_ANSWER], 10, 5);
    let resp = mutate(&c.env, &c.user, &c.chat, old, op).await;
    let events = expect_mutated(&resp, op);
    let new = new_request_id(&events);
    Replaced {
        c,
        old,
        new,
        events,
    }
}

/// The user message content the replacement turn must carry.
fn replacement_content(op: Op) -> &'static str {
    if op == Op::Edit { EDITED } else { "Q-TWO" }
}

fn uuid_str(id: Uuid) -> Value {
    json!(id.to_string())
}

