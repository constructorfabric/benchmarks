async fn check_a_failed_mutation_turn(op: Op) {
    let c = two_turns().await;
    let old = c.last().request_id;
    enqueue_chat(&c.env, failed_script("boom", None));

    let resp = mutate(&c.env, &c.user, &c.chat, old, op).await;

    let events = expect_stream(&resp);
    let error = terminal(&events);
    assert_eq!(error.event, "error", "{events:?}");
    assert_eq!(error.data["code"], json!("provider_error"));
    let new = new_request_id(&events);
    let turn = turn_row(&c.env, &c.chat, new).await.unwrap();
    assert_eq!(turn.state, "failed");
    assert_eq!(turn.error_code.as_deref(), Some("provider_error"));
    assert!(turn.has_completed_at);
    assert_eq!(
        turn.assistant_message_id, None,
        "no content: null assistant message"
    );
    assert!(turn_detail(&c.env, &c.chat, old).await.deleted);
    let status = get(&c.env, &c.user, &turn_path(&c.chat, &new.to_string()))
        .await
        .json();
    assert_eq!(status["state"], json!("error"));
    assert_eq!(status["error_code"], json!("provider_error"));
    let usage = c.env.outbox_payloads(USAGE_QUEUE).await;
    assert_eq!(usage.last().unwrap()["request_id"], uuid_str(new));
    assert_eq!(usage.last().unwrap()["billing_outcome"], json!("failed"));
    assert_eq!(total_reserved(&c.env).await, 0, "the reserve is settled");
    // A failed turn is terminal and the latest: retry works again.
    enqueue_text(&c.env, &["second try"], 10, 5);
    let again = expect_stream(&retry(&c.env, &c.user, &c.chat, new).await);
    assert_eq!(streamed_text(&again), "second try");
    assert_eq!(
        turn_detail(&c.env, &c.chat, new).await.replaced_by,
        Some(new_request_id(&again))
    );
}
per_replacing_op!(
    a_failed_mutation_turn_is_error_with_null_content_and_can_be_retried,
    check_a_failed_mutation_turn
);

